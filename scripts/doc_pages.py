"""DOC (S14): write the documentation site's generated pages from the code.

Two pages are generated, never edited. `docs-site/guide/units.md`: every model the revision binder
admits (`MODEL_BUILDERS`), with the property bases it binds on (`MODEL_BASES`) and what its
signature declares — ports, required parameters, pins and one-of specifications — as the
application's own `list_models` publishes it (`MODEL_SIGNATURES`). A model added to, or removed
from, the registry therefore changes the page, and `--check` (run by
`tests/test_doc_pages.py`) fails until it is regenerated. `docs-site/api/operations.md`: the
operations table (`OPERATIONS`), each operation with its right, transports, HTTP route and MCP tool.

    python scripts/doc_pages.py           # write the pages
    python scripts/doc_pages.py --check   # exit 1 if a page differs
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from openflowsheet.application.local import LocalApplication
from openflowsheet.application.operations import OPERATIONS
from openflowsheet.application.revision_binding import MODEL_BASES, MODEL_BUILDERS

SITE = Path(__file__).resolve().parents[1] / "docs-site"
PAGE = SITE / "guide" / "units.md"
OPERATIONS_PAGE = SITE / "api" / "operations.md"

#: Provider id -> how the page names the basis (the user guide's property-basis page).
BASES: Mapping[str, str] = {
    "syn001": "SYN-001 (synthetic A, B, C)",
    "pr-c1-v1": "Peng–Robinson C1 (H2, N2, NH3, Ar, CH4)",
    "iapws95-v1": "IAPWS-95 water",
    "coolprop-heos-v1": "CoolProp HEOS (one pure fluid)",
    "wilson-ig-v2": "Wilson γ–φ (CH3OH, C2H5OH, H2O)",
}

#: Model id prefix -> the section it is listed under, in page order.
FAMILIES: Sequence[tuple[str, str]] = (
    ("thermal.", "Pure-fluid units (`thermal.*`)"),
    ("syn001.", "Mixture units (`syn001.*`)"),
    ("c1.", "Ammonia-loop units (`c1.*`)"),
)

MARKER = "<!-- Generated by scripts/doc_pages.py from the code. Do not edit; --check compares. -->"
HEADER = (
    MARKER
    + """

# Unit catalogue

Every unit model the revision binder admits, with the property bases it binds on and what its
signature declares. A model is named in a revision by its id (`instances[].model.id`); a model
that is not listed here, or one placed on a basis it does not bind on, is refused at binding with
`model_unsupported(<id>)`. The same information is served at run time by `list_models` (Python,
CLI, HTTP and MCP), which also gives each pin's accepted specification encodings.

Optional parameters a builder reads beyond its signature — for example the `thermal.*` units'
`outlet_vapor_fraction` (the quality mode) and the column's feed stages and stage pressures — are
described on the pages for those units ([property bases](property-bases.md),
[distillation column](column.md)).

| Basis id | Basis |
| --- | --- |
"""
)


def _join(items: Sequence[str]) -> str:
    return ", ".join(f"`{item}`" for item in items) if items else "—"


def _ports(model: Mapping[str, Any]) -> str:
    return ", ".join(
        f"`{port['name']}` ({port['direction']}, {port['kind']})" for port in model["ports"]
    )


def _specifications(option: Mapping[str, Any]) -> str:
    paths = sorted({f"{s['object_type']} `{s['path']}`" for s in option["specifications"]})
    return f"`{option['name']}` ({option['quantity']}: {', '.join(paths)})"


def _model(model: Mapping[str, Any]) -> str:
    model_id = model["model_id"]
    lines = [
        f"### `{model_id}`",
        "",
        "| | |",
        "| --- | --- |",
        f"| Bases | {_join(sorted(MODEL_BASES[model_id]))} |",
        f"| Ports | {_ports(model)} |",
        f"| Required parameters | {_join(model['required'])} |",
    ]
    if model["zero"]:
        lines.append(f"| Parameters admitted only as 0 | {_join(model['zero'])} |")
    if model["pins"]:
        lines.append(f"| Pins | {'; '.join(_specifications(pin) for pin in model['pins'])} |")
    for choice in model["choices"]:
        options = "; ".join(_specifications(option) for option in choice["options"])
        lines.append(f"| One of (`{choice['name']}`) | {options} |")
    return "\n".join(lines) + "\n"


def render() -> str:
    with LocalApplication.in_memory() as app:
        models = {m["model_id"]: m for m in app.list_models().as_document()["models"]}
    if set(models) != set(MODEL_BUILDERS) or set(MODEL_BASES) != set(MODEL_BUILDERS):
        raise SystemExit("list_models, MODEL_BASES and MODEL_BUILDERS disagree")
    used = sorted({basis for bases in MODEL_BASES.values() for basis in bases})
    unknown = [basis for basis in used if basis not in BASES]
    if unknown:
        raise SystemExit(f"a basis without a name on the page: {unknown}")
    parts = [HEADER]
    parts.extend(f"| `{basis}` | {BASES[basis]} |\n" for basis in used)
    for prefix, title in FAMILIES:
        members = sorted(model_id for model_id in models if model_id.startswith(prefix))
        parts.append(f"\n## {title}\n")
        parts.extend("\n" + _model(models[model_id]) for model_id in members)
    listed = {m for prefix, _ in FAMILIES for m in models if m.startswith(prefix)}
    if listed != set(models):
        raise SystemExit(f"models outside every family: {sorted(set(models) - listed)}")
    return "".join(parts)


OPERATIONS_HEADER = (
    MARKER
    + """

# Operations table

Every transport sends a request document through `dispatch`, which looks the operation up in
`OPERATIONS`, checks the caller's right, decodes the request, calls the `LocalApplication` method
of the same name and encodes the response. The request and response schemas are in the
repository's `schemas/` directory.

| Operation | Right | Transports | HTTP | MCP tool |
| --- | --- | --- | --- | --- |
"""
)

OPERATIONS_FOOTER = """
::: openflowsheet.application.operations.dispatch

::: openflowsheet.application.operations.Operation
"""


def render_operations() -> str:
    rows = []
    for operation in OPERATIONS.values():
        http = f"`{operation.http[0]} {operation.http[1]}`" if operation.http else "—"
        tool = f"`{operation.mcp_tool}`" if "mcp" in operation.transports else "—"
        transports = ", ".join(operation.transports)
        rows.append(
            f"| `{operation.name}` | {operation.right} | {transports} | {http} | {tool} |\n"
        )
    return OPERATIONS_HEADER + "".join(rows) + OPERATIONS_FOOTER


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a page differs")
    arguments = parser.parse_args(argv)
    pages = {PAGE: render(), OPERATIONS_PAGE: render_operations()}
    if arguments.check:
        stale = [
            path
            for path, text in pages.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        for path in stale:
            print(f"{path} differs from the code; run scripts/doc_pages.py")
        if not stale:
            print("generated pages: up to date")
        return 1 if stale else 0
    for path, text in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
