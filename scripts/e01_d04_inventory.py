def check() -> list[str]:
    problems: list[str] = []
    if not DATA_RECORD.is_file():
        return [f"{DATA_RECORD.name} missing"]
    data = json.loads(DATA_RECORD.read_text(encoding="utf-8"))
    entries = {row["path"]: row for row in data.get("files", ())}
    for path in sorted(DATA.rglob("*")):
        if not path.is_file():
            continue
        key = f"openflowsheet/_data/assessment/{path.relative_to(DATA).as_posix()}"
        row = entries.get(key)
        if row is None:
            problems.append(f"{key}: no D04 entry")
            continue
        if row["sha256"] != _sha256(path):
            problems.append(f"{key}: sha256 differs from the D04 entry")
        if not row.get("licence") or not row.get("licence_text_sha256"):
            problems.append(f"{key}: no licence or licence text")
        if row.get("redistribution") != "allowed" or row.get("derived_from_ecoinvent"):
            problems.append(f"{key}: not redistributable, yet in the package data")
    if not PACKAGES_RECORD.is_file():
        return [*problems, f"{PACKAGES_RECORD.name} missing"]
    packages = json.loads(PACKAGES_RECORD.read_text(encoding="utf-8"))
    if packages.get("requirements") != lca_requirements():
        problems.append("the package record's requirements are not the `lca` extra's")
    if packages.get("lock", {}).get("sha256") != _sha256(LCA_LOCK):
        problems.append("the package record was not made from the current lca-pip.lock")
    rows = {row["name"]: row for row in packages.get("distributions", ())}
    for name, version in lock_pins(LCA_LOCK).items():
        row = rows.get(name)
        if row is None or row["version"] != version:
            problems.append(f"{name}=={version}: no package row at that version")
            continue
        if not str(row["verdict"]).startswith("ok"):
            problems.append(f"{name}: verdict {row['verdict']}")
        if not row["license_files"] and "audit" not in row:
            problems.append(f"{name}: no licence file and no audit")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--packages", action="store_true")
    group.add_argument("--data", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.packages:
        record = packages_record()
        PACKAGES_RECORD.write_text(
            json.dumps(record, indent=1, sort_keys=True) + "\n", encoding="utf-8"
        )
        print(f"e01 packages: {len(record['distributions'])} rows, failures {record['failures']}")
        return 1 if record["failures"] else 0
    if args.data:
        record = data_record()
        DATA_RECORD.write_text(
            json.dumps(record, indent=1, sort_keys=True, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        print(f"e01 data: {len(record['files'])} files")
        return 0
    problems = check()
    print("A42 " + ("PASS" if not problems else "FAIL: " + "; ".join(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
