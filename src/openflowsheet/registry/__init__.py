#: The distribution every built-in descriptor belongs to.
BUILTIN_DISTRIBUTION = "openflowsheet"
#: The built-in table whose descriptors are D6's legacy forms (`stability` core for their kinds).
LEGACY_TABLE = legacy.TABLE_NAME


class RegistryBuildError(ValueError):
    """A built-in descriptor fails validation: a bug, which fails the build (D4, D7, D8)."""

    def __init__(self, reason: Coded) -> None:
        super().__init__(f"{reason.code}{dict(reason.params)}")
        self.reason = reason


class FactoryRefusedError(LookupError):
    """D7's lazy factory resolution refused, with its typed reason: `platform_unsupported`,
    `dependency_missing` or `factory_unavailable` (no factory constructs this descriptor)."""

    def __init__(self, reason: Coded) -> None:
        super().__init__(f"{reason.code}{dict(reason.params)}")
        self.reason = reason


@dataclass(frozen=True)
class Source:
    """Where a descriptor comes from: its distribution and the import root its `modules` are
    relative to (D3). `legacy_form` marks D6's legacy built-ins."""

    distribution: str
    distribution_version: str
    entry_point: str | None
    import_root: Path | None
    builtin: bool
    legacy_form: bool = False


@dataclass(frozen=True)
class ExtensionPackage:
    """An extension package document already loaded from its entry point (D7), with the
    distribution that declared it and the import root of its top-level package."""

    distribution: str
    distribution_version: str
    entry_point: str
    import_root: Path | None
    document: object


def _builtin_root() -> Path:
    import openflowsheet  # noqa: PLC0415

    assert openflowsheet.__file__ is not None
    return Path(openflowsheet.__file__).resolve().parent.parent


def _attested(
    document: Mapping[str, Any], digest: str, self_sha: str, attestations: frozenset[Attestation]
) -> bool:
    return Attestation(document["id"], document["version"], digest, self_sha) in attestations


def _registered(
    document: Mapping[str, Any], source: Source, attestations: frozenset[Attestation]
) -> Registered:
    """Normalise one schema-valid descriptor and compute D2's fields (self-hash may raise)."""
    normal = normalise(document)
    digest = descriptor_sha256(normal)
    self_sha = self_sha256(source.import_root, normal["implementation"]["modules"])
    attested = not source.builtin and _attested(normal, digest, self_sha, attestations)
    effective = effective_status(normal["status"], builtin=source.builtin, attested=attested)
    return Registered(
        document=normal,
        descriptor_sha256=digest,
        self_sha256=self_sha,
        origin=origin(normal, builtin=source.builtin),
        distribution=source.distribution,
        distribution_version=source.distribution_version,
        entry_point=source.entry_point,
        effective_status=effective,
        evidence_class=evidence_class(effective, builtin=source.builtin, attested=attested),
        stability=stability(normal["kind"], builtin=source.builtin, legacy_form=source.legacy_form),
    )


def _token_problem(
    document: Mapping[str, Any], source: Source, namespace: str | None
) -> Coded | None:
    """D4's validation of every token of one normalised descriptor, `requires` then `provides`."""
    for clause in document["requires"]:
        for token in clause:
            found = token_problem(
                token, providing=False, builtin=source.builtin, namespace=namespace
            )
            if found is not None:
                return found
    for token in document["provides"]:
        found = token_problem(token, providing=True, builtin=source.builtin, namespace=namespace)
        if found is not None:
            return found
    return None


def _limitation_problem(document: Mapping[str, Any], codes: frozenset[str]) -> str | None:
    """D2: the pointer of the first limitation whose code is not in `codes`, relative to the
    descriptor (declared order), or `None`."""
    for index, limitation in enumerate(document["limitations"]):
        if limitation["code"] not in codes:
            return f"/limitations/{index}/code"
    return None


#: The registry's per-thread build state: the depth of `Registry.build` calls running on this
#: thread (a catalogue lookup then raises, D8) and whether it is building the process registry.
_build_state = threading.local()


def _building() -> bool:
    return bool(getattr(_build_state, "depth", 0))


@contextmanager
def _build_scope() -> Iterator[None]:
    _build_state.depth = getattr(_build_state, "depth", 0) + 1
    try:
        yield
    finally:
        _build_state.depth -= 1


#: MSG's `register(document, *, namespace)` slot (ADR 0058 §4.11), or a test's.
CatalogueRegister = Callable[..., None]


class Registry:
    """A set of registered descriptors, open while it is built and closed afterwards (D8)."""

    def __init__(self) -> None:
        self._entries: dict[tuple[str, str, tuple[int, int, int]], Registered] = {}
        self._quarantined: list[Quarantine] = []
        self._closed = False
        #: (id, version key) of each registered `message_entries` descriptor -> its namespace
        #: and its pre-validated catalogue document (D7), registered with MSG at step 4 (D8).
        self._catalogues: dict[tuple[str, tuple[int, int, int]], tuple[str, Mapping[str, Any]]]
        self._catalogues = {}
        self._messages = discovery.CatalogueCheck()

    # -- building ------------------------------------------------------------------------------

    @classmethod
    def build(
        cls,
        *,
        builtin_tables: Mapping[str, Sequence[Mapping[str, Any]]],
        entry_points: Iterable[discovery.Discovered] = (),
        packages: Iterable[ExtensionPackage] = (),
        attestations: Iterable[Attestation] = (),
        builtin_root: Path | None = None,
        builtin_version: str | None = None,
        catalogue_register: CatalogueRegister | None = None,
    ) -> Registry:
        """Build and close an independent registry (D8 steps 1 to 6).

        `builtin_tables` maps a table name to its descriptors; `entry_points` are discovered by
        `discovery.entry_points()` (D7); `packages` are extension packages already loaded;
        `builtin_root` is the import root of built-in `modules` (default: the directory
        containing the `openflowsheet` package); `attestations` are the project's review
        records (D9; none exist in 0.5); `catalogue_register` receives each registered
        extension's message catalogue, sorted by id (the process registry passes MSG's
        `register`; `None` registers none). A catalogue lookup on this thread meanwhile raises."""
        if builtin_version is None:
            import openflowsheet  # noqa: PLC0415

            builtin_version = openflowsheet.__version__
        root = _builtin_root() if builtin_root is None else builtin_root
        attested = frozenset(attestations)
        registry = cls()
        with _build_scope():
            for table in sorted(builtin_tables, key=lambda name: name.encode("utf-8")):
                source = Source(
                    BUILTIN_DISTRIBUTION, builtin_version, None, root, True, table == LEGACY_TABLE
                )
                for document in builtin_tables[table]:
                    registry.register(registry._builtin(document, source, attested))
            reserved = discovery.RESERVED_NAMESPACES | {
                entry.id.split(".", 1)[0] for entry in registry._entries.values()
            }
            loaded, refused = discovery.discover(entry_points, reserved=reserved)
            for found, reason in refused:
                registry._quarantined.append(
                    Quarantine(
                        found.distribution, found.distribution_version, found.namespace, reason
                    )
                )
            for item in loaded:
                registry._add_package(
                    ExtensionPackage(
                        item.found.distribution,
                        item.found.distribution_version,
                        item.found.namespace,
                        item.import_root,
                        item.document,
                    ),
                    attested,
                )
            for package in packages:
                registry._add_package(package, attested)
            registry._resolve()
            if catalogue_register is not None:
                for key in sorted(registry._catalogues, key=lambda k: (k[0].encode("utf-8"), k[1])):
                    namespace, catalogue = registry._catalogues[key]
                    catalogue_register(catalogue, namespace=namespace)
            registry._closed = True
        return registry

    def _builtin(
        self, document: Mapping[str, Any], source: Source, attestations: frozenset[Attestation]
    ) -> Registered:
        identity = f"{document.get('kind')}:{document.get('id')}@{document.get('version')}"
        pointer = descriptor_problem(document, legacy_form=source.legacy_form)
        if pointer is None and document["limitations"]:
            pointer = _limitation_problem(document, self._messages.core_codes())
        if pointer is not None:
            raise RegistryBuildError(
                Coded("extension_invalid", {"entry_point": identity, "pointer": pointer})
            )
        found = _token_problem(normalise(document), source, None)
        if found is not None:
            raise RegistryBuildError(found)
        try:
            return _registered(document, source, attestations)
        except SelfHashUnavailableError as error:
            raise RegistryBuildError(
                Coded("self_hash_unavailable", {"id": str(document["id"]), "path": error.path})
            ) from None

    def _add_package(self, package: ExtensionPackage, attestations: frozenset[Attestation]) -> None:
        """Register a package whole or quarantine it with its first problem (D7): per descriptor
        in document order its schema, id prefix, uniqueness, tokens, self-hash and (for
        `message_entries`) catalogue; then each descriptor's limitation codes, which may name
        the codes of any of the package's catalogues."""

        def quarantine(reason: Coded) -> None:
            self._quarantined.append(
                Quarantine(
                    package.distribution, package.distribution_version, package.entry_point, reason
                )
            )

        def invalid(pointer: str) -> None:
            quarantine(
                Coded("extension_invalid", {"entry_point": package.entry_point, "pointer": pointer})
            )

        document = package.document
        pointer = schema_problem(document, "/$defs/package")
        if pointer is not None:
            return invalid(pointer)
        assert isinstance(document, Mapping)
        namespace = str(document["namespace"])
        if namespace != package.entry_point:
            return invalid("/namespace")
        source = Source(
            package.distribution,
            package.distribution_version,
            package.entry_point,
            package.import_root,
            False,
        )
        registered: list[Registered] = []
        catalogues: dict[tuple[str, tuple[int, int, int]], tuple[str, Mapping[str, Any]]] = {}
        codes: set[str] = set()
        seen: set[tuple[str, str, tuple[int, int, int]]] = set()
        for index, descriptor in enumerate(document["descriptors"]):
            where = f"/descriptors/{index}"
            found = descriptor_problem(descriptor)
            if found is not None:
                return invalid(where + found)
            if not str(descriptor["id"]).startswith(namespace + "."):
                return invalid(where + "/id")
            key = (descriptor["kind"], descriptor["id"], version_key(descriptor["version"]))
            if key in seen:
                return invalid(where)
            seen.add(key)
            problem = _token_problem(normalise(descriptor), source, namespace)
            if problem is not None:
                return quarantine(problem)
            try:
                registered.append(_registered(descriptor, source, attestations))
            except SelfHashUnavailableError as error:
                return quarantine(
                    Coded(
                        "self_hash_unavailable", {"id": str(descriptor["id"]), "path": error.path}
                    )
                )
            if descriptor["kind"] == "message_entries":
                try:
                    catalogue = self._messages.load(descriptor["payload"]["catalogue"])
                except Exception:  # noqa: BLE001 (a missing or unparsable resource quarantines)
                    return invalid(where + "/payload/catalogue")
                if self._messages.problem(catalogue, namespace) is not None:
                    return invalid(where + "/payload/catalogue")
                assert isinstance(catalogue, Mapping)
                catalogues[(descriptor["id"], key[2])] = (namespace, catalogue)
                codes.update(str(item["code"]) for item in catalogue["entries"])
        for index, descriptor in enumerate(document["descriptors"]):
            if descriptor["limitations"]:
                allowed = self._messages.core_codes() | codes
                found = _limitation_problem(descriptor, allowed)
                if found is not None:
                    return invalid(f"/descriptors/{index}{found}")
        clashes = [e for e in registered if (e.kind, e.id, version_key(e.version)) in self._entries]
        if clashes:
            # Discovery quarantines both packages of a namespace before they reach this (D7).
            raise RegistryBuildError(Coded("namespace_conflict", {"namespace": namespace}))
        for entry in registered:
            self.register(entry)
        self._catalogues.update(catalogues)
        return None

    def register(self, entry: Registered) -> None:
        """Add one registered descriptor; (kind, id, version) is unique. Raises
        `RuntimeError("registry_closed")` once the registry is built."""
        if self._closed:
            raise RuntimeError("registry_closed")
        key = (entry.kind, entry.id, version_key(entry.version))
        if key in self._entries:
            raise ValueError(f"{entry.kind} {entry.id} {entry.version} is already registered")
        self._entries[key] = entry

    def _resolve(self) -> None:
        """D4: record, on each descriptor, its tokens whose registry-derived name no registered
        descriptor gives. Static tokens were validated when they were registered."""
        names: set[tuple[str, str]] = set()
        by_kind = {kind: space for space, kind in REGISTRY_SPACES.items() if kind is not None}
        for entry in self._entries.values():
            if entry.kind in by_kind:
                names.add((by_kind[entry.kind], entry.id))
            names.update(
                (token.space, token.name)
                for token in map(parse, entry.provides)
                if token.space == "x"
            )
        for key, entry in self._entries.items():
            tokens = {token for clause in entry.requires for token in clause} | set(entry.provides)
            unresolved = sorted(
                (
                    token
                    for token in tokens
                    if parse(token).space in REGISTRY_SPACES
                    and (parse(token).space, parse(token).name) not in names
                ),
                key=lambda token: token.encode("utf-8"),
            )
            self._entries[key] = replace(entry, unresolved=tuple(unresolved))

    # -- reading -------------------------------------------------------------------------------

    @property
    def closed(self) -> bool:
        return self._closed

    def descriptors(self, kinds: Sequence[str] | None = None) -> tuple[Registered, ...]:
        """The registered descriptors (of `kinds`, if given), sorted by (kind, id, version key)."""
        selected = (e for e in self._entries.values() if kinds is None or e.kind in kinds)
        return tuple(sorted(selected, key=Registered.sort_key))

    def resolve(self, kind: str, identifier: str, version: str | None = None) -> Registered:
        """The descriptor (kind, id, version), the highest version when `version` is `None`;
        `KeyError` when none is registered. Appends (kind, id, version) to the active `usage()`
        record (D8)."""
        entry = self._lookup(kind, identifier, version)
        _record(entry)
        return entry

    def _lookup(self, kind: str, identifier: str, version: str | None = None) -> Registered:
        """`resolve` without recording: the registry's own queries (admission, the derived
        extensions used) are not uses."""
        if version is not None:
            return self._entries[(kind, identifier, version_key(version))]
        versions = [e for e in self._entries.values() if e.kind == kind and e.id == identifier]
        if not versions:
            raise KeyError((kind, identifier))
        return max(versions, key=Registered.sort_key)

    def admit(
        self,
        unit: str,
        method: str,
        definition: str,
        *,
        unit_version: str | None = None,
        method_version: str | None = None,
    ) -> Admission:
        """D5 on the registered unit, method and definition named (highest versions by default)."""
        return admit(
            self._lookup("unit_model", unit, unit_version),
            self._lookup("property_method", method, method_version),
            self._lookup("connection_definition", definition),
        )

    def admission_matrix(self, definition: str) -> tuple[Verdict, ...]:
        """D5's matrix over every registered unit × method on `definition`."""
        return admission_matrix(self, self._lookup("connection_definition", definition))

    @property
    def quarantined(self) -> tuple[Quarantine, ...]:
        return tuple(self._quarantined)

    @property
    def registry_sha256(self) -> str:
        return registry_sha256(self._entries.values())

    def snapshot(self) -> dict[str, Any]:
        """D10's snapshot document."""
        return snapshot_document(self._entries.values(), self._quarantined)

    # -- factories (D7) ------------------------------------------------------------------------

    def factory(self, kind: str, identifier: str, version: str | None = None) -> object:
        """D7's lazy factory resolution: `implementation.factory`'s attribute of its module,
        indexed by `key` when it has one; nothing is constructed. Appends to the active
        `usage()` record. Raises `FactoryRefusedError`:

        - `factory_unavailable(<kind>, <id>)` when no factory constructs the descriptor: a null
          factory, or a legacy property method no basis selects (`selectable` false; the binder's
          `basis_provider` cannot construct `pr-lib-v1` or `wilson-ig-v1`, W2-5);
        - `platform_unsupported(<id>, <platform>)` when `platforms` excludes this platform;
        - `dependency_missing(<id>, <extra>)` when the factory's import fails for want of the
          optional dependency its `pip_extra` installs."""
        entry = self.resolve(kind, identifier, version)
        declared = entry.document["implementation"]["factory"]
        legacy_unselectable = (
            entry.kind == "property_method"
            and entry.stability == "core"
            and entry.document["payload"].get("selectable") is False
        )
        if declared is None or legacy_unselectable:
            raise FactoryRefusedError(
                Coded("factory_unavailable", {"kind": entry.kind, "id": entry.id})
            )
        here = current_platform()
        platforms = entry.document["platforms"]
        if platforms != ["any"] and here not in platforms:
            raise FactoryRefusedError(
                Coded("platform_unsupported", {"id": entry.id, "platform": here})
            )
        extra = entry.document["pip_extra"]
        try:
            module = importlib.import_module(declared["module"])
        except ImportError:
            if extra is None:
                raise
            raise FactoryRefusedError(
                Coded("dependency_missing", {"id": entry.id, "extra": extra})
            ) from None
        resolved: object = getattr(module, declared["attribute"])
        if declared["key"] is not None:
            assert isinstance(resolved, Mapping)
            resolved = resolved[declared["key"]]
        return resolved

    # -- extensions used (D8, D9) --------------------------------------------------------------

    def extensions_used(self, references: Iterable[tuple[str, str, str | None]]) -> ExtensionsUsed:
        """D8's extensions used, derived from the (kind, id, version) references a run's
        documents make (`None`: the highest registered version), each looked up here; a
        reference no registered descriptor matches is listed in `unregistered`. Nothing is
        recorded in `usage()`."""
        used: dict[tuple[str, str, tuple[int, int, int]], Registered] = {}
        missing: set[tuple[str, str, str | None]] = set()
        for kind, identifier, version in references:
            try:
                entry = self._lookup(kind, identifier, version)
            except KeyError:
                missing.add((kind, identifier, version))
                continue
            used[(entry.kind, entry.id, version_key(entry.version))] = entry
        return ExtensionsUsed(
            tuple(sorted(used.values(), key=Registered.sort_key)),
            tuple(
                sorted(
                    missing,
                    key=lambda row: tuple("" if part is None else part for part in row),
                )
            ),
        )


def current_platform() -> str:
    """This interpreter's D2 platform name (`linux-x86_64`, `macos-arm64`, ...)."""
    system = {"Linux": "linux", "Windows": "windows", "Darwin": "macos"}.get(
        platform.system(), platform.system().lower()
    )
    machine = {"amd64": "x86_64"}.get(platform.machine().lower(), platform.machine().lower())
    if system == "linux" and machine == "arm64":
        machine = "aarch64"
    if system == "macos" and machine == "aarch64":
        machine = "arm64"
    return f"{system}-{machine}"


@dataclass(frozen=True)
class ExtensionsUsed:
    """A run's extensions used (D8): the registered descriptors its documents reference, sorted
    by (kind, id, version key), and the references no registered descriptor matches."""

    descriptors: tuple[Registered, ...]
    unregistered: tuple[tuple[str, str, str | None], ...] = ()

    def rows(self) -> list[dict[str, Any]]:
        """One row per descriptor: its identity and D9's evidence fields."""
        return [
            {
                "kind": entry.kind,
                "id": entry.id,
                "version": entry.version,
                "descriptor_sha256": entry.descriptor_sha256,
                "self_sha256": entry.self_sha256,
                "origin": entry.origin,
                "evidence_class": entry.evidence_class,
                "stability": entry.stability,
            }
            for entry in self.descriptors
        ]

    def notices(self) -> tuple[Coded, ...]:
        """D9's flag: `extension_unreviewed(<id>, <origin>)` for each `unreviewed` descriptor and
        `preview_kind(<kind>, <id>)` for each `preview` one, sorted by (code, params)."""
        found = [
            Coded("extension_unreviewed", {"id": entry.id, "origin": entry.origin})
            for entry in self.descriptors
            if entry.evidence_class == "unreviewed"
        ]
        found += [
            Coded("preview_kind", {"kind": entry.kind, "id": entry.id})
            for entry in self.descriptors
            if entry.stability == "preview"
        ]
        unique = {notice.sort_key(): notice for notice in found}
        return tuple(unique[key] for key in sorted(unique))


