"""The extension registry: one registration point for every kind of extension (ADR 0060).

This layer was introduced by package F1 (roadmap 0.5). A registry holds registered descriptors
(`descriptor`), each with its capability tokens (`tokens`) and the self-hash of its implementation
set (`selfhash`); `capability` is the pure admission function over three of them, and `snapshot`
the identity of what is loaded (`registry_sha256`) and the snapshot document.

`Registry.build` builds an independent registry from built-in tables, entry points (`discovery`,
D7) and already loaded extension packages, registers the extensions' message catalogues through
`catalogue_register`, then closes it: `register` afterwards raises
`RuntimeError("registry_closed")`.
The order of every input is irrelevant: descriptors iterate sorted by (kind, id, version key) and
the snapshot's lists are sorted.

A package is registered whole or not at all (D7). It is quarantined, with one typed reason, when
its namespace is reserved or declared twice, its entry point fails to load (`discovery`), its
document fails the schema, the namespace or the id prefix (`extension_invalid`), a token is
unknown or reserved (`capability_unknown`, `reserved_capability`), a self-hash path is missing
(`self_hash_unavailable`), its message catalogue fails MSG's schema or namespace rule, or a
limitation names a code neither the core catalogue nor its own catalogue has (both
`extension_invalid`). Its validation reads only the package itself and the static tables, so one
package's quarantine never quarantines another. A built-in failing any of these is a bug and
raises `RegistryBuildError`.

`default_registry()` builds the process registry once, under a lock, from the built-in tables
(`registry/builtin/*.json`, package data generated by `scripts/registry_builtin.py`: `legacy.json`,
D6, and `core.json`, E01's contributors, listed only), the entry points on `sys.path`, and
registers their message catalogues with MSG's `register`; the message catalogue's first lookup
calls it before it freezes (`before_catalogue_freeze`). A catalogue lookup on a thread that is
building a registry raises. Tests build their own instances with `Registry.build`; the process
registry is never mutated.

`resolve` and `factory` (D7's lazy factory resolution) append (kind, id, version) to the active
`usage()` record, D8's cross-check of a run's extensions used, which `extensions_used` derives
from the references a run's documents make (D8, D9).
"""

