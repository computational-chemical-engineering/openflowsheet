# The usage recorder (D8's cross-check)


@dataclass
class Usage:
    """The (kind, id, version) of every descriptor `resolve` or `factory` returned while this
    record was active."""

    entries: set[tuple[str, str, str]] = field(default_factory=set)

    def sorted(self) -> tuple[tuple[str, str, str], ...]:
        return tuple(
            sorted(
                self.entries,
                key=lambda row: (
                    row[0].encode("utf-8"),
                    row[1].encode("utf-8"),
                    version_key(row[2]),
                ),
            )
        )


#: D8: the active usage record of this context; a run's executor copies the context into its
#: workers (`contextvars.copy_context`), so a worker thread records into its run's record.
_usage: Final[ContextVar[Usage | None]] = ContextVar("openflowsheet_registry_usage", default=None)


def _record(entry: Registered) -> None:
    record = _usage.get()
    if record is not None:
        record.entries.add((entry.kind, entry.id, entry.version))


@contextmanager
def usage() -> Iterator[Usage]:
    """D8's usage recorder: within the block, `resolve` and `factory` record into the yielded
    `Usage`, of this context only (nested blocks record into the innermost)."""
    record = Usage()
    token = _usage.set(record)
    try:
        yield record
    finally:
        _usage.reset(token)


