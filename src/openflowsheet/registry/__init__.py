_process_registry: Registry | None = None


def default_registry() -> Registry:
    """D8: the process registry, built once under a lock from the built-in tables and the entry
    points on `sys.path`, its extensions' message catalogues registered with MSG, and closed;
    every later call returns the same instance. Its `register` raises
    `RuntimeError("registry_closed")`. Called again on the thread building it, it raises
    rather than deadlock."""
    global _process_registry  # noqa: PLW0603
    built = _process_registry
    if built is not None:
        return built
    if getattr(_build_state, "process", False):
        raise RuntimeError("a re-entrant default_registry call during the process registry's build")
    with _process_lock:
        if _process_registry is None:
            from openflowsheet.messages import catalogue  # noqa: PLC0415

            _build_state.process = True
            try:
                _process_registry = Registry.build(
                    builtin_tables=discovery.builtin_tables(),
                    entry_points=discovery.entry_points(),
                    catalogue_register=catalogue.register,
                )
            finally:
                _build_state.process = False
        return _process_registry


def before_catalogue_freeze() -> None:
    """D8, called by the message catalogue's first lookup before it freezes: builds the process
    registry, so extension entries are present whatever the call order. A lookup on a thread
    building a registry raises `RuntimeError("catalogue lookup during registry build")`."""
    if _building():
        raise RuntimeError("catalogue lookup during registry build")
    default_registry()
