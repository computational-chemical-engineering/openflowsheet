"""The registry's two sources and the entry-point rules (ADR 0060 D7).

The **built-in tables** are package data, `registry/builtin/*.json` (generated by
`scripts/registry_builtin.py`), each named by its file stem. The **entry-point group**
`openflowsheet.extensions` is read from every distribution on the path, copies included, so that
one distribution seen twice can be told from two distributions declaring one namespace.

`discover` turns the entry points into loaded extension packages and quarantine records, in this
order, first problem wins:

1. a distribution seen twice (the same normalised name and version) is deduplicated;
2. a namespace (the entry point's name) declared by two distributions quarantines both,
   `namespace_conflict(<namespace>)`;
3. a reserved namespace is `reserved_namespace(<namespace>)`;
4. an entry point that fails to load, or whose callable raises, is
   `extension_load_failed(<entry point>)`; the exception class goes to the log, not the code.

Packages whose namespace is quarantined in steps 2 and 3 are not loaded. The loaded package's
document is validated by `Registry.build` (schema, the namespace equal to the entry point's name,
tokens, self-hash, message catalogue, limitation codes). Entry points are processed sorted by
(normalised distribution name, entry-point name), UTF-8 byte order; nothing depends on the order
`importlib.metadata` returns them in.

`CatalogueCheck` pre-validates an extension's message catalogue against MSG's schema and
namespace rule on a scratch catalogue, and gives the core catalogue's codes for the validation
of `limitations` codes, without a lookup on the process catalogue (D2, D8).
"""

from __future__ import annotations

import importlib.metadata
import importlib.util
import json
import logging
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final

from openflowsheet.registry.tokens import Coded

if TYPE_CHECKING:
    from openflowsheet.messages.catalogue import Catalogue

__all__ = [
    "GROUP",
    "RESERVED_NAMESPACES",
    "CatalogueCheck",
    "Discovered",
    "builtin_tables",
    "discover",
    "entry_points",
    "normalised_name",
]

_logger = logging.getLogger(__name__)

#: D7's entry-point group.
GROUP: Final = "openflowsheet.extensions"
#: D7's reserved namespaces besides the first segment of every built-in id.
RESERVED_NAMESPACES: Final = frozenset({"openflowsheet", "core", "std", "legacy", "x", "user"})
#: D7's package document format.
PACKAGE_FORMAT: Final = "openflowsheet-extension-package-v1"
#: The built-in tables' package-data directory, relative to `openflowsheet.registry`.
BUILTIN_DIRECTORY: Final = "builtin"


def builtin_tables() -> dict[str, list[dict[str, Any]]]:
    """Every built-in table (`registry/builtin/*.json`), by file stem, read through
    `importlib.resources`."""
    directory = resources.files("openflowsheet.registry").joinpath(BUILTIN_DIRECTORY)
    tables: dict[str, list[dict[str, Any]]] = {}
    for entry in sorted(directory.iterdir(), key=lambda item: item.name.encode("utf-8")):
        if entry.name.endswith(".json"):
            tables[entry.name.removesuffix(".json")] = json.loads(entry.read_text(encoding="utf-8"))
    return tables


def normalised_name(name: str) -> str:
    """A distribution name normalised as packaging's PEP 503 rule does."""
    return re.sub(r"[-_.]+", "-", name).lower()


@dataclass(frozen=True)
class Discovered:
    """One entry point of `GROUP` and the distribution that declares it (D7)."""

    distribution: str
    distribution_version: str
    entry_point: importlib.metadata.EntryPoint

    @property
    def namespace(self) -> str:
        """The entry point's name, which is the extension's namespace (D7)."""
        return self.entry_point.name

    def sort_key(self) -> tuple[bytes, bytes, bytes, bytes]:
        return (
            self.distribution.encode("utf-8"),
            self.namespace.encode("utf-8"),
            self.distribution_version.encode("utf-8"),
            self.entry_point.value.encode("utf-8"),
        )


def entry_points(path: Sequence[str] | None = None) -> tuple[Discovered, ...]:
    """Every entry point of `GROUP` of every distribution on `path` (default `sys.path`),
    one per copy of a distribution found twice (`discover` deduplicates them)."""
    distributions = (
        importlib.metadata.distributions()
        if path is None
        else importlib.metadata.distributions(path=list(path))
    )
    found = []
    for distribution in distributions:
        name = distribution.metadata["Name"]
        if not name:
            continue
        for entry_point in distribution.entry_points.select(group=GROUP):
            found.append(Discovered(normalised_name(name), str(distribution.version), entry_point))
    return tuple(found)


def _import_root(module: str) -> Path | None:
    """D3: the directory containing the entry point's top-level package (or module); `None`
    for a namespace package or a zip import, whose `modules` then cannot be self-hashed."""
    spec = importlib.util.find_spec(module.split(".", 1)[0])
    if spec is None or spec.origin is None:
        return None
    origin = Path(spec.origin)
    if not origin.is_file():
        return None
    origin = origin.resolve()
    return origin.parent.parent if spec.submodule_search_locations is not None else origin.parent


@dataclass(frozen=True)
class Loaded:
    """An entry point's package document, loaded, and the import root of its top-level package."""

    found: Discovered
    document: object
    import_root: Path | None


def discover(
    found: Iterable[Discovered], *, reserved: frozenset[str]
) -> tuple[tuple[Loaded, ...], tuple[tuple[Discovered, Coded], ...]]:
    """D7's discovery over `found`: the loaded packages, sorted, and the quarantined entry
    points with their reasons. `reserved` is every reserved namespace (built-in first segments
    included)."""
    unique: dict[tuple[str, str, str], Discovered] = {}
    for item in sorted(found, key=Discovered.sort_key):
        unique.setdefault((item.distribution, item.distribution_version, item.namespace), item)
    ordered = sorted(unique.values(), key=Discovered.sort_key)
    declared: dict[str, set[tuple[str, str]]] = {}
    for item in ordered:
        declared.setdefault(item.namespace, set()).add(
            (item.distribution, item.distribution_version)
        )
    loaded: list[Loaded] = []
    quarantined: list[tuple[Discovered, Coded]] = []
    for item in ordered:
        namespace = item.namespace
        if len(declared[namespace]) > 1:
            quarantined.append((item, Coded("namespace_conflict", {"namespace": namespace})))
            continue
        if namespace in reserved:
            quarantined.append((item, Coded("reserved_namespace", {"namespace": namespace})))
            continue
        try:
            document = item.entry_point.load()()
            root = _import_root(item.entry_point.module)
        except Exception as error:  # noqa: BLE001 (D7: any failure quarantines; class logged)
            _logger.warning(
                "extension entry point %r of %s %s failed to load: %s",
                namespace,
                item.distribution,
                item.distribution_version,
                type(error).__name__,
            )
            quarantined.append((item, Coded("extension_load_failed", {"entry_point": namespace})))
            continue
        loaded.append(Loaded(item, document, root))
    return tuple(loaded), tuple(quarantined)


class CatalogueCheck:
    """MSG's validation of extension catalogues, on a scratch catalogue, and the core codes,
    without a lookup on the process catalogue (D2, D7, D8). Built lazily, once per build."""

    def __init__(self) -> None:
        self._scratch: Catalogue | None = None
        self._core: frozenset[str] | None = None

    def core_codes(self) -> frozenset[str]:
        """The core catalogue's codes (a lookup on a throw-away instance)."""
        if self._core is None:
            from openflowsheet.messages.catalogue import Catalogue  # noqa: PLC0415

            self._core = frozenset(Catalogue().keys())
        return self._core

    @staticmethod
    def load(reference: Mapping[str, Any]) -> object:
        """D7: the YAML document a `message_entries` payload names, through
        `importlib.resources`."""
        from openflowsheet.messages.catalogue import _yaml_load  # noqa: PLC0415

        path = resources.files(str(reference["package"])).joinpath(
            *str(reference["path"]).split("/")
        )
        return _yaml_load(path.read_text(encoding="utf-8"))

    def problem(self, document: object, namespace: str) -> str | None:
        """MSG's schema and namespace rule (`Catalogue.register`'s checks) on `document`, or
        `None` when it would register; the scratch catalogue keeps a valid document, so the
        codes of a package's documents are unique across them."""
        from openflowsheet.messages.catalogue import Catalogue, CatalogueError  # noqa: PLC0415

        if self._scratch is None:
            self._scratch = Catalogue()
        if not isinstance(document, Mapping):
            return "not a catalogue document"
        try:
            self._scratch.register(document, namespace=namespace)
        except CatalogueError as error:
            return str(error)
        return None
