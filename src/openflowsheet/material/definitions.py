"""Connection definitions: templates, instances and their identity (ADR 0062 D3).

Two levels. A **template** is a registered `connection_definition` descriptor: `nTP-v1` (ADR 0060
D6, the legacy table) and the four built-ins this module lists, `mat-v1`, `heat-v1`, `work-v1` and
`signal-v1` (`registry/builtin/material.json`, generated by `scripts/registry_builtin.py` from
`TEMPLATES`). An **instance** is a canonical document, `{template: <id>, <the template's
parameters>}` (`schemas/connection-definition.schema.json`), whose SHA is the connection's
definition identity:

    definition_sha256 = document_sha256(
        {"template": [id, version, descriptor_sha256], "body": body}
    )

with `body` the normalised instance without its `template` member: groups by id, attributes by
(kind, components), component and species lists as given, everything else as given (canonical JSON
orders the keys). So `nTP-v1`'s body is `{}`, a revision-local id is in no preimage, and equal
definitions in two revisions share a SHA. Every layout order (D3's carried indices, F2-WO3) is the
normalised instance's, so equal SHAs mean equal layouts.

The rules a schema cannot state (one `mixed` substream at most, unique ids, components in the
revision's order, strictly increasing grid edges, solid roles, the conserved basis against its fast
reactions through `material.basis`, attribute kinds and grids) are the revision validator's
(F2-WO4), with the typed codes of the ADR's catalogue.
"""

from __future__ import annotations

import copy
from collections.abc import Mapping, Sequence
from fractions import Fraction
from types import MappingProxyType
from typing import Any, Final, NamedTuple

from openflowsheet.canonical import document_sha256
from openflowsheet.material.basis import SpeciesBasis
from openflowsheet.schema_check import schema_errors

