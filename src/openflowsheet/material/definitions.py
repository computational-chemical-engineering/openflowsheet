#: The instance schema, under `schemas/` (package data `_data/schemas/`).
SCHEMA_NAME: Final = "connection-definition.schema.json"
#: ADR 0060 D6's legacy definition, registered in the legacy table.
LEGACY_TEMPLATE: Final = "nTP-v1"


class Template(NamedTuple):
    """A built-in template of D3's table: its descriptor's version, title, and the pointer of its
    instance grammar in `SCHEMA_NAME`."""

    version: str
    title: str
    pointer: str


#: D3's built-in templates other than `nTP-v1` (core once ADR 0062 is Accepted), by id.
TEMPLATES: Final[Mapping[str, Template]] = MappingProxyType(
    {
        "mat-v1": Template("1.0.0", "Material connection definition mat-v1", "/$defs/mat_v1"),
        "heat-v1": Template("1.0.0", "Heat connection definition heat-v1", "/$defs/heat_v1"),
        "work-v1": Template("1.0.0", "Work connection definition work-v1", "/$defs/work_v1"),
        "signal-v1": Template(
            "1.0.0", "Signal connection definition signal-v1", "/$defs/signal_v1"
        ),
    }
)


def instance_problems(instance: object) -> list[str]:
    """Every error of `instance` against `schemas/connection-definition.schema.json`, as
    `<pointer>: <message>`; empty when it is schema-valid."""
    return schema_errors(SCHEMA_NAME, instance)


def _utf8(text: str) -> bytes:
    return text.encode("utf-8")


def _attribute_key(attribute: Mapping[str, Any]) -> tuple[bytes, int, tuple[bytes, ...]]:
    """(kind, components): a substream-scope attribute (`components: null`) before any list."""
    components = attribute["components"]
    if components is None:
        return (_utf8(attribute["kind"]), 0, ())
    return (_utf8(attribute["kind"]), 1, tuple(_utf8(c) for c in components))


def normalise_instance(instance: Mapping[str, Any]) -> dict[str, Any]:
    """D3's normal form of a schema-valid instance (idempotent): in each `mat-v1` substream the
    groups of a group basis by id and the attributes by (kind, components), both by UTF-8 bytes.
    Component, species and substream lists keep their order (it is the layout's)."""
    normal = copy.deepcopy(dict(instance))
    for substream in normal.get("substreams", ()):
        basis = substream["conserved_basis"]
        if "groups" in basis:
            basis["groups"] = sorted(basis["groups"], key=lambda group: _utf8(group["id"]))
        substream["attributes"] = sorted(substream["attributes"], key=_attribute_key)
    return normal


def definition_body(instance: Mapping[str, Any]) -> dict[str, Any]:
    """The normalised instance without `template`: the `body` of D3's identity preimage."""
    body = normalise_instance(instance)
    del body["template"]
    return body


def definition_sha256(
    instance: Mapping[str, Any], template_version: str, template_descriptor_sha256: str
) -> str:
    """D3's `definition_sha256` of a schema-valid instance, its template registered at
    (`instance["template"]`, `template_version`) with `template_descriptor_sha256`."""
    preimage = {
        "template": [instance["template"], template_version, template_descriptor_sha256],
        "body": definition_body(instance),
    }
    return document_sha256(preimage)


def species_basis(
    substream: Mapping[str, Any],
    charges: Mapping[str, int],
    reactions: Sequence[Mapping[str, Fraction | int]] = (),
) -> SpeciesBasis:
    """A `mat-v1` substream's conserved basis as Q3.R1's (S, A, z, R), for `material.basis`.

    The true preset is A = I over the substream's components, R = ∅ (Q3.R2). A group basis has the
    declared species, its groups in instance order with their content (a species a group does not
    name has content 0), and `reactions`, the fast reactions of its `fast_reactions` set as
    stoichiometric maps over the species (the caller resolves the reaction set; none when it is
    `null`). `charges` holds each species' charge (from its record)."""
    basis = substream["conserved_basis"]
    if "groups" not in basis:
        components = tuple(substream["components"])
        return SpeciesBasis.true_basis(components, tuple(charges[c] for c in components))
    species = tuple(basis["species"])
    groups = tuple(group["id"] for group in basis["groups"])
    content = tuple(
        tuple(int(group["content"].get(s, 0)) for s in species) for group in basis["groups"]
    )
    if any(set(reaction) - set(species) for reaction in reactions):
        raise ValueError("a fast reaction names a species outside the basis")
    vectors = tuple(tuple(Fraction(reaction.get(s, 0)) for s in species) for reaction in reactions)
    return SpeciesBasis(species, groups, content, tuple(charges[s] for s in species), vectors)
