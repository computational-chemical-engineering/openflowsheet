"""ADR 0008 A1 J1–J3, J5: T07's acceptance for the binding items of Amendment 1 C6.

The amendment names four acceptance items for T07's own test module:
(a) `Job` fixtures with 0, 1 and 3 outputs validate, the last mixing kinds;
(b) the lifecycle checker accepts a stream with two output events and a progress event before the
    event that ends the job, and the job's output list afterwards holds the two references in
    order;
(c) a request with an operation outside the enum is rejected, and each enum value has exactly one
    request branch;
(d) each shipped consumer ignores an output and an event of unknown kind without error, and
    recognizes an unknown-kind event that ends the job through J5's member.

Items (b) and (c) are here from W1; item (a) from W4a, whose fixtures are emitted by real jobs
(`scripts/t07_schema_fixtures.py`, R-015). Item (d) needs the shipped consumers and joins this
module with each: the CLI's from W5b; HTTP's and MCP's with W6. The kinds T07 names for (b) are
`output`, `progress` and `ended`, and J5's member is `ends_job` (design note §5.6).
"""

