# -- the corpus (§9.4) ---------------------------------------------------------------------------


def _parse(path: Path) -> Any:
    text = path.read_text(encoding="utf-8")
    if path.suffix == ".json":
        return json.loads(text)
    return yaml.safe_load(text)


def _excluded(relative: str) -> bool:
    parts = relative.split("/")
    if relative.startswith("tests/fixtures/") and "invalid" in parts:
        return True  # registered schema-invalid fixtures
    return relative.startswith("benchmarks/t07/v17/runs/")  # recorded campaign artifacts


def _corpus() -> dict[str, Document]:
    listed = subprocess.run(
        ["git", "ls-files", "-z", "--", *CORPUS_ROOTS],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8")
    corpus: dict[str, Document] = {}
    for relative in sorted(filter(None, listed.split("\0"))):
        if Path(relative).suffix not in (".json", ".yaml", ".yml") or _excluded(relative):
            continue
        try:
            document = _parse(REPO_ROOT / relative)
        except (ValueError, yaml.YAMLError, UnicodeDecodeError):
            continue  # a file that does not parse is not in the corpus
        if isinstance(document, dict) and all(key in document for key in CORPUS_KEYS):
            corpus[relative] = document
    return corpus


CORPUS = _corpus()


def _instances(document: Document) -> Iterator[Mapping[str, Any]]:
    for instance in document["instances"]:
        if isinstance(instance, Mapping):
            yield instance


def _model_id(instance: Mapping[str, Any]) -> Any:
    model = instance.get("model")
    return model.get("id") if isinstance(model, Mapping) else None


