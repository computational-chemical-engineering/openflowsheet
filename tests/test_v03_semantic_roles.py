def _sha256(document: Document) -> str | None:
    try:
        return document_sha256(document)
    except Exception:  # a non-canonical document is refused typed by the binder, not here
        return None


def _outcome(document: Document) -> tuple[Any, ...]:
    try:
        answer = bind_revision_flowsheet(document)
    except Exception as error:
        return ("raised", type(error).__name__, str(error))
    return s11_identity_recorder.outcome(answer, _sha256(document))


def _all_other(document: Document) -> Document:
    altered = copy.deepcopy(document)
    for instance in altered["instances"]:
        if isinstance(instance, dict) and "semantic_role" in instance:
            instance["semantic_role"] = "other"
    return altered


def test_a31_b_the_role_does_not_move_a_binding_outcome() -> None:
    differing = [
        path
        for path, document in CORPUS.items()
        if _outcome(document) != _outcome(_all_other(document))
    ]
    assert differing == []


def _nudge(
    document: Document, unit: str, parameter: str, step: Callable[[float], float]
) -> Document:
    altered = copy.deepcopy(document)
    (instance,) = (i for i in altered["instances"] if i["id"] == unit)
    instance["parameters"][parameter]["value"] = step(instance["parameters"][parameter]["value"])
    return altered


def test_a31_b_control_a_parameter_nudge_moves_the_outcome() -> None:
    """Constructed: GP-M1 with `M`'s efficiency one ulp up, so the comparison sees parameters."""
    document = CORPUS["benchmarks/s11/gp/GP-M1.json"]
    nudged = _nudge(document, "M", "efficiency", lambda v: math.nextafter(v, math.inf))
    assert _outcome(document) != _outcome(nudged)


def test_the_nine_cases_carry_no_other() -> None:
    """The nine regenerated cases hold no `other`, so A31 (b) compares real roles with `other`."""
    pattern = re.compile(r'"semantic_role": "other"')
    assert [path for path in NINE if pattern.search((REPO_ROOT / path).read_text())] == []
