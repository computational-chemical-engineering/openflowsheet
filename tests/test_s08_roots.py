# -- A10: D1 through Stage A, and through Stage B when Stage A is forced to fail -------------------


def test_a10_d1_is_wo_g_s_root_through_stage_a() -> None:
    """A10: D1 reaches WO-G's root `(V, V, 2P, 2P, 2P)` through Stage A, with no `reentry`."""
    answer = solved("D1")
    check_root("D1", answer)
    assert answer.reentry is None
    assert source(answer.result) == PRESOLVE_ID


def _stage_a_stalls(monkeypatch: pytest.MonkeyPatch) -> None:
    """Stage A's solve (and only Stage A's: `initializer_source` is the pre-solve's) answers
    `HOMOTOPY_STALLED`, a trigger of §5.1 (i)."""
    real = solve_module.target_attempt

    def stalled(*args: Any, **kwargs: Any) -> Any:
        result, recovered_from, regimes, failures, unsupported = real(*args, **kwargs)
        if kwargs.get("initializer_source", PRESOLVE_ID) != PRESOLVE_ID:
            return result, recovered_from, regimes, failures, unsupported
        typed = replace(result, outcome="HOMOTOPY_STALLED", message="homotopy_stalled(stub)")
        return typed, recovered_from, regimes, (), None

    monkeypatch.setattr(solve_module, "target_attempt", stalled)


def test_a10_d1_through_stage_b_when_stage_a_fails(monkeypatch: pytest.MonkeyPatch) -> None:
    """A10: with Stage A stubbed to `HOMOTOPY_STALLED`, Stage B's `(2, 0)` gives the same root:
    WO-G's, and Stage A's unstubbed answer within the state tolerance."""
    _stage_a_stalls(monkeypatch)
    answer = solve_column(D1, PROVIDER)
    assert isinstance(answer, ColumnSolution), answer
    assert answer.reentry is not None and answer.reentry.trigger == "HOMOTOPY_STALLED"
    assert answer.reentry.stage_a.cause == "homotopy_stalled(stub)"
    check_stage_b("D1", answer)
    check_root("D1", answer)
    worst = deviation_from(D1, dict(solved("D1").state), answer.state)
    assert max(worst.values()) <= 1.0, worst


# -- A11: core decoupling --------------------------------------------------------------------------


def test_a11_p3_and_f1_share_their_core() -> None:
    """A11: stages 1–3 of P3 and F1 (`T`, `l`, `v`, and `Q_1`) agree within the state tolerance."""
    p3, f1 = solved("P3").state, solved("F1").state
    for j in (1, 2, 3):
        name = stage_temperature_id(UNIT, j)
        assert abs(p3[name] - f1[name]) <= T_ABS, name
        for c in P3.components:
            for column in (liquid_id, vapor_id):
                name = column(UNIT, j, c)
                assert abs(p3[name] - f1[name]) <= FLOW_REL * abs(f1[name]) + FLOW_ABS, name
    name = stage_duty_id(UNIT, 1)
    assert abs(p3[name] - f1[name]) <= Q_ABS


# -- A14 (b), (c): mutations that must break A08 ---------------------------------------------------


def test_a14b_stripping_the_l_block_fails_a08(monkeypatch: pytest.MonkeyPatch) -> None:
    """A14 (b): with the L-block given `S_ij = K_ij ρ` in the tridiagonal (the core bottom's `T`
    and `ρ` on the L-block stages, so its vapour is no longer exactly zero), P3's only candidate
    is refused (its L-block energy has no root on the domain), Stage A's typed answer is
    returned, and A08 fails."""
    real = blocks_module._core_flows

    def stripped(*args: Any) -> Any:
        spec, provider, carry, core, temperatures, rho, phi = args
        bottom = core[-1]
        temperatures = {j: temperatures.get(j, temperatures[bottom]) for j in carry}
        rho = {j: rho.get(j, rho[bottom]) for j in carry}
        return real(spec, provider, carry, carry, temperatures, rho, phi)

    monkeypatch.setattr(blocks_module, "_core_flows", stripped)
    answer = solve_column(P3, PROVIDER)
    with pytest.raises(AssertionError):
        check_a08(answer)
    assert isinstance(answer, ColumnSolution) and answer.outcome in REENTRY_OUTCOMES
    assert answer.reentry is not None and [r.endpoint for r in answer.reentry.candidates] == [
        "initialization_failed(s08-block-endpoint-v1, block_energy_outside_domain)"
    ]


def test_a14c_the_core_bottom_s_bubble_temperature_on_the_l_block_fails_a08(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A14 (c): with every L-block `T_j` set to the core bottom's bubble `T` instead of §5.3 step
    5's energy solve, P3's candidate is refused (`inadmissible_endpoint(4)`) and A08 fails."""
    real = blocks_module._block_stage

    def bubble(
        spec: Any, provider: Any, stage: int, flows: Any, phase: str, neighbour: Any
    ) -> float:
        if phase == "LIQUID" and neighbour is not None:
            return float(neighbour[1])  # the stage above: the core bottom, or its copy
        return float(real(spec, provider, stage, flows, phase, neighbour))

    monkeypatch.setattr(blocks_module, "_block_stage", bubble)
    answer = solve_column(P3, PROVIDER)
    with pytest.raises(AssertionError):
        check_a08(answer)
    assert isinstance(answer, ColumnSolution) and answer.reentry is not None
    assert [r.endpoint for r in answer.reentry.candidates] == [
        "initialization_failed(s08-block-endpoint-v1, inadmissible_endpoint(4))"
    ]
