"""S08 WO-4 — the registered block roots: S08 design note §6.2 and §7 A07, A08, A10, A11 and
A14 (b), (c); A01 and the inline specs against WO-G's record.

Expectations are WO-G's 50-digit roots in `docs/derivations/scripts/s08_reference.json` (R-732;
generated by `s08_reference.py`, which imports nothing from `src/`) and §6.2's closed form for P2.
A root agrees when every column is within S02 §10's state tolerance (`deviation_from` ≤ 1) and
every pin of the record is `+0.0` with its sign bit checked. A09 (F1) is in `test_s08_reentry.py`
beside the mutations that must break it; its root check is `check_root` here. Each test names the
assertion of §7 it closes.
"""

