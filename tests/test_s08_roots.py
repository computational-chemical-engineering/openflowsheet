REFERENCE_PATH = REPO_ROOT / "docs" / "derivations" / "scripts" / "s08_reference.json"
#: The record as WO-G committed it (`s08_reference.py --check` byte-compares it).
REFERENCE_SHA256 = "55eed532c8a2a0421ccb00c8c1cc4c598c71db7763eb78afff4c6e57c64bd52c"
REFERENCE: dict[str, Any] = json.loads(REFERENCE_PATH.read_bytes())
CASES: dict[str, ColumnSpec] = {"P2": P2, "P3": P3, "F1": F1, "D1": D1}


@cache
def solved(name: str) -> ColumnSolution:
    """`solve_column` on a §6.2 case, unmutated, once per session."""
    answer = solve_column(CASES[name], PROVIDER)
    assert isinstance(answer, ColumnSolution), answer
    return answer


def source(result: RegionResult) -> str:
    """The `initializer_source` of a solve's attempt 0 (its certificate's)."""
    return str(result.branch_provenance[0]["initializer_source"])


def root_deviation(name: str, state: Any) -> dict[str, float]:
    """The worst error of `state` against WO-G's root of `name`, per kind, in units of S02 §10's
    state tolerance (≤ 1 passes)."""
    spec = CASES[name]
    expected = stages_state(spec, REFERENCE["cases"][name]["root"]["stages"])
    return deviation_from(spec, expected, state)


def check_root(name: str, answer: Any) -> None:
    """`answer` is `CONVERGED` at WO-G's root of `name`: its signature, every column within the
    state tolerance, and every pinned flow of the record exactly `+0.0`."""
    record = REFERENCE["cases"][name]
    spec = CASES[name]
    assert isinstance(answer, ColumnSolution), answer
    assert (answer.outcome, answer.cause) == ("CONVERGED", "")
    assert answer.signature == tuple(record["signature"])
    worst = root_deviation(name, answer.state)
    assert max(worst.values()) <= 1.0, worst
    for pin in record["pinned_zero"]:
        phase, stage = pin.split("_")
        column = {"l": liquid_id, "v": vapor_id}[phase]
        for c in spec.components:
            value = answer.state[column(UNIT, int(stage), c)]
            assert value == 0.0 and math.copysign(1.0, value) == 1.0, (pin, c, value)


def check_stage_b(name: str, answer: ColumnSolution) -> None:
    """The route of a Stage-B root (§5.1, §5.6): Stage A typed (trigger (i)), one candidate, WO-G's,
    built and accepted; the answer's solve opened from the block endpoint."""
    reentry = answer.reentry
    assert reentry is not None and reentry.trigger in REENTRY_OUTCOMES
    assert reentry.stage_a.outcome == reentry.trigger and reentry.stage_a.failures == ()
    a, c = REFERENCE["cases"][name]["candidate"]
    assert [(r.a, r.c, r.endpoint, r.outcome, r.cause) for r in reentry.candidates] == [
        (a, c, "built", "CONVERGED", "")
    ]
    assert reentry.accepted == 0
    assert source(answer.result) == BLOCK_ENDPOINT_ID


def check_a08(answer: Any) -> None:
    """A08: P3 gives WO-G's root through Stage B."""
    check_root("P3", answer)
    check_stage_b("P3", answer)


# -- WO-G's record ---------------------------------------------------------------------------------


def test_the_reference_is_wo_g_s_record() -> None:
    assert sha256_of(REFERENCE_PATH) == REFERENCE_SHA256
    assert REFERENCE["precision_digits"] == 50 and REFERENCE["inputs_changed"]["cases"] == []


def _inlet(record: dict[str, Any] | None) -> Any:
    if record is None:
        return None
    return (tuple(float(n) for n in record["n"]), float(record["T"]), float(record["P"]))


@pytest.mark.parametrize("name", list(CASES))
def test_the_inline_specs_are_the_registered_inputs(name: str) -> None:
    """The specs the S08 tests solve (`test_s08_blocks.py`, §6.2) are WO-G's inputs, exactly."""
    spec, inputs = CASES[name], REFERENCE["cases"][name]["inputs"]

    def end(value: Any) -> Any:
        return None if value is None else (value.kind, value.value)

    def end_record(record: dict[str, Any] | None) -> Any:
        return None if record is None else (record["kind"], float(record["value"]))

    def inlet(state: Any) -> Any:
        if state is None:
            return None
        return (tuple(state.n), state.temperature, state.pressure)

    assert spec.stage_count == inputs["stage_count"]
    assert spec.pressures == tuple(float(p) for p in inputs["pressures"])
    assert spec.duties == tuple(None if q is None else float(q) for q in inputs["duties"])
    assert (spec.condenser, spec.reboiler) == (inputs["condenser"], inputs["reboiler"])
    assert end(spec.condenser_spec) == end_record(inputs["condenser_spec"])
    assert end(spec.reboiler_spec) == end_record(inputs["reboiler_spec"])
    for port in ("top", "bottom"):
        state, record = getattr(spec, port), inputs[port]
        assert inlet(state) == _inlet(record), port
        assert state is None or state.phase == record["phase"], port
    assert [
        (side.port, side.stage, inlet(side.state), side.state.phase) for side in spec.sides
    ] == [(side["port"], side["stage"], _inlet(side), side["phase"]) for side in inputs["sides"]]


def test_a01_candidate_lists_equal_wo_g_s_transcription() -> None:
    """A01 against WO-G's independent transcription of §5.2 (all 13 specifications)."""
    recorded = REFERENCE["candidate_lists"]
    names = {key.replace(".", " "): key for key in EXPECTED_CANDIDATES}
    assert set(recorded) == set(names)
    for name, record in recorded.items():
        spec, _ = EXPECTED_CANDIDATES[names[name]]
        assert candidates(spec) == tuple(tuple(pair) for pair in record["candidates"]), name


# -- A07: P2, the closed form through Stage B ------------------------------------------------------


def test_a07_p2_is_the_closed_form_through_stage_b() -> None:
    """A07 (§6.2): P2 is `CONVERGED` at V×5 through Stage B's `(5, 0)`: `v_j` the bottom inlet on
    every stage, `T_j = 420` K for j ≥ 2 and `T_1 = 420 + Q_c*/(F C_P) = 390` K, every `l_j`
    (the bottoms) `+0.0`; and WO-G's root."""
    answer = solved("P2")
    check_stage_b("P2", answer)
    check_root("P2", answer)
    feed = P2.bottom
    assert feed is not None
    for j in P2.equilibrium_stages():
        temperature = answer.state[stage_temperature_id(UNIT, j)]
        assert abs(temperature - (390.0 if j == 1 else 420.0)) <= T_ABS, (j, temperature)
        for c, n in zip(P2.components, feed.n, strict=True):
            assert abs(answer.state[vapor_id(UNIT, j, c)] - n) <= FLOW_REL * n + FLOW_ABS
    (attempt,) = answer.result.attempts
    assert attempt.outcome == "CONVERGED" and answer.recovered_from is None


