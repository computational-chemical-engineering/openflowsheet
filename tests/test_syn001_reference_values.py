def test_a4_k_values_match_the_reference_grid(reference_values: dict[str, Any]) -> None:
    """Every `K_values` entry of the reference file (specification §4 A.4)."""
    grid = reference_values["K_values"]
    assert isinstance(grid, dict) and grid, "the reference file has no K_values table"
    for key, expected in grid.items():
        match = K_GRID_KEY.match(key)
        assert match is not None, f"unparsable K_values key {key!r}"
        actual = k_values(float(match.group("T")), float(match.group("P")))
        for index in COMPONENTS:
            close(actual[index], expected[index])


def test_a4_reference_constants_match_the_oracle_constants(
    reference_values: dict[str, Any],
) -> None:
    """The oracle's `Syn001Constants` are the constants the reference was generated from."""
    constants = reference_values["constants"]
    close(SYN001.R, constants["R"])
    close(SYN001.T_r, constants["T_r_K"])
    close(SYN001.P_r, constants["P_r_Pa"])
    for index in COMPONENTS:
        close(SYN001.c_p[index], constants["c_p_J_per_mol_K"])
        close(SYN001.T_b[index], constants["T_b_K"][index])
        close(SYN001.L[index], constants["L_J_per_mol"][index])
        close(SYN001.v[index], constants["v_m3_per_mol"][index])
        close(SYN001.M[index], constants["M_kg_per_mol"][index])


def test_a3_pure_component_checks_match_the_reference(reference_values: dict[str, Any]) -> None:
    """K_i(T_b,i, P_r) = 1 and h_i^V - h_i^L = L_i, against the reference file's own values."""
    checks = reference_values["pure_component_checks"]
    for index, name in enumerate(("A", "B", "C")):
        close(k_values(SYN001.T_b[index], SYN001.P_r)[index], checks[f"K_{name}(T_b,P_r)"])
        close(SYN001.L[index], checks[f"h_vap_{name}_at_P_r_J_per_mol"])


def test_a4_fresh_feed_summary_values_match_the_reference(
    reference_values: dict[str, Any],
) -> None:
    """`sum z K` at 350 K and 310 K, and `sum z/K` at 420 K, for the equimolar feed."""
    feed = reference_values["fresh_feed"]
    z = 1.0 / 3.0
    close(math.fsum(z * k for k in k_values(350.0, SYN001.P_r)), feed["sum_zK_at_350K"])
    close(math.fsum(z * k for k in k_values(310.0, SYN001.P_r)), feed["sum_zK_at_310K"])
    close(math.fsum(z / k for k in k_values(420.0, SYN001.P_r)), feed["sum_z_over_K_at_420K"])


