@pytest.mark.parametrize("case_id", VARIANT_IDS)
def test_e_zero_flow_streams_are_exactly_zero(
    case_id: str, reference_values: dict[str, Any]
) -> None:
    """A dormant stream is exactly 0.0 in every component, not merely small (ADR 0001 D3.1)."""
    expected = variant(reference_values, case_id)
    result = result_for(case_id)
    dormant = {
        "recycle_phase_signature": result.recycle,
        "purge_phase_signature": result.purge,
        "vapor_product_phase_signature": result.vapor_product,
    }
    checked = 0
    for key, stream in dormant.items():
        if expected[key] != "ZERO_FLOW":
            continue
        for index in COMPONENTS:
            assert stream[index] == 0.0, f"{key} component {index} is {stream[index]!r}"
            assert math.copysign(1.0, stream[index]) > 0.0, "signed zero was not normalized"
        checked += 1
    if case_id in ("SYN-001-once-through", "SYN-001-all-liquid-310K"):
        assert checked == 1
    elif case_id == "SYN-001-all-vapor-420K":
        assert checked == 2


