PLAN_NOMINAL = {
    "q": 0.4150855900,
    "L": 3.2783818616,
    "V": 1.3608090692,
    "x": (0.1816607866, 0.3333333333, 0.4850058800),
}


def test_d_nominal_matches_the_plan_printed_digits() -> None:
    """q, L, V and x against the digits printed in implementation plan §3.2 (§4 D)."""
    result = result_for("SYN-001-nominal")
    assert result.q is not None
    liquid = math.fsum(result.recycle) + math.fsum(result.purge)
    assert result.q == pytest.approx(PLAN_NOMINAL["q"], abs=1e-10)
    assert liquid == pytest.approx(PLAN_NOMINAL["L"], abs=1e-10)
    assert result.flash.V == pytest.approx(PLAN_NOMINAL["V"], abs=1e-10)
    assert result.flash.x is not None
    for index in COMPONENTS:
        assert result.flash.x[index] == pytest.approx(PLAN_NOMINAL["x"][index], abs=1e-10)


def test_d_nominal_residuals_are_far_inside_the_registered_tolerances() -> None:
    """balance_residual <= 1e-14 mol/s and energy_residual <= 1e-9 W (specification §4 D)."""
    result = result_for("SYN-001-nominal")
    assert max(abs(value) for value in result.balance_residual) <= 1e-14
    assert abs(result.energy_residual) <= 1e-9


