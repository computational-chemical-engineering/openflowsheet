"""SYN-001 oracle compared against Fable's independent 20-digit reference values.

Implements items A.4, the reference half of C, D, E and L of
`docs/derivations/SYN-001-oracle-spec.md` §4.

`benchmarks/syn001/reference_values.yaml` was generated by Fable with mpmath at 40 significant
digits from the plan §3.1 definitions only, by
`docs/derivations/scripts/syn001_reference.py`. It is independent of the oracle implementation
and is never regenerated from it: that would turn an independent expectation into a
self-generated regression fixture (CLAUDE.md, "Scientific conduct"). This file only reads it. A
disagreement is reported as a failure, not accommodated by loosening a tolerance.

Comparison tolerance, from the specification: relative 1e-13 or absolute 1e-14, whichever is
looser, unless a tighter or looser one is stated for a particular quantity.
"""

from __future__ import annotations

import math
import re
from pathlib import Path
from typing import Any

import pytest
from conftest import load_json, sha256_of

from benchmarks.syn001.oracle import SYN001, k_values, recycle_oracle

FRESH_FEED = (1.0, 1.0, 1.0)
COMPONENTS = (0, 1, 2)

REFERENCE_RELATIVE = 1e-13
REFERENCE_ABSOLUTE = 1e-14

# A template placeholder: an angle bracket immediately followed by a non-space character, as in
# `<actual commit hash>`. Prose such as "r < 1 ... as r -> 1" is not a placeholder, so the
# opening bracket must not be followed by whitespace.
ANGLE_PLACEHOLDER = re.compile(r"<[^<>\s][^<>]*>")
K_GRID_KEY = re.compile(r"^T=(?P<T>[0-9.]+)K,P=(?P<P>[0-9.]+)Pa$")

VARIANT_INPUTS: dict[str, tuple[float, float]] = {
    "SYN-001-nominal": (0.5, 360.0),
    "SYN-001-once-through": (0.0, 360.0),
    "SYN-001-high-recycle": (0.95, 360.0),
    "SYN-001-all-liquid-310K": (0.5, 310.0),
    "SYN-001-all-vapor-420K": (0.5, 420.0),
}

VARIANT_IDS = tuple(VARIANT_INPUTS)


def close(actual: float, expected_text: str | float, *, rel: float = REFERENCE_RELATIVE) -> None:
    """Assert `actual` matches the reference, at `rel` relative or 1e-14 absolute, whichever is
    looser. The reference is parsed from its decimal string; no rounding of the reference."""
    expected = float(expected_text)
    tolerance = max(REFERENCE_ABSOLUTE, rel * abs(expected))
    assert abs(actual - expected) <= tolerance, (
        f"got {actual!r}, reference {expected_text!r}, "
        f"deviation {abs(actual - expected):.3e} > tolerance {tolerance:.3e}"
    )


def variant(reference_values: dict[str, Any], case_id: str) -> dict[str, Any]:
    for entry in reference_values["variants"]:
        if entry["case_id"] == case_id:
            assert isinstance(entry, dict)
            return entry
    raise AssertionError(f"{case_id} is not present in reference_values.yaml")


def result_for(case_id: str) -> Any:
    r, T_flash = VARIANT_INPUTS[case_id]
    return recycle_oracle(FRESH_FEED, r, T_flash, case_id=case_id)


def is_undefined(reference_field: Any) -> bool:
    """The reference file writes `undefined ...` where a composition or ratio does not exist."""
    return isinstance(reference_field, str) and reference_field.startswith("undefined")


