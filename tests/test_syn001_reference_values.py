@pytest.mark.parametrize("case_id", VARIANT_IDS)
def test_c_fresh_feed_flash_matches_the_reference(
    case_id: str, reference_values: dict[str, Any]
) -> None:
    """The fresh-feed flash at (T_flash, P_r): state, beta, x, y, V, K (specification §4 C)."""
    expected = variant(reference_values, case_id)
    flash = result_for(case_id).flash
    assert flash.state == expected["flash_phase_state"]
    close(flash.beta, expected["beta_fresh_feed_vapor_fraction"])
    close(flash.V, expected["V_mol_per_s"])
    close(flash.sum_zK, expected["sum_zK_fresh"])
    close(flash.sum_z_over_K, expected["sum_z_over_K_fresh"])
    for index in COMPONENTS:
        close(flash.K[index], expected["K_at_flash"][index])
    if is_undefined(expected["x"]):
        assert flash.x is None
    else:
        assert flash.x is not None
        for index in COMPONENTS:
            close(flash.x[index], expected["x"][index])
        assert math.fsum(flash.x) == pytest.approx(1.0, abs=1e-14)
    if is_undefined(expected["y"]):
        assert flash.y is None
    else:
        assert flash.y is not None
        for index in COMPONENTS:
            close(flash.y[index], expected["y"][index])
        assert math.fsum(flash.y) == pytest.approx(1.0, abs=1e-14)
    assert abs(flash.rr_residual) <= 1e-14


