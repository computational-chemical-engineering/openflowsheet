def _strings(node: Any, path: str = "$") -> list[tuple[str, str]]:
    if isinstance(node, str):
        return [(path, node)]
    if isinstance(node, dict):
        found: list[tuple[str, str]] = []
        for key, value in node.items():
            found.extend(_strings(key, f"{path}.<key>"))
            found.extend(_strings(value, f"{path}.{key}"))
        return found
    if isinstance(node, list):
        return [
            item for index, value in enumerate(node) for item in _strings(value, f"{path}[{index}]")
        ]
    return []


def test_l_reference_file_parses_and_has_no_angle_bracket_placeholders(
    reference_values: dict[str, Any],
) -> None:
    """The file parses, and no value is a template placeholder (specification §4 L)."""
    assert reference_values["variants"], "the reference file registers no variants"
    offenders = [
        f"{path}: {text}"
        for path, text in _strings(reference_values)
        if ANGLE_PLACEHOLDER.search(text)
    ]
    assert not offenders, "angle-bracket placeholders are never valid values: " + "; ".join(
        offenders
    )


def test_l_every_reference_variant_is_registered(
    reference_values: dict[str, Any], registry: dict[str, Any]
) -> None:
    """Every variant in the reference file appears in benchmarks/registry.yaml (§4 L)."""
    registered = {case["case_id"] for case in registry["cases"]}
    for entry in reference_values["variants"]:
        assert entry["case_id"] in registered, f"{entry['case_id']} is not registered"


def test_l_registry_records_the_reference_file_digest(repo_root: Path) -> None:
    """The registry pins the exact reference bytes it was registered against."""
    digest = sha256_of(repo_root / "benchmarks" / "syn001" / "reference_values.yaml")
    registry_text = (repo_root / "benchmarks" / "registry.yaml").read_text(encoding="utf-8")
    assert digest in registry_text, (
        f"benchmarks/registry.yaml does not record the current reference digest {digest}; "
        "either the reference file changed deliberately, in which case update the registry, "
        "or it changed by accident"
    )


def test_l_reference_digest_is_recorded_in_the_p01_evidence_manifest(repo_root: Path) -> None:
    """Specification §4 L: the sha256 of the reference file is recorded in the P01 manifest.

    Fable writes `evidence/P01/<commit>/manifest.json`; Opus must not write an evidence
    manifest for a package it does not lead. Until it exists this test skips with the reason,
    and it fails if a manifest exists without the digest.
    """
    manifests = sorted((repo_root / "evidence" / "P01").glob("*/manifest.json"))
    if not manifests:
        pytest.skip(
            "no evidence/P01/<commit>/manifest.json yet; Fable 5.1 leads P01 and writes it "
            "after verification (CLAUDE.md, 'Branch and merge discipline')"
        )
    digest = sha256_of(repo_root / "benchmarks" / "syn001" / "reference_values.yaml")
    for manifest_path in manifests:
        blob = load_json(manifest_path)
        assert digest in repr(blob), (
            f"{manifest_path} does not record the reference file digest {digest}"
        )
