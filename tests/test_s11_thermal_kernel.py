def _agrees(closure: k.Closure, expected: dict[str, Any], t_sat: float) -> None:
    beta = expected["beta"]
    if closure.regime == expected["regime"]:
        assert abs(closure.temperature - expected["T"]) <= CLOSURE_T_TOL
        if beta is not None:
            assert closure.beta is not None
            assert abs(closure.beta - beta) <= CLOSURE_BETA_TOL
        return
    # A boundary point (quality exactly 0 or 1): the adjacent single-phase regime at T_sat.
    adjacent = {0.0: "LIQUID", 1.0: "VAPOR"}
    assert beta in adjacent, (closure.regime, expected)
    assert closure.regime == adjacent[beta]
    assert abs(closure.temperature - t_sat) <= CLOSURE_T_TOL


@pytest.mark.parametrize(
    ("component", "point", "key"),
    GRID_CASES,
    ids=[f"{c}-{p['label']}-{key}" for c, p, key in GRID_CASES],
)
def test_a43_a44_closures_equal_coolprops_flash(
    component: str, point: dict[str, Any], key: str
) -> None:
    provider = _provider(component)
    total = 2.5
    if key == "ph":
        closure = _ok(k.ph_closure(provider, total, point["P"], total * point["h"], CONTEXT))
    else:
        closure = _ok(k.ps_closure(provider, total, point["P"], total * point["s"], CONTEXT))
    expected = point[key]
    sat = k.saturation(provider, point["P"], CONTEXT)
    t_sat = math.nan if isinstance(sat, k.Failure) else sat.temperature
    _agrees(closure, expected, t_sat)


