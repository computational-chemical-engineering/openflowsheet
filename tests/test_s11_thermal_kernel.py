def _psat(temperature: float) -> float:
    result = WATER.evaluate_phase(
        PropertyRequest(
            state=StreamState((1.0,), temperature, P_ATM), phase="LIQUID", properties=("Psat",)
        ),
        CONTEXT,
    )
    assert result.status == "ok", result.message
    return float(result.values["Psat"])


def test_a45_a_state_past_the_margin_is_refused() -> None:
    temperature = 360.0
    p_sat = _psat(temperature)
    vapour_side = p_sat * (1.0 - 1e-7)
    assert k.declared_admissible(WATER, temperature, vapour_side, "LIQUID", CONTEXT) is False
    assert k.declared_admissible(WATER, temperature, vapour_side, "VAPOR", CONTEXT) is True
    # Inside eps_sigma the provider still answers the liquid, so a target exists; the declared
    # outlet is refused because its root is not on the liquid side of T_sat(P).
    jets = _ok(k.phase_properties(WATER, CONTEXT, temperature, vapour_side, "LIQUID", ("h",)))
    answer = k.declared_state(WATER, 1.0, vapour_side, jets["h"][0], "LIQUID", "h", CONTEXT)
    assert isinstance(answer, k.Mismatch)
    assert answer.regime == "SATURATED"
    liquid_side = p_sat * (1.0 + 1e-7)
    assert k.declared_admissible(WATER, temperature, liquid_side, "VAPOR", CONTEXT) is False
    within = p_sat * (1.0 - 5e-10)
    assert k.declared_admissible(WATER, temperature, within, "LIQUID", CONTEXT) is True


def _admissibility_grid() -> list[tuple[float, float]]:
    factors = (
        0.5,
        1.0 - 1e-6,
        1.0 - 2e-9,
        1.0 - 5e-10,
        1.0,
        1.0 + 5e-10,
        1.0 + 2e-9,
        1.0 + 1e-6,
        2.0,
        1.0 + 1e-3,
    )
    temperatures = [280.0 + 19.0 * i for i in range(18)] + [650.0, 700.0]
    points = []
    for temperature in temperatures:
        if temperature < 647.0:
            p_sat = _psat(temperature)
            pressures = [p_sat * factor for factor in factors]
        else:
            pressures = [1.0e3, 1.0e5, 1.0e6, 5.0e6, 1.0e7, 2.5e7, 3.0e7, 5.0e7, 8.0e7, 1.0e8]
        points.extend((temperature, pressure) for pressure in pressures)
    return points


def test_a45_declared_admissible_agrees_with_the_verifier_on_200_points() -> None:
    grid = _admissibility_grid()
    assert len(grid) == 200
    compared = 0
    for temperature, pressure in grid:
        stream = StreamState((1.0,), temperature, pressure)
        for phase in ("LIQUID", "VAPOR"):
            violation, _ = _pure_fluid_margin(WATER, stream, phase, CONTEXT)  # type: ignore[arg-type]
            mine = _ok(k.declared_admissible(WATER, temperature, pressure, phase, CONTEXT))  # type: ignore[arg-type]
            if violation is None:
                continue
            compared += 1
            assert mine is (violation == 0.0), (temperature, pressure, phase)
    assert compared == 400


# -- S11.A46 Jacobians against central differences ------------------------------------------------

FD_STEP = 1e-6
FD_TOL = 1e-6


def _fd_worst(block: Any, inputs: Sequence[float], step: float = FD_STEP) -> float:
    """The worst disagreement of the analytic Jacobian with central differences at `step`.

    Each entry is judged in scaled units: relative to the larger of |dF_i/dx_j| and |F_i/x_j|,
    the entry the solver sees after scaling (S11C_DECISIONS C1-3). For an entry whose elasticity
    (x/F)(dF/dx) is at least 1 this is the plain relative error; an entry far below its output's
    scale (a liquid's dh/dP) is below the difference quotient's rounding at a 1e-6 step, and its
    value is pinned by the thermodynamic identities of `test_a46_identities_pin_the_small_entries`.
    """
    analytic = {(i, j): value for i, j, value in block.jacobian(inputs)}
    assert set(analytic) == set(block.jacobian_pattern())
    centre = block.values(inputs)
    worst = 0.0
    for j, x in enumerate(inputs):
        h = step * abs(x) if x != 0.0 else step
        up = list(inputs)
        down = list(inputs)
        up[j] = x + h
        down[j] = x - h
        f_up, f_down = block.values(up), block.values(down)
        for i in range(len(block.output_ids)):
            if (i, j) not in analytic:
                assert f_up[i] == f_down[i]
                continue
            fd = (f_up[i] - f_down[i]) / ((x + h) - (x - h))
            exact = analytic[(i, j)]
            scale = max(abs(exact), abs(centre[i]) / abs(x) if x != 0.0 else 0.0)
            worst = max(worst, abs(fd - exact) / scale)
    return worst


def _liquid_pressure(i: int, temperature: float) -> float:
    if temperature < 370.0:
        return (1.0e5, 3.0e7)[i % 2]
    if temperature < 450.0:
        return (1.0e6, 1.0e7)[i % 2]
    return (1.0e7, 3.0e7)[i % 2]


LIQUID_STATES = [
    (0.5 + 0.3 * i, 280.0 + 15.0 * i, _liquid_pressure(i, 280.0 + 15.0 * i)) for i in range(20)
]
VAPOR_STATES = [
    (0.5 + 0.3 * i, 420.0 + 20.0 * i, pressure)
    for i, pressure in enumerate([1.0e3, 1.0e4, 5.0e4, 1.0e5] * 5)
]


@pytest.mark.parametrize(("phase", "states"), [("LIQUID", LIQUID_STATES), ("VAPOR", VAPOR_STATES)])
def test_a46_phase_flow_block_jacobian(phase: str, states: list[tuple[float, ...]]) -> None:
    block = PhaseFlowBlock(WATER, "H2O", phase, CONTEXT, block_id=phase_block_id("S1", phase))  # type: ignore[arg-type]
    assert len(states) == 20
    worst = max(_fd_worst(block, state) for state in states)
    assert worst <= FD_TOL, worst


def test_a46_saturated_flow_block_jacobian_including_the_range_ends() -> None:
    from openflowsheet.thermo.iapws95 import _tsat_bounds  # noqa: PLC0415

    low, high = _tsat_bounds()
    block = SaturatedFlowBlock(WATER, "H2O", CONTEXT, block_id=saturated_block_id("S1"))
    pressures = [low * 1.5 * 1.6**i for i in range(18)]
    assert pressures[-1] < high
    worst = max(
        _fd_worst(block, (0.3 + 0.1 * i, 1.2 - 0.05 * i, p)) for i, p in enumerate(pressures)
    )
    # Within 1e-6 of each end the central step must stay inside the range: half the step there.
    worst = max(worst, _fd_worst(block, (0.7, 0.4, low * (1.0 + 1e-6)), step=0.5 * FD_STEP))
    assert worst <= FD_TOL, worst


#: S11.A46 at the two near-top states (restated, R-834): the provider's Maxwell floor bounds the
#: central quotient's error by eps_H/(h |elasticity|) = 1.29e-11/(1e-6 * 3.39) = 3.8e-6 at every
#: admissible step; one fixed bound above it, no measured-noise term.
FD_TOL_TOP = 1e-5


def test_a46_saturated_flow_block_at_the_top_of_the_range() -> None:
    """S11.A46 (restated, R-834): at P = p_sigma(647.0 K)(1 - 1e-6) and (1 - 1e-4), a central step
    of 1e-6 agrees within 1e-5, and the upper stencil point stays below p_sigma(647.0 K)."""
    from openflowsheet.thermo.iapws95 import _tsat_bounds  # noqa: PLC0415

    _, high = _tsat_bounds()
    block = SaturatedFlowBlock(WATER, "H2O", CONTEXT, block_id=saturated_block_id("S1"))
    worst = 0.0
    for below in (1e-6, 1e-4):
        state = (0.7, 0.4, high * (1.0 - below))
        assert state[2] + FD_STEP * state[2] < high, below
        worst = max(worst, _fd_worst(block, state, step=FD_STEP))
    assert worst <= FD_TOL_TOP, worst


