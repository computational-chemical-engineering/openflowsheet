P_ATM = 101325.0


def _water_target(case: str) -> float:
    sat = _ok(k.saturation(WATER, P_ATM, CONTEXT))
    if case == "LIQUID":
        jets = _ok(k.phase_properties(WATER, CONTEXT, 330.0, P_ATM, "LIQUID", ("h",)))
        return float(jets["h"][0])
    if case == "VAPOR":
        jets = _ok(k.phase_properties(WATER, CONTEXT, 450.0, P_ATM, "VAPOR", ("h",)))
        return float(jets["h"][0])
    return 0.5 * (sat.value("LIQUID", "h") + sat.value("VAPOR", "h"))


@pytest.mark.parametrize("regime", ["LIQUID", "VAPOR", "SATURATED"])
@pytest.mark.parametrize("form", ["LIQUID", "VAPOR", "SATURATED"])
def test_a45_declared_state_table(form: k.Regime, regime: str) -> None:
    total = 3.0
    answer = k.declared_state(
        WATER, total, P_ATM, total * _water_target(regime), form, "h", CONTEXT
    )
    if form == regime:
        assert isinstance(answer, k.Outlet)
        assert answer.form == form
        expected = {"LIQUID": 330.0, "VAPOR": 450.0}.get(regime)
        if expected is not None:
            assert abs(answer.temperature - expected) <= 1e-9
            assert answer.beta is None
        else:
            assert answer.beta is not None and abs(answer.beta - 0.5) <= 1e-12
        return
    assert isinstance(answer, k.Mismatch)
    failure = answer.failure("S7")
    capability = {"LIQUID": "liquid", "VAPOR": "vapor", "SATURATED": "vapor_liquid"}[regime]
    assert failure.code == "phase_regime_mismatch(S7)"
    assert failure.message.splitlines()[1].endswith(f"declare {capability}")


