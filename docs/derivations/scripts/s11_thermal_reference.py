class UnavailableError(RuntimeError):
    """CoolProp 8.0.0 cannot be imported."""


def _coolprop() -> Any:
    try:
        module = importlib.import_module("CoolProp")
    except ImportError as error:
        raise UnavailableError(f"CoolProp is not importable ({error})") from error
    if module.__version__ != PINNED_VERSION:
        raise UnavailableError(f"CoolProp {module.__version__} is not the pinned {PINNED_VERSION}")
    return importlib.import_module("CoolProp.CoolProp")


def _sanity(what: str, value: float, expected: float, bound: float) -> None:
    if not abs(value - expected) <= bound:
        raise SystemExit(f"sanity: {what} = {value!r} is not within {bound} of {expected}")


class _Fluid:
    def __init__(self, cp: Any, component: str) -> None:
        self._cp = cp
        self.component = component
        self.name = FLUIDS[component]
        self.t_c = float(cp.PropsSI("Tcrit", self.name))
        self.p_c = float(cp.PropsSI("pcrit", self.name))

    def __call__(self, output: str, a: str, x: float, b: str, y: float) -> float:
        return float(self._cp.PropsSI(output, a, x, b, y, self.name))

    def saturation(self, pressure: float) -> dict[str, float]:
        return {
            "P": pressure,
            "T": self("T", "P", pressure, "Q", 0.0),
            "h_liquid": self("Hmolar", "P", pressure, "Q", 0.0),
            "h_vapor": self("Hmolar", "P", pressure, "Q", 1.0),
            "s_liquid": self("Smolar", "P", pressure, "Q", 0.0),
            "s_vapor": self("Smolar", "P", pressure, "Q", 1.0),
        }

    def classify(self, pressure: float, temperature: float, quality: float) -> dict[str, Any]:
        """CoolProp's flash answer as (regime, T, beta); beta only when saturated."""
        if 0.0 <= quality <= 1.0:
            return {"regime": "SATURATED", "T": temperature, "beta": quality}
        if pressure < self.p_c:
            t_sat = self("T", "P", pressure, "Q", 0.0)
            regime = "LIQUID" if temperature < t_sat else "VAPOR"
        else:
            regime = "LIQUID" if temperature < self.t_c else "VAPOR"
        return {"regime": regime, "T": temperature, "beta": None}

    def ph(self, pressure: float, enthalpy: float) -> dict[str, Any]:
        temperature = self("T", "P", pressure, "Hmolar", enthalpy)
        quality = self("Q", "P", pressure, "Hmolar", enthalpy)
        return self.classify(pressure, temperature, quality)

    def ps(self, pressure: float, entropy: float) -> dict[str, Any]:
        temperature = self("T", "P", pressure, "Smolar", entropy)
        quality = self("Q", "P", pressure, "Smolar", entropy)
        return self.classify(pressure, temperature, quality)


def _grid_point(
    fluid: _Fluid, label: str, pressure: float, at: tuple[str, float]
) -> dict[str, Any]:
    key, value = at
    h = fluid("Hmolar", "P", pressure, key, value)
    s = fluid("Smolar", "P", pressure, key, value)
    return {
        "label": label,
        "P": pressure,
        "nominal": {key: value},
        "h": h,
        "s": s,
        "ph": fluid.ph(pressure, h),
        "ps": fluid.ps(pressure, s),
    }


def _units(cp: Any) -> dict[str, Any]:
    water = _Fluid(cp, "H2O")
    units: dict[str, Any] = {}

    # S11.A51: saturated liquid at 1 MPa throttled to 0.1 MPa.
    h1 = water("Hmolar", "P", 1.0e6, "Q", 0.0)
    throttled = water.ph(1.0e5, h1)
    _sanity("A51 beta", throttled["beta"], 0.1528, 5e-4)
    units["A51_throttling"] = {
        "fluid": "H2O",
        "inlet": {"P": 1.0e6, "beta": 0.0, "T": water("T", "P", 1.0e6, "Q", 0.0), "h": h1},
        "outlet": {"P": 1.0e5, **throttled, "T_sat": water("T", "P", 1.0e5, "Q", 0.0)},
    }

    # S11.A52: the heater at 101 325 Pa, n = 1 mol/s.
    p = 101325.0
    sat = water.saturation(p)
    _sanity("A42 T_sat(101325 Pa)", sat["T"], 373.1243, 1e-3)
    dh_vap = sat["h_vapor"] - sat["h_liquid"]
    _sanity("A42 dh_vap(101325 Pa) J/mol", dh_vap, 40650.0, 20.0)
    h300 = water("Hmolar", "T", 300.0, "P", p)
    h500 = water("Hmolar", "T", 500.0, "P", p)
    h_half = water("Hmolar", "P", p, "Q", 0.5)
    units["A52_heater"] = {
        "fluid": "H2O",
        "n": 1.0,
        "P": p,
        "quality_0_to_1": {"Q": dh_vap},
        "t_mode": {"T_in": 300.0, "T_out": 500.0, "Q": h500 - h300},
        "duty_mode": {"T_in": 300.0, "Q": h_half - h300, **water.ph(p, h_half)},
    }

    # S11.A53: the turbine, steam at 3 MPa, 673.15 K -> 10 kPa, eta = 0.85, n = 1 mol/s.
    p_in, t_in, p_out, eta = 3.0e6, 673.15, 1.0e4, 0.85
    h_in = water("Hmolar", "T", t_in, "P", p_in)
    s_in = water("Smolar", "T", t_in, "P", p_in)
    isentropic = water.ps(p_out, s_in)
    h_s = water("Hmolar", "P", p_out, "Smolar", s_in)
    work = eta * (h_s - h_in)
    outlet = water.ph(p_out, h_in + work)
    _sanity("A53 x_s", isentropic["beta"], 0.8366, 5e-4)
    _sanity("A53 x_2", outlet["beta"], 0.9017, 5e-4)
    _sanity("A53 W J/mol", work, -15910.0, 20.0)
    units["A53_turbine"] = {
        "fluid": "H2O",
        "n": 1.0,
        "inlet": {"P": p_in, "T": t_in, "h": h_in, "s": s_in},
        "P_out": p_out,
        "efficiency": eta,
        "isentropic": {**isentropic, "h": h_s},
        "W": work,
        "outlet": outlet,
    }

    # S11.A54: the pump, saturated liquid at 10 kPa -> 3 MPa, eta = 0.75, n = 1 mol/s.
    p_in, p_out, eta = 1.0e4, 3.0e6, 0.75
    h_in = water("Hmolar", "P", p_in, "Q", 0.0)
    s_in = water("Smolar", "P", p_in, "Q", 0.0)
    h_s = water("Hmolar", "P", p_out, "Smolar", s_in)
    work = (h_s - h_in) / eta
    outlet = water.ph(p_out, h_in + work)
    _sanity("A54 W J/mol", work, 72.5, 0.3)
    units["A54_pump"] = {
        "fluid": "H2O",
        "n": 1.0,
        "inlet": {"P": p_in, "beta": 0.0, "T": water("T", "P", p_in, "Q", 0.0), "h": h_in},
        "P_out": p_out,
        "efficiency": eta,
        "isentropic": {**water.ps(p_out, s_in), "h": h_s},
        "W": work,
        "outlet": outlet,
    }

    # S11.A55: the compressor, CO2 at 300 K, 1e5 -> 5e5 Pa, eta = 0.8; and a dry fluid's
    # saturated vapour whose isentropic state at the outlet pressure is two-phase.
    co2 = _Fluid(cp, "CO2")
    p_in, t_in, p_out, eta = 1.0e5, 300.0, 5.0e5, 0.8
    h_in = co2("Hmolar", "T", t_in, "P", p_in)
    s_in = co2("Smolar", "T", t_in, "P", p_in)
    h_s = co2("Hmolar", "P", p_out, "Smolar", s_in)
    work = (h_s - h_in) / eta
    units["A55_compressor"] = {
        "fluid": "CO2",
        "n": 1.0,
        "inlet": {"P": p_in, "T": t_in, "h": h_in},
        "P_out": p_out,
        "efficiency": eta,
        "isentropic": {**co2.ps(p_out, s_in), "h": h_s},
        "W": work,
        "outlet": co2.ph(p_out, h_in + work),
    }
    pentane = _Fluid(cp, "n-Pentane")
    p_in, p_out = 1.0e5, 3.0e5
    s_in = pentane("Smolar", "P", p_in, "Q", 1.0)
    dry = pentane.ps(p_out, s_in)
    if dry["regime"] != "SATURATED":
        raise SystemExit(f"A55: n-Pentane's isentropic state is {dry['regime']}, not two-phase")
    units["A55_dry_fluid"] = {
        "fluid": "n-Pentane",
        "inlet": {"P": p_in, "beta": 1.0, "s": s_in},
        "P_out": p_out,
        "s_vapor_sat_out": pentane("Smolar", "P", p_out, "Q", 1.0),
        "isentropic": dry,
    }

    # S11.A56: the mixer, vapour at 400 K and liquid at 300 K, 101 325 Pa, 1 mol/s each.
    h_v = water("Hmolar", "T", 400.0, "P", p)
    h_l = water("Hmolar", "T", 300.0, "P", p)
    mixed = water.ph(p, 0.5 * (h_v + h_l))
    units["A56_mixer"] = {
        "fluid": "H2O",
        "P": p,
        "inlets": [
            {"n": 1.0, "T": 400.0, "h": h_v},
            {"n": 1.0, "T": 300.0, "h": h_l},
        ],
        "outlet": {"n": 2.0, **mixed},
    }

    # S11.A57: the drum, wet steam at 0.5 MPa.
    units["A57_drum"] = {"fluid": "H2O", "P": 5.0e5, "T_sat": water("T", "P", 5.0e5, "Q", 0.0)}

    # S11.A58: the A51 valve outlet read by a heater in quality mode 1, n = 1 mol/s.
    units["A58_carriage"] = {
        "fluid": "H2O",
        "n": 1.0,
        "P": 1.0e5,
        "Q": water("Hmolar", "P", 1.0e5, "Q", 1.0) - h1,
    }
    return units


def build() -> dict[str, Any]:
    cp = _coolprop()
    fluids = {component: _Fluid(cp, component) for component in FLUIDS}
    return {
        "schema_version": 1,
        "generator": "docs/derivations/scripts/s11_thermal_reference.py",
        "coolprop": {"version": PINNED_VERSION, "backend": "HEOS", "function": "PropsSI"},
        "fluids": {
            component: {"coolprop_name": fluid.name, "T_c": fluid.t_c, "P_c": fluid.p_c}
            for component, fluid in fluids.items()
        },
        "saturation": {
            component: [fluids[component].saturation(p) for p in pressures]
            for component, pressures in SATURATION_PRESSURES.items()
        },
        "grid": {
            component: [_grid_point(fluids[component], *point) for point in points]
            for component, points in GRID.items()
        },
        "units": _units(cp),
    }


def render(document: dict[str, Any]) -> str:
    text = _HEADER + yaml.safe_dump(document, sort_keys=False, default_flow_style=False, width=100)
    if yaml.safe_load(text) != document:
        raise SystemExit("the emitted YAML does not round-trip to the generated values")
    return text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--emit", action="store_true", help="write the YAML")
    mode.add_argument("--check", action="store_true", help="regenerate and compare byte for byte")
    args = parser.parse_args(argv)
    try:
        text = render(build())
    except UnavailableError as error:
        if args.check:
            print(f"SKIP: {error}; {OUT.relative_to(ROOT)} not regenerated")
            return 0
        print(f"cannot emit: {error}", file=sys.stderr)
        return 2
    if args.emit:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    committed = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if committed != text:
        print(f"FAIL: {OUT.relative_to(ROOT)} differs from the regenerated references")
        return 1
    print(f"OK: {OUT.relative_to(ROOT)} matches CoolProp {PINNED_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
