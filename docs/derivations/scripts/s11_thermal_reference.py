class UnavailableError(RuntimeError):
    """CoolProp 8.0.0 cannot be imported."""


def _coolprop() -> Any:
    try:
        module = importlib.import_module("CoolProp")
    except ImportError as error:
        raise UnavailableError(f"CoolProp is not importable ({error})") from error
    if module.__version__ != PINNED_VERSION:
        raise UnavailableError(f"CoolProp {module.__version__} is not the pinned {PINNED_VERSION}")
    cp = importlib.import_module("CoolProp.CoolProp")
    # R-843 (as R-723 for S10): stated, not left to CoolProp's default. The committed file was
    # written with superancillaries on; with them off the A55 CO2 PS flash refuses its PQ call.
    cp.set_config_bool(cp.ENABLE_SUPERANCILLARIES, True)
    return cp


def _sanity(what: str, value: float, expected: float, bound: float) -> None:
    if not abs(value - expected) <= bound:
        raise SystemExit(f"sanity: {what} = {value!r} is not within {bound} of {expected}")


class _Fluid:
    def __init__(self, cp: Any, component: str) -> None:
        self._cp = cp
        self.component = component
        self.name = FLUIDS[component]
        self.t_c = float(cp.PropsSI("Tcrit", self.name))
        self.p_c = float(cp.PropsSI("pcrit", self.name))

    def __call__(self, output: str, a: str, x: float, b: str, y: float) -> float:
        return float(self._cp.PropsSI(output, a, x, b, y, self.name))

    def saturation(self, pressure: float) -> dict[str, float]:
        return {
            "P": pressure,
            "T": self("T", "P", pressure, "Q", 0.0),
            "h_liquid": self("Hmolar", "P", pressure, "Q", 0.0),
            "h_vapor": self("Hmolar", "P", pressure, "Q", 1.0),
            "s_liquid": self("Smolar", "P", pressure, "Q", 0.0),
            "s_vapor": self("Smolar", "P", pressure, "Q", 1.0),
        }

    def classify(self, pressure: float, temperature: float, quality: float) -> dict[str, Any]:
        """CoolProp's flash answer as (regime, T, beta); beta only when saturated."""
        if 0.0 <= quality <= 1.0:
            return {"regime": "SATURATED", "T": temperature, "beta": quality}
        if pressure < self.p_c:
            t_sat = self("T", "P", pressure, "Q", 0.0)
            regime = "LIQUID" if temperature < t_sat else "VAPOR"
        else:
            regime = "LIQUID" if temperature < self.t_c else "VAPOR"
        return {"regime": regime, "T": temperature, "beta": None}

    def ph(self, pressure: float, enthalpy: float) -> dict[str, Any]:
        temperature = self("T", "P", pressure, "Hmolar", enthalpy)
        quality = self("Q", "P", pressure, "Hmolar", enthalpy)
        return self.classify(pressure, temperature, quality)

    def ps(self, pressure: float, entropy: float) -> dict[str, Any]:
        temperature = self("T", "P", pressure, "Smolar", entropy)
        quality = self("Q", "P", pressure, "Smolar", entropy)
        return self.classify(pressure, temperature, quality)


def _grid_point(
    fluid: _Fluid, label: str, pressure: float, at: tuple[str, float]
) -> dict[str, Any]:
    key, value = at
    h = fluid("Hmolar", "P", pressure, key, value)
    s = fluid("Smolar", "P", pressure, key, value)
    ph = fluid.ph(pressure, h)
    ps = fluid.ps(pressure, s)
    if key == "T":
        # R-845: the flash lands within the watch fraction of B_FLASH·T of the nominal T.
        for name, answer in (("ph", ph), ("ps", ps)):
            if answer["regime"] in ("LIQUID", "VAPOR"):
                _sanity(
                    f"{fluid.component}[{label}] {name} T",
                    answer["T"],
                    value,
                    WATCH_FRACTION * B_FLASH * value,
                )
    return {
        "label": label,
        "P": pressure,
        "nominal": {key: value},
        "h": h,
        "s": s,
        "ph": ph,
        "ps": ps,
    }


def _units(cp: Any) -> dict[str, Any]:
    water = _Fluid(cp, "H2O")
    units: dict[str, Any] = {}

    # S11.A51: saturated liquid at 1 MPa throttled to 0.1 MPa.
    h1 = water("Hmolar", "P", 1.0e6, "Q", 0.0)
    throttled = water.ph(1.0e5, h1)
    _sanity("A51 beta", throttled["beta"], 0.1528, 5e-4)
    units["A51_throttling"] = {
        "fluid": "H2O",
        "inlet": {"P": 1.0e6, "beta": 0.0, "T": water("T", "P", 1.0e6, "Q", 0.0), "h": h1},
        "outlet": {"P": 1.0e5, **throttled, "T_sat": water("T", "P", 1.0e5, "Q", 0.0)},
    }

    # S11.A52: the heater at 101 325 Pa, n = 1 mol/s.
    p = 101325.0
    sat = water.saturation(p)
    _sanity("A42 T_sat(101325 Pa)", sat["T"], 373.1243, 1e-3)
    dh_vap = sat["h_vapor"] - sat["h_liquid"]
    _sanity("A42 dh_vap(101325 Pa) J/mol", dh_vap, 40650.0, 20.0)
    h300 = water("Hmolar", "T", 300.0, "P", p)
    h500 = water("Hmolar", "T", 500.0, "P", p)
    h_half = water("Hmolar", "P", p, "Q", 0.5)
    units["A52_heater"] = {
        "fluid": "H2O",
        "n": 1.0,
        "P": p,
        "quality_0_to_1": {"Q": dh_vap},
        "t_mode": {"T_in": 300.0, "T_out": 500.0, "Q": h500 - h300},
        "duty_mode": {"T_in": 300.0, "Q": h_half - h300, **water.ph(p, h_half)},
    }

    # S11.A53: the turbine, steam at 3 MPa, 673.15 K -> 10 kPa, eta = 0.85, n = 1 mol/s.
    p_in, t_in, p_out, eta = 3.0e6, 673.15, 1.0e4, 0.85
    h_in = water("Hmolar", "T", t_in, "P", p_in)
    s_in = water("Smolar", "T", t_in, "P", p_in)
    isentropic = water.ps(p_out, s_in)
    h_s = water("Hmolar", "P", p_out, "Smolar", s_in)
    work = eta * (h_s - h_in)
    outlet = water.ph(p_out, h_in + work)
    _sanity("A53 x_s", isentropic["beta"], 0.8366, 5e-4)
    _sanity("A53 x_2", outlet["beta"], 0.9017, 5e-4)
    _sanity("A53 W J/mol", work, -15910.0, 20.0)
    units["A53_turbine"] = {
        "fluid": "H2O",
        "n": 1.0,
        "inlet": {"P": p_in, "T": t_in, "h": h_in, "s": s_in},
        "P_out": p_out,
        "efficiency": eta,
        "isentropic": {**isentropic, "h": h_s},
        "W": work,
        "outlet": outlet,
    }

    # S11.A54: the pump, saturated liquid at 10 kPa -> 3 MPa, eta = 0.75, n = 1 mol/s.
    p_in, p_out, eta = 1.0e4, 3.0e6, 0.75
    h_in = water("Hmolar", "P", p_in, "Q", 0.0)
    s_in = water("Smolar", "P", p_in, "Q", 0.0)
    h_s = water("Hmolar", "P", p_out, "Smolar", s_in)
    work = (h_s - h_in) / eta
    outlet = water.ph(p_out, h_in + work)
    _sanity("A54 W J/mol", work, 72.5, 0.3)
    units["A54_pump"] = {
        "fluid": "H2O",
        "n": 1.0,
        "inlet": {"P": p_in, "beta": 0.0, "T": water("T", "P", p_in, "Q", 0.0), "h": h_in},
        "P_out": p_out,
        "efficiency": eta,
        "isentropic": {**water.ps(p_out, s_in), "h": h_s},
        "W": work,
        "outlet": outlet,
    }

    # S11.A55: the compressor, CO2 at 300 K, 1e5 -> 5e5 Pa, eta = 0.8; and a dry fluid's
    # saturated vapour whose isentropic state at the outlet pressure is two-phase.
    co2 = _Fluid(cp, "CO2")
    p_in, t_in, p_out, eta = 1.0e5, 300.0, 5.0e5, 0.8
    h_in = co2("Hmolar", "T", t_in, "P", p_in)
    s_in = co2("Smolar", "T", t_in, "P", p_in)
    h_s = co2("Hmolar", "P", p_out, "Smolar", s_in)
    work = (h_s - h_in) / eta
    units["A55_compressor"] = {
        "fluid": "CO2",
        "n": 1.0,
        "inlet": {"P": p_in, "T": t_in, "h": h_in},
        "P_out": p_out,
        "efficiency": eta,
        "isentropic": {**co2.ps(p_out, s_in), "h": h_s},
        "W": work,
        "outlet": co2.ph(p_out, h_in + work),
    }
    pentane = _Fluid(cp, "n-Pentane")
    p_in, p_out = 1.0e5, 3.0e5
    s_in = pentane("Smolar", "P", p_in, "Q", 1.0)
    dry = pentane.ps(p_out, s_in)
    if dry["regime"] != "SATURATED":
        raise SystemExit(f"A55: n-Pentane's isentropic state is {dry['regime']}, not two-phase")
    units["A55_dry_fluid"] = {
        "fluid": "n-Pentane",
        "inlet": {"P": p_in, "beta": 1.0, "s": s_in},
        "P_out": p_out,
        "s_vapor_sat_out": pentane("Smolar", "P", p_out, "Q", 1.0),
        "isentropic": dry,
    }

    # S11.A56: the mixer, vapour at 400 K and liquid at 300 K, 101 325 Pa, 1 mol/s each.
    h_v = water("Hmolar", "T", 400.0, "P", p)
    h_l = water("Hmolar", "T", 300.0, "P", p)
    mixed = water.ph(p, 0.5 * (h_v + h_l))
    units["A56_mixer"] = {
        "fluid": "H2O",
        "P": p,
        "inlets": [
            {"n": 1.0, "T": 400.0, "h": h_v},
            {"n": 1.0, "T": 300.0, "h": h_l},
        ],
        "outlet": {"n": 2.0, **mixed},
    }

    # S11.A57: the drum, wet steam at 0.5 MPa.
    units["A57_drum"] = {"fluid": "H2O", "P": 5.0e5, "T_sat": water("T", "P", 5.0e5, "Q", 0.0)}

    # S11.A58: the A51 valve outlet read by a heater in quality mode 1, n = 1 mol/s.
    units["A58_carriage"] = {
        "fluid": "H2O",
        "n": 1.0,
        "P": 1.0e5,
        "Q": water("Hmolar", "P", 1.0e5, "Q", 1.0) - h1,
    }
    return units


def _flowsheets(cp: Any) -> dict[str, Any]:
    """S11.A59–A61 (WO-C6): the reference cycles and the recycle case's sequential-modular
    solution, each state from CoolProp's PT, PH or PS answer; n = 1 mol/s feeds."""
    water = _Fluid(cp, "H2O")
    flowsheets: dict[str, Any] = {}

    # S11.A59 TH-C1: liquid at 10 kPa, 318.15 K -> pump (3 MPa, 0.75) -> boiler (673.15 K) ->
    # turbine (10 kPa, 0.85) -> condenser (quality 0).
    p_lo, p_hi, t_feed, t_boil, eta_p, eta_t = 1.0e4, 3.0e6, 318.15, 673.15, 0.75, 0.85
    h1 = water("Hmolar", "T", t_feed, "P", p_lo)
    s1 = water("Smolar", "T", t_feed, "P", p_lo)
    w_p = (water("Hmolar", "P", p_hi, "Smolar", s1) - h1) / eta_p
    h2 = h1 + w_p
    h3 = water("Hmolar", "T", t_boil, "P", p_hi)
    s3 = water("Smolar", "T", t_boil, "P", p_hi)
    w_t = eta_t * (water("Hmolar", "P", p_lo, "Smolar", s3) - h3)
    h4 = h3 + w_t
    h5 = water("Hmolar", "P", p_lo, "Q", 0.0)
    q_b, q_c = h3 - h2, h5 - h4
    _sanity("TH-C1 W_t J/mol", w_t, -15905.0, 20.0)
    flowsheets["TH-C1"] = {
        "fluid": "H2O",
        "n": 1.0,
        "W_pump": w_p,
        "Q_boiler": q_b,
        "W_turbine": w_t,
        "Q_condenser": q_c,
        "efficiency": (-w_t - w_p) / q_b,
        "pump_outlet": water.ph(p_hi, h2),
        "turbine_outlet": water.ph(p_lo, h4),
        "condenser_outlet": water.ph(p_lo, h5),
    }

    # S11.A60 TH-C2: R134a vapour at 0.2 MPa, 270 K -> compressor (1 MPa, 0.75) -> condenser
    # (quality 0) -> valve (0.2 MPa) -> evaporator (quality 1).
    r134a = _Fluid(cp, "R134a")
    p_lo, p_hi, t_feed, eta = 2.0e5, 1.0e6, 270.0, 0.75
    h1 = r134a("Hmolar", "T", t_feed, "P", p_lo)
    s1 = r134a("Smolar", "T", t_feed, "P", p_lo)
    w_c = (r134a("Hmolar", "P", p_hi, "Smolar", s1) - h1) / eta
    h2 = h1 + w_c
    h3 = r134a("Hmolar", "P", p_hi, "Q", 0.0)
    h5 = r134a("Hmolar", "P", p_lo, "Q", 1.0)
    q_e = h5 - h3
    flowsheets["TH-C2"] = {
        "fluid": "R134a",
        "n": 1.0,
        "W_compressor": w_c,
        "Q_condenser": h3 - h2,
        "Q_evaporator": q_e,
        "COP": q_e / w_c,
        "compressor_outlet": r134a.ph(p_hi, h2),
        "valve_outlet": r134a.ph(p_lo, h3),
    }

    # S11.A61 TH-R1: feed liquid (1 mol/s, 300 K, 0.5 MPa) -> mixer -> heater (duty, 0.5 MPa) ->
    # valve (0.2 MPa) -> drum (Q = 0, dP = 0); drum liquid -> pump (0.5 MPa, 0.75) -> splitter
    # (0.5 to the recycle) -> mixer. Sequential-modular, the recycle torn, direct substitution
    # to 1e-12 relative in the recycle flow and enthalpy.
    p_hi, p_lo, t_feed, duty, eta, split = 5.0e5, 2.0e5, 300.0, 2.5e4, 0.75, 0.5
    h_feed = water("Hmolar", "T", t_feed, "P", p_hi)
    h_l = water("Hmolar", "P", p_lo, "Q", 0.0)
    s_l = water("Smolar", "P", p_lo, "Q", 0.0)
    w_pump = (water("Hmolar", "P", p_hi, "Smolar", s_l) - h_l) / eta
    h_pumped = h_l + w_pump
    n_r, sweeps = 0.0, 0
    while True:
        sweeps += 1
        n_m = 1.0 + n_r
        h_m = (h_feed + n_r * h_pumped) / n_m
        h_h = h_m + duty / n_m
        beta = water("Q", "P", p_lo, "Hmolar", h_h)
        n_next = split * (n_m - beta * n_m)
        if abs(n_next - n_r) <= 1e-12 * n_next or sweeps > 200:
            n_r = n_next
            break
        n_r = n_next
    if sweeps > 200:
        raise SystemExit("TH-R1: the tear did not converge in 200 sweeps")
    n_m = 1.0 + n_r
    h_m = (h_feed + n_r * h_pumped) / n_m
    h_h = h_m + duty / n_m
    drum = water.ph(p_lo, h_h)
    if not 0.1 < drum["beta"] < 0.9:
        raise SystemExit(f"TH-R1: the drum's beta {drum['beta']} is outside (0.1, 0.9)")
    vapour, liquid = drum["beta"] * n_m, n_m - drum["beta"] * n_m
    flowsheets["TH-R1"] = {
        "fluid": "H2O",
        "inputs": {
            "feed": {"n": 1.0, "T": t_feed, "P": p_hi},
            "heater_duty": duty,
            "valve_P": p_lo,
            "pump": {"P": p_hi, "efficiency": eta},
            "split_fraction": split,
        },
        "sweeps": sweeps,
        "mixer_outlet": {"n": n_m, **water.ph(p_hi, h_m)},
        "heater_outlet": {"n": n_m, **water.ph(p_hi, h_h)},
        "drum": {"n": n_m, **drum, "V": vapour, "L": liquid},
        "pump_outlet": {"n": liquid, **water.ph(p_hi, h_pumped)},
        "W_pump": liquid * w_pump,
        "recycle": {"n": n_r},
        "purge": {"n": liquid - n_r},
    }
    return flowsheets


def build() -> dict[str, Any]:
    cp = _coolprop()
    fluids = {component: _Fluid(cp, component) for component in FLUIDS}
    return {
        "schema_version": 1,
        "generator": "docs/derivations/scripts/s11_thermal_reference.py",
        "coolprop": {"version": PINNED_VERSION, "backend": "HEOS", "function": "PropsSI"},
        "fluids": {
            component: {"coolprop_name": fluid.name, "T_c": fluid.t_c, "P_c": fluid.p_c}
            for component, fluid in fluids.items()
        },
        "saturation": {
            component: [fluids[component].saturation(p) for p in pressures]
            for component, pressures in SATURATION_PRESSURES.items()
        },
        "grid": {
            component: [_grid_point(fluids[component], *point) for point in points]
            for component, points in GRID.items()
        },
        "units": _units(cp),
        "flowsheets": _flowsheets(cp),
    }


def render(document: dict[str, Any]) -> str:
    text = _HEADER + yaml.safe_dump(document, sort_keys=False, default_flow_style=False, width=100)
    if yaml.safe_load(text) != document:
        raise SystemExit("the emitted YAML does not round-trip to the generated values")
    return text


def floor_class(key: str, where: str, parent: dict[str, Any]) -> str:
    """R-843's class of a float leaf, by its key: `energy` (s_f = R·T_c, times the case's n for a
    rate), `entropy` (s_f = R), `unit` (s_f = 1) or `relative` (s_f = 0); R-845's `flash` is a `T`
    whose enclosing mapping `parent` has `regime` LIQUID or VAPOR (bound B_FLASH·|x|, no floor).

    A grid point's `nominal.Q` is the nominal quality, a generator input, so it takes beta's
    class `unit`, not the heat-duty class its initial would give; `split_fraction` is a
    dimensionless input of class `relative`, not an entropy. A key outside the map is an error.
    """
    if key == "T" and parent.get("regime") in ("LIQUID", "VAPOR"):
        return "flash"
    if key == "Q" and where.endswith(".nominal.Q"):
        return "unit"
    if key in _RELATIVE_KEYS or key[:1] in ("T", "P"):
        return "relative"
    if key in ("beta", "efficiency", "COP"):
        return "unit"
    if key[:1] in ("h", "Q", "W"):
        return "energy"
    if key[:1] == "s":
        return "entropy"
    raise ValueError(f"{where}: no R-843 floor class for a float under {key!r}")


def _is_rate(key: str) -> bool:
    """A heat duty or work rate (W) of a unit or flowsheet case, as opposed to a molar h (J/mol)."""
    return key[:1] in ("Q", "W") or key == "heater_duty"


def classed_problems(
    committed: Any, computed: Any
) -> tuple[list[str], dict[str, tuple[float, str]]]:
    """R-843's comparison: (problems, the worst |Δ|/bound per class with its leaf path).

    Exact: keys and their order, list lengths, strings, integers, booleans and nulls (a `null`
    that becomes a number, or the reverse, is a problem). Every other float: |Δ| <= B_REL·max(|x|,
    s_f) with x the committed value and s_f the floor of `floor_class`: R·T_c of the case's fluid
    for `energy` (times the case's n for a rate), R for `entropy`, 1 for `unit`, 0 for
    `relative`; the class `flash` (R-845) is bounded B_FLASH·|x| instead. T_c is the committed
    document's; a case is a fluid's `saturation`/`grid` list, or a `units`/`flowsheets` entry (its
    `fluid`, and its `n` or, for TH-R1, its feed's).
    """
    problems: list[str] = []
    worst: dict[str, tuple[float, str]] = {c: (0.0, "-") for c in CLASSES}
    t_c = {c: f["T_c"] for c, f in committed.get("fluids", {}).items()}

    def case_of(path: tuple[str, ...]) -> tuple[str | None, float | None]:
        if len(path) >= 2 and path[0] in ("saturation", "grid"):
            return path[1], None
        if len(path) >= 2 and path[0] in ("units", "flowsheets"):
            case = committed[path[0]][path[1]]
            n = case.get("n")
            if n is None:
                n = case.get("inputs", {}).get("feed", {}).get("n")
            return case.get("fluid"), n
        return None, None

    def floor(
        key: str, where: str, path: tuple[str, ...], parent: dict[str, Any]
    ) -> tuple[str, float]:
        kind = floor_class(key, where, parent)
        if kind == "unit":
            return kind, 1.0
        if kind in ("relative", "flash"):
            return kind, 0.0
        fluid, n = case_of(path)
        if kind == "entropy":
            return kind, R_GAS
        if fluid not in t_c:
            raise ValueError(f"{where}: an energy leaf outside a case with a known fluid")
        scale = R_GAS * t_c[fluid]
        if _is_rate(key):
            if n is None:
                raise ValueError(f"{where}: a rate outside a case with a molar flow n")
            scale *= n
        return kind, scale

    def walk(
        a: Any, b: Any, where: str, path: tuple[str, ...], key: str, parent: dict[str, Any]
    ) -> None:
        if isinstance(a, dict) and isinstance(b, dict):
            if list(a) != list(b):
                problems.append(f"{where}: keys {list(a)} != {list(b)}")
                return
            for k in a:
                walk(a[k], b[k], f"{where}.{k}", (*path, str(k)), str(k), a)
        elif isinstance(a, list) and isinstance(b, list):
            if len(a) != len(b):
                problems.append(f"{where}: length {len(a)} != {len(b)}")
                return
            for i, (x, y) in enumerate(zip(a, b, strict=True)):
                walk(x, y, f"{where}[{i}]", path, key, parent)
        elif type(a) is float and type(b) is float:
            kind, s_f = floor(key, where, path, parent)
            bound = (B_FLASH * abs(a)) if kind == "flash" else B_REL * max(abs(a), s_f)
            delta = abs(a - b)
            ratio = delta / bound if bound > 0.0 else (0.0 if delta == 0.0 else float("inf"))
            if ratio > worst[kind][0] or worst[kind][1] == "-":
                worst[kind] = (ratio, where)
            if not delta <= bound:
                problems.append(f"{where}: |delta| = {delta:.3e} > {bound:.3e} ({kind})")
        elif type(a) is not type(b) or a != b:
            problems.append(f"{where}: {a!r} != {b!r}")

    walk(committed, computed, "$", (), "", {})
    return problems, worst


def _report(worst: dict[str, tuple[float, str]]) -> None:
    for kind in CLASSES:
        ratio, where = worst[kind]
        watch = "  WATCH (R-843: escalate)" if ratio > WATCH_FRACTION else ""
        print(f"  class {kind}: worst |delta|/bound {ratio:.3e} at {where}{watch}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--emit", action="store_true", help="write the YAML")
    mode.add_argument(
        "--check",
        action="store_true",
        help="regenerate and compare (byte for byte on x86-64, classed elsewhere; R-843)",
    )
    args = parser.parse_args(argv)
    try:
        text = render(build())
    except UnavailableError as error:
        if args.check:
            print(f"SKIP: {error}; {OUT.relative_to(ROOT)} not regenerated")
            return 0
        print(f"cannot emit: {error}", file=sys.stderr)
        return 2
    if args.emit:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    if not OUT.exists():
        print(f"FAIL: {OUT.relative_to(ROOT)} is absent")
        return 1
    committed = OUT.read_text(encoding="utf-8")
    machine = platform.machine()
    problems, worst = classed_problems(yaml.safe_load(committed), yaml.safe_load(text))
    if machine == "x86_64":
        ok = committed == text
        print(f"check (R-843): bitwise on {machine}; the classed comparison, for the record:")
    else:
        ok = not problems
        print(f"check (R-843): classed on {machine}, |delta| <= {B_REL:g}·max(|x|, s_f):")
    _report(worst)
    for problem in problems[:10]:
        print(f"  {problem}")
    # The verdict is the last line (scripts/s11_evidence_manifest.py reads it).
    if not ok:
        print(f"FAIL: {OUT.relative_to(ROOT)} differs from the regenerated references")
        return 1
    print(f"OK: {OUT.relative_to(ROOT)} matches CoolProp {PINNED_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
