"""Generate `benchmarks/s11/thermal_reference.yaml`: CoolProp 8.0.0 references for track C.

S11 units design §6.1 (S11.A42-A61; ADR 0051; the flowsheet cycles and TH-R1's
sequential-modular solution are WO-C6's). Every value here comes from CoolProp's own
`PropsSI` on the HEOS backend (its saturation solver, its PH and PS flashes), never from
`openflowsheet`: the script imports nothing from the package, so it is an independent expectation
for the pure-fluid kernel and the `thermal.*` units, which call the in-tree Helmholtz providers
(`iapws95-v1` for water, `coolprop-heos-v1` for the others) and solve their own closures.

Molar quantities throughout (`Hmolar` J/mol, `Smolar` J/(mol K)), in each fluid's default
CoolProp reference state, which is what `COOLPROP-DEF-ref-v1` and `IAPWS95-ref-v1` are.

**Steam-table sanity.** Each water row that the design brackets is checked against the
IAPWS-95 steam-table value of §6.1 before anything is written; a reference outside its bracket
stops the script. The brackets bound the reference, not the code under test.

**Phase labels.** CoolProp's quality `Q` is the regime: `0 <= Q <= 1` is `SATURATED` (beta = Q);
otherwise `LIQUID` below the saturation temperature at that pressure (or below T_c above P_c) and
`VAPOR` above it.

Usage (CoolProp is not a dependency of the package; use a scratch install of the `coolprop`
extra):
    PYTHONPATH=<coolprop-site> python docs/derivations/scripts/s11_thermal_reference.py --emit
    PYTHONPATH=<coolprop-site> python docs/derivations/scripts/s11_thermal_reference.py --check

Without CoolProp 8.0.0, `--check` prints `SKIP: ...` with the reason and exits 0 (units design
§7 Q25); `--emit` exits 2.

**The check (R-843).** On x86-64, the architecture that wrote the file, `--check` compares byte for
byte. Elsewhere it compares the parsed documents leaf by leaf (`classed_problems`): the structure,
key order, strings, integers and nulls exactly, and every other float within
1e-10·max(|x|, s_f), with the floor s_f set by the leaf's key (`floor_class`). On every
architecture it prints the worst |Δ|/bound per class.

**The flash class (R-845).** The `T` of a single-phase (LIQUID or VAPOR) PH/PS flash answer is a
root CoolProp converges only to about 1e-9·T, so it takes its own class `flash`,
|Δ| <= B_FLASH·|x| with no floor. The generator asserts that floor at every grid point with a
nominal T (`_grid_point`), on every architecture. Every other class and the x86-64 byte check
are unchanged.
"""

