"""Reference values and executable self-claims for the T08 release specification.

``docs/derivations/T08-release-spec.md`` makes claims about numbers and about the repository: which
evidence manifests it cites and what they contain, which registered digests the release candidate
must reproduce, the Clopper-Pearson bounds it quotes, the closed form of the verifier's
alias-pressure-shift limit, the scored real-chemistry dossier and its ranking, and the catalogue of
numbered assertions. Every one of those claims is re-derived here, and the script refuses to emit
when one fails (T08 spec §10).

Emitted, and labelled as such in the YAML:

* ``registered`` -- values read from committed repository files (manifests, the benchmark
  registry, the lock file), each compared against the literal the specification quotes. These are
  facts about the repository, not expectations derived from definitions.
* ``closed_form`` -- expectations derived from definitions: the one-sided 95 % Clopper-Pearson
  lower bounds (mpmath, 40 digits, written to 20) and the alias-shift position limit (exact
  rationals).
* ``dossier`` -- the V19 selection rubric, the candidate scores with their evidence labels, the
  totals, the ranking under the tie-break rule, and the sensitivity of the ranking to every
  provisional score. The scores are design-lane judgements; the arithmetic on them is checked.
* ``assertions`` -- the catalogue of numbered assertions, cross-checked against the
  specification's own table in both directions.

It imports nothing from ``process_runtime`` or ``benchmarks`` (it reads their committed files as
data), so none of its expectations comes from the code under judgement.

Run from the repository root inside the project environment::

    python docs/derivations/scripts/t08_reference.py --check
    python docs/derivations/scripts/t08_reference.py --emit benchmarks/t08/reference_values.yaml

``--check`` re-derives every claim and requires the committed YAML to equal the regenerated bytes.
``--emit`` is byte-reproducible.
"""

