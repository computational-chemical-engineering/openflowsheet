def total(scores: dict[str, tuple[int, bool]]) -> int:
    return sum(v for v, _ in scores.values())


def rank(cands: dict[str, dict[str, Any]]) -> list[str]:
    """Selectable candidates (no hard criterion `fails`) by total, then the tie-break keys."""
    selectable = [c for c, d in cands.items() if "fails" not in d["hard"].values()]

    def key(c: str) -> tuple[Any, ...]:
        s = cands[c]["scores"]
        return (-total(s), *(-s[k][0] for k in TIE_BREAK), c)

    return sorted(selectable, key=key)


def sensitivity(cands: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    """For every provisional score, the top two at its extremes 0 and 2."""
    rows = []
    for c, d in cands.items():
        for s, (value, provisional) in d["scores"].items():
            if not provisional:
                continue
            tops = {}
            for trial in (0, 2):
                alt = json.loads(json.dumps(cands))
                alt[c]["scores"][s] = [trial, True]
                alt = {
                    k: {**v, "scores": {kk: tuple(vv) for kk, vv in v["scores"].items()}}
                    for k, v in alt.items()
                }
                tops[trial] = rank(alt)[:2]
            rows.append(
                {
                    "candidate": c,
                    "score": s,
                    "as_registered": value,
                    "top_two_at_0": tops[0],
                    "top_two_at_2": tops[2],
                    "moves_top": tops[0][0] != RECOMMENDED or tops[2][0] != RECOMMENDED,
                }
            )
    return rows


