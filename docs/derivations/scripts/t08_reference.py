class Claims:
    def __init__(self) -> None:
        self.results: list[tuple[str, bool, str]] = []

    def check(self, name: str, ok: bool, detail: str = "") -> None:
        self.results.append((name, bool(ok), detail))

    @property
    def failed(self) -> list[tuple[str, bool, str]]:
        return [r for r in self.results if not r[1]]


def sha256_file(rel: str) -> str:
    return hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()


def manifest_facts(claims: Claims) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for pkg, (prefix, status, tallies) in CITED_MANIFESTS.items():
        found = sorted((ROOT / "evidence" / pkg).glob("*/manifest.json"))
        claims.check(f"A01.{pkg}.one_manifest", len(found) == 1, f"{len(found)} manifests")
        if len(found) != 1:
            continue
        m = json.loads(found[0].read_text(encoding="utf-8"))
        tally: dict[str, int] = {}
        for c in m["checks"]:
            r = c.get("result")
            tally[r] = tally.get(r, 0) + 1
        rel = found[0].relative_to(ROOT).as_posix()
        claims.check(f"A01.{pkg}.commit", m["commit"].startswith(prefix), m["commit"])
        claims.check(f"A01.{pkg}.status", m["status"] == status, m["status"])
        claims.check(f"A01.{pkg}.tallies", tally == tallies, str(tally))
        out[pkg] = {
            "path": rel,
            "status": m["status"],
            "checks": dict(sorted(tally.items())),
            "limitations": len(m.get("limitations", [])),
        }
    return out


