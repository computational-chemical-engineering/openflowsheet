def catalogue(claims: Claims) -> dict[str, Any]:
    text = SPEC.read_text(encoding="utf-8")
    in_spec = re.findall(r"^\| (T08\.A\d\d) \|", text, flags=re.M)
    claims.check(
        "A00.spec_ids_unique",
        len(in_spec) == len(set(in_spec)),
        str(sorted({i for i in in_spec if in_spec.count(i) > 1})),
    )
    claims.check(
        "A00.spec_equals_catalogue",
        set(in_spec) == set(ASSERTIONS),
        f"spec only {sorted(set(in_spec) - set(ASSERTIONS))}; "
        f"catalogue only {sorted(set(ASSERTIONS) - set(in_spec))}",
    )
    claims.check("A00.spec_order", in_spec == sorted(in_spec), "")
    gate_rows = re.findall(r"^\| \*\*(V\d\d)\*\* \|", text, flags=re.M)
    claims.check("A00.one_summary_row_per_gate", gate_rows == list(GATES), str(gate_rows))
    return {k: {"subject": s, "judged_by": j} for k, (s, j) in ASSERTIONS.items()}


def build(claims: Claims) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "generator": "docs/derivations/scripts/t08_reference.py",
        "specification": "docs/derivations/T08-release-spec.md",
        "precision": "mpmath 40 significant digits, written to 20; integers and rationals exact",
        "independence": "imports nothing from process_runtime or benchmarks; reads committed files",
        "registered": {
            "manifests": manifest_facts(claims),
            "harvest_today": harvest_counts(claims),
            **registered_facts(claims),
        },
        "closed_form": closed_forms(claims),
        "dossier": dossier(claims),
        "amendment_r3": amendment_r3(claims),
        "assertions": catalogue(claims),
    }


def dump(data: dict[str, Any]) -> str:
    header = (
        "# Generated by docs/derivations/scripts/t08_reference.py -- do not edit.\n"
        "# Re-derive with --check; regenerate with --emit.\n"
    )
    return header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="re-derive every claim and compare with the committed YAML",
    )
    parser.add_argument("--emit", metavar="PATH", help="write the reference YAML")
    args = parser.parse_args(argv)
    if not args.check and not args.emit:
        parser.error("choose --check and/or --emit PATH")
    claims = Claims()
    text = dump(build(claims))
    for name, ok, detail in claims.results:
        if not ok:
            print(f"FAIL {name}: {detail}")
    print(f"{len(claims.results) - len(claims.failed)} of {len(claims.results)} claims pass")
    if claims.failed:
        return 1
    data = text.encode("utf-8")
    if args.check:
        committed = YAML_PATH.read_bytes() if YAML_PATH.exists() else b""
        same = committed == data
        print(
            f"committed YAML {'equals' if same else 'DIFFERS FROM'} the regenerated bytes "
            f"(sha256 {hashlib.sha256(data).hexdigest()})"
        )
        if not same:
            return 1
    if args.emit:
        path = Path(args.emit)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {path} ({len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
