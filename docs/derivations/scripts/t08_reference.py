def module_string_constants(rel: str) -> dict[str, str]:
    """A script's module-level string constants, read with `ast` (the script is not imported)."""
    tree = ast.parse((ROOT / rel).read_text(encoding="utf-8"), filename=rel)
    out: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets, value = [node.target], node.value
        elif isinstance(node, ast.Assign):
            targets, value = [t for t in node.targets if isinstance(t, ast.Name)], node.value
        else:
            continue
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            out.update({t.id: value.value for t in targets})
    return out


def register_entry(entry: str) -> str:
    """The text of one entry of the decision register, from its heading to the next heading."""
    text = (ROOT / REGISTER).read_text(encoding="utf-8")
    m = re.search(rf"^## {re.escape(entry)} .*?(?=^## |\Z)", text, flags=re.M | re.S)
    return m.group(0) if m else ""


