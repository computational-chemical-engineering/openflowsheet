def closed_forms(claims: Claims) -> dict[str, Any]:
    cp = []
    for x, n, recorded in CP_POINTS:
        v = cp_lower(x, n)
        # The bound is the root of I_p(x, n-x+1) = 0.05; check the residual at 30 digits.
        resid = betainc(x, n - x + 1, 0, v, regularized=True) - mpf("0.05")
        claims.check(f"cp.{x}_of_{n}.root", abs(resid) < mpf("1e-30"), nstr(resid, 5))
        if recorded is not None:
            digits = len(recorded.split(".")[1])
            claims.check(
                f"cp.{x}_of_{n}.equals_recorded",
                abs(v - mpf(recorded)) <= mpf(10) ** (-digits) / 2 + mpf("1e-16"),
                f"{nstr(v, 20)} vs {recorded}",
            )
        cp.append({"x": x, "n": n, "lower_95_one_sided": nstr(v, 20), "recorded": recorded})
    claims.check("cp.threshold_below_point", mpf(cp_lower(418, 440)) < mpf(418) / 440, "")

    alias = []
    for p in ALIAS_PROBES:
        jm = alias_jmax(p)
        # The closed form agrees with the rule itself at the threshold and one past it, and the
        # rule is monotone: once unsupported, unsupported for every larger j up to 400.
        claims.check(f"alias.{p}.at_jmax", alias_direction(p, jm) != "unsupported", str(jm))
        claims.check(f"alias.{p}.past_jmax", alias_direction(p, jm + 1) == "unsupported", str(jm))
        claims.check(
            f"alias.{p}.monotone",
            all(alias_direction(p, j) == "unsupported" for j in range(jm + 1, 401)),
            "",
        )
        alias.append(
            {
                "P_pa": p,
                "j_max": jm,
                "direction_at_j_max": alias_direction(p, jm),
                "first_unsupported_j": jm + 1,
            }
        )
    worst = min(alias_jmax(p) for p in range(P_LO, P_HI + 1, 50))
    best = max(alias_jmax(p) for p in range(P_LO, P_HI + 1, 50))
    claims.check("alias.worst_is_at_125kPa", worst == alias_jmax(125_000) == 74, str(worst))
    claims.check("alias.best_is_at_domain_edges", best == 149, str(best))
    # The registered NET-11 figure (T06 spec F3): S4.P = 1.8e5 Pa shifted to 204 925 Pa means
    # 997 (j + 1) = 24 925, i.e. j = 24, and the rule sends that column down.
    claims.check("alias.net11_position", ALIAS_BASE_PA * 25 == 24_925, "")
    claims.check("alias.net11_goes_down", alias_direction(180_000, 24) == "down", "")
    # Two sanity directions at 1.8e5 Pa quoted in spec §5.4.
    claims.check("alias.180k_j19_up", alias_direction(180_000, 19) == "up", "")
    claims.check("alias.180k_j20_down", alias_direction(180_000, 20) == "down", "")
    return {
        "clopper_pearson": cp,
        "alias_shift": {
            "base_pa": ALIAS_BASE_PA,
            "domain_pa": [P_LO, P_HI],
            "rule": "supported iff 997 (j + 1) <= max(2e5 - P, P - 5e4)",
            "probes": alias,
            "worst_j_max": worst,
            "best_j_max": best,
        },
    }


def dossier(claims: Claims) -> dict[str, Any]:
    for c, d in CANDIDATES.items():
        claims.check(f"dossier.{c}.hard_complete", set(d["hard"]) == set(HARD), "")
        claims.check(f"dossier.{c}.hard_values", set(d["hard"].values()) <= set(HARD_VALUES), "")
        claims.check(f"dossier.{c}.scores_complete", set(d["scores"]) == set(SCORED), "")
        claims.check(
            f"dossier.{c}.scores_range", all(v in (0, 1, 2) for v, _ in d["scores"].values()), ""
        )
    order = rank(CANDIDATES)
    claims.check("A65.recommended_is_top", order[0] == RECOMMENDED, str(order))
    claims.check("A65.runner_up_is_second", order[1] == RUNNER_UP, str(order))
    sens = sensitivity(CANDIDATES)
    # The specification claims (spec §7.4) that no single provisional score moves the top choice;
    # what moves it is a hard criterion (H5 or H1 failing for C1) or Frank naming a group model
    # for another candidate (S1 of that candidate to 2), which the sensitivity rows show.
    moved = [r for r in sens if r["moves_top"]]
    claims.check(
        "A65.only_s1_of_others_moves_top",
        all(r["score"] == "S1" and r["candidate"] != RECOMMENDED for r in moved),
        str([(r["candidate"], r["score"]) for r in moved]),
    )
    claims.check(
        "A65.c2_s1_moves_top", any(r["candidate"] == "C2" and r["score"] == "S1" for r in moved), ""
    )
    without_c1 = {k: v for k, v in CANDIDATES.items() if k != RECOMMENDED}
    claims.check(
        "A65.fallback_if_c1_unselectable", rank(without_c1)[0] == RUNNER_UP, str(rank(without_c1))
    )
    return {
        "hard_criteria": HARD,
        "hard_values": list(HARD_VALUES),
        "scored_criteria": {k: {"criterion": a, "anchors": b} for k, (a, b) in SCORED.items()},
        "tie_break": list(TIE_BREAK),
        "candidates": {
            c: {
                "label": d["label"],
                "hard": d["hard"],
                "scores": {k: {"score": v, "provisional": p} for k, (v, p) in d["scores"].items()},
                "total": total(d["scores"]),
            }
            for c, d in CANDIDATES.items()
        },
        "ranking": order,
        "recommended": RECOMMENDED,
        "runner_up": RUNNER_UP,
        "sensitivity": sens,
    }


