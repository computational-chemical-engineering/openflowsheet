#: ADR 0014 D5 / T06 spec §8.2: pressure column j (0-based position in `variable_ids`) is shifted
#: by s_j = 997 (j + 1) Pa, up if the provider domain admits P + s_j, else down if it admits
#: P - s_j, else the alias certificate is unsupported. SYN-001's domain is [5e4, 2e5] Pa inclusive.
ALIAS_BASE_PA = 997
P_LO, P_HI = 50_000, 200_000
ALIAS_PROBES = [50_000, 100_000, 125_000, 180_000, 200_000]


def cp_lower(x: int, n: int, alpha: str = "0.05") -> Any:
    """The p with P(X >= x | n, p) = alpha, i.e. I_p(x, n - x + 1) = alpha, by bisection."""
    a = mpf(alpha)
    lo, hi = mpf(0), mpf(x) / n
    for _ in range(200):
        mid = (lo + hi) / 2
        if betainc(x, n - x + 1, 0, mid, regularized=True) > a:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2


def alias_direction(p: int, j: int) -> str:
    """The rule of ADR 0014 D5 at pressure `p` for column position `j`, in exact integers."""
    s = ALIAS_BASE_PA * (j + 1)
    if P_LO <= p + s <= P_HI:
        return "up"
    if P_LO <= p - s <= P_HI:
        return "down"
    return "unsupported"


def alias_jmax(p: int) -> int:
    """Largest j that is not unsupported at `p`: 997 (j + 1) <= max(P_HI - p, p - P_LO)."""
    room = Fraction(max(P_HI - p, p - P_LO))
    return int(room // ALIAS_BASE_PA) - 1


