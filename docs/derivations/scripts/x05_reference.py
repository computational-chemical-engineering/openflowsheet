"""Reference values and executable self-claims for ADR 0069 (package X05, replay from the wheel).

``docs/adr/0069-X05-replay-from-the-wheel.md`` decides when a build records `lock_sha256` (D2, D3)
and what replay then reports (D5), and registers numbered assertions X05.A01-A25 against states it
names. This script is a second, independent statement of the ADR's rule. It emits:

* ``lock`` -- the registered lock's digest, its line count and the runtime closure's pins, read from
  the committed `requirements.lock` and `pyproject.toml`.
* ``templates`` -- the finding and reason templates of D5, verbatim.
* ``cases`` -- the verifier's registered states (V01-V36): a lock edit, an installed-version map
  and the expected `(sha256, findings)`, each rendered by this script's own implementation of D2.
* ``end_to_end`` -- the shadow and stray constructs and the 4 x 2 replay matrix of X05.A13-A17.
* ``f0`` -- what X05.A22 is judged against: the 52 committed F0 bundles and M7's registered values.
* ``assertions`` -- the catalogue, cross-checked with the ADR's own table in both directions.

It refuses to emit when a claim fails: the lock's digest is the one the ADR quotes; the closure the
ADR registers is the closure measured from installed metadata (``packaging`` markers, no extras)
in an environment at the lock; every closure member is pinned once in the lock; every declared
dependency in ``pyproject.toml`` is an exact pin, in the closure, at the lock's version (true
before the build adds D3's four pins and after, so the JSON does not move when it does); the
per-member findings are pairwise distinct; an empty lock fails once per member (no vacuous pass);
every malformed case names the line it edited; the stray lock differs from the packaged one and
would itself verify (so only reading it, not verifying it, is what A13/A14 catch); the shadow
version differs from the pin; the ADR's template table, case table and assertion table equal this
script's, in both directions; the counts the ADR quotes are the measured ones; and every F0 bundle
records the lock. It imports nothing from ``openflowsheet``: none of its expectations comes from
the code under judgement.

Run from the repository root inside the project environment (one at the lock)::

    python docs/derivations/scripts/x05_reference.py --check
    python docs/derivations/scripts/x05_reference.py --emit benchmarks/x05/reference_values.json

``--check`` re-derives every claim and requires the committed JSON to equal the regenerated bytes.
``--emit`` is byte-reproducible.
"""

