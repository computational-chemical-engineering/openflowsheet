LINE = re.compile(r"([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)==([A-Za-z0-9][A-Za-z0-9.+!_-]*)")


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse(data: bytes, where: str) -> tuple[dict[str, str] | None, str | None]:
    """The lock's pins by normalised name, or the one finding that stops verification."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None, TEMPLATES["F1"].format(where=where)
    pins: dict[str, str] = {}
    for number, raw in enumerate(text.split("\n"), 1):
        body = raw.split("#", 1)[0].strip()
        if not body:
            continue
        match = LINE.fullmatch(body)
        name = normalise(match.group(1)) if match else None
        if match is None or name in pins:
            return None, TEMPLATES["F2"].format(where=where, line=number, text=repr(raw))
        pins[str(name)] = match.group(2)
    return pins, None


def verify(
    data: bytes | None, installed: Callable[[str], str | None], where: str
) -> tuple[str, tuple[str, ...]]:
    if data is None:
        return "", (TEMPLATES["F1"].format(where=where),)
    pins, failure = parse(data, where)
    if pins is None:
        return "", (str(failure),)
    findings: list[str] = []
    for name in CLOSURE:
        if name not in pins:
            findings.append(TEMPLATES["F5"].format(name=name))
            continue
        try:
            found = installed(name)
        except Exception as error:
            findings.append(TEMPLATES["F6"].format(name=name, error=type(error).__name__))
            continue
        if found is None:
            findings.append(TEMPLATES["F3"].format(name=name, locked=pins[name]))
        elif found != pins[name]:
            findings.append(TEMPLATES["F4"].format(name=name, installed=found, locked=pins[name]))
    return ("" if findings else hashlib.sha256(data).hexdigest()), tuple(findings)


def lookup(table: Mapping[str, Any]) -> Callable[[str], str | None]:
    def installed(name: str) -> str | None:
        value = table.get(name)
        if isinstance(value, dict):
            errors = {"ValueError": ValueError, "OSError": OSError, "TypeError": TypeError}
            raise errors[value["raises"]](name)
        return value

    return installed


