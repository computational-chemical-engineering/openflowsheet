def apply(base: bytes, edits: list[dict[str, Any]]) -> bytes | None:
    """The lock a case hands the verifier: `base` with `edits` applied in order (ADR §Spec 2)."""
    data: bytes | None = base
    for edit in edits:
        op = edit["op"]
        if op == "missing":
            data = None
        elif op == "bytes":
            data = bytes.fromhex(edit["hex"])
        else:
            assert data is not None
            lines = data.decode("utf-8").split("\n")
            if op in ("remove_line", "replace_line"):
                where = [i for i, line in enumerate(lines) if line == edit["line"]]
                claim(len(where) == 1, f"edit {edit} must match exactly one line")
                lines[where[0] : where[0] + 1] = [] if op == "remove_line" else [edit["with"]]
                data = "\n".join(lines).encode("utf-8")
            elif op == "append":
                data = data + edit["text"].encode("utf-8")
            else:
                raise RefusalError(f"unknown edit {op!r}")
    return data


def lock_pins(data: bytes) -> dict[str, str]:
    pins, failure = parse(data, "requirements.lock")
    claim(pins is not None, f"the committed lock does not parse: {failure}")
    assert pins is not None
    return pins


