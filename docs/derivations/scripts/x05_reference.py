def declared_dependencies(pins: dict[str, str]) -> None:
    """Every `[project].dependencies` entry is an exact pin of a closure member at the lock's
    version, and the five pre-X05 pins are among them. Holds before and after D3's pins."""
    project = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]
    found: dict[str, str] = {}
    for requirement in project["dependencies"]:
        match = re.fullmatch(r"([A-Za-z0-9._-]+)==([^\s;]+)", requirement)
        claim(match is not None, f"pyproject dependency {requirement!r} is not an exact pin")
        assert match is not None
        found[normalise(match.group(1))] = match.group(2)
    claim(set(PRE_X05_DIRECT) <= set(found), f"the declared dependencies are {sorted(found)}")
    claim(set(found) <= set(CLOSURE), f"declared {sorted(set(found) - set(CLOSURE))} not in it")
    for name, version in found.items():
        claim(pins.get(name) == version, f"{name}: pyproject pins {version}, the lock {pins[name]}")


def measured_closure(pins: dict[str, str]) -> list[str]:
    """The transitive closure of `[project].dependencies`, no extras, from installed metadata."""
    from importlib import metadata

    try:
        from packaging.requirements import Requirement
    except ImportError as missing:
        raise RefusalError(
            "`packaging` is needed to measure the closure (it is in the lock)"
        ) from missing
    project = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]
    seen: set[str] = set()
    todo = [Requirement(text) for text in project["dependencies"]]
    while todo:
        requirement = todo.pop()
        if requirement.marker is not None and not requirement.marker.evaluate({"extra": ""}):
            continue
        name = normalise(requirement.name)
        if name in seen:
            continue
        seen.add(name)
        try:
            installed = metadata.version(name)
        except metadata.PackageNotFoundError as missing:
            raise RefusalError(
                f"{name} is not installed: measure in an environment at the lock"
            ) from (missing)
        claim(installed == pins.get(name), f"{name} {installed} is not the lock's: measure at it")
        todo.extend(Requirement(text) for text in metadata.requires(name) or [])
    return sorted(seen)


def f0_facts() -> dict[str, Any]:
    corpus = json.loads(F0_CORPUS.read_text(encoding="utf-8"))
    m7 = corpus["measures"]["M7"]
    values = sorted({json.dumps(value, sort_keys=True) for value in m7.values()})
    manifests = sorted(F0_BUNDLES.glob("*/*/run-manifest.json"))
    locks = {json.loads(p.read_text("utf-8"))["environment"]["lock_sha256"] for p in manifests}
    claim(len(m7) == len(manifests) == 52, f"F0: {len(m7)} M7 entries, {len(manifests)} bundles")
    claim(locks == {LOCK_SHA256}, f"F0: every bundle records the lock ({sorted(locks)})")
    return {
        "bundles": len(manifests),
        "directory": F0_BUNDLES.relative_to(ROOT).as_posix(),
        "recorded_lock_sha256": LOCK_SHA256,
        "m7_registered_values": [json.loads(value) for value in values],
        "reference_platform": corpus["reference_platform"],
        "registered_in": F0_CORPUS.relative_to(ROOT).as_posix() + " measures.M7",
    }


def end_to_end(base: bytes, pins: dict[str, str]) -> dict[str, Any]:
    closure_only = {name: pins[name] for name in CLOSURE}
    stray = base + STRAY_SUFFIX.encode("utf-8")
    stray_sha, stray_findings = verify(stray, lookup(closure_only), "stray")
    claim(
        stray_sha not in ("", LOCK_SHA256) and not stray_findings,
        "the stray lock differs from the packaged one and would itself verify",
    )
    claim(SHADOW[1] != pins[SHADOW[0]], "the shadow version differs from the pin")
    off = verify(base, lookup({**closure_only, SHADOW[0]: SHADOW[1]}), WHERE)
    claim(off[0] == "" and len(off[1]) == 1, "the shadow construct fails on exactly one finding")
    off_findings = list(off[1])
    joined = TEMPLATES["JOIN"].join(off_findings)
    states = {
        "installed": {"lock_sha256": LOCK_SHA256, "lock_findings": []},
        "checkout": {"lock_sha256": LOCK_SHA256, "lock_findings": []},
        "installed-off": {"lock_sha256": "", "lock_findings": off_findings},
        "checkout-off": {"lock_sha256": "", "lock_findings": off_findings},
    }
    bundles = {
        "on": {"written_by": "installed", "lock_sha256": LOCK_SHA256},
        "off": {"written_by": "installed-off", "lock_sha256": ""},
    }
    replays: list[dict[str, Any]] = []
    for state, environment in states.items():
        for bundle, written in bundles.items():
            archive_known, here_known = (
                bool(written["lock_sha256"]),
                bool(environment["lock_sha256"]),
            )
            if archive_known and here_known:
                row = {"mode": "exact_replay", "verdict": "MATCH", "reasons": []}
            elif not archive_known and here_known:
                row = {
                    "mode": "inspected_archived_results",
                    "verdict": "NOT_RUN",
                    "reason0": TEMPLATES["R_ARCHIVE"],
                }
            elif archive_known:
                row = {
                    "mode": "inspected_archived_results",
                    "verdict": "NOT_RUN",
                    "reason0": TEMPLATES["R_THIS"].format(findings=joined),
                }
            else:
                row = {
                    "mode": "inspected_archived_results",
                    "verdict": "NOT_RUN",
                    "reason0": TEMPLATES["R_BOTH"].format(findings=joined),
                }
            replays.append({"state": state, "bundle": bundle, **row})
    reasons = {row.get("reason0") for row in replays if "reason0" in row}
    claim(len(reasons) == 3, "the unmatched cells carry three distinct reasons")
    claim(
        all(r.startswith("the dependency set is unknown on ") for r in reasons),
        "T08.A19's prefix is kept",
    )
    claim(sum(row["verdict"] == "MATCH" for row in replays) == 2, "two matched cells")
    return {
        "stray": {
            "content": "the packaged lock followed by the suffix",
            "suffix": STRAY_SUFFIX,
            "sha256": stray_sha,
        },
        "shadow": {
            "name": SHADOW[0],
            "version": SHADOW[1],
            "dist_info": f"{SHADOW[0]}-{SHADOW[1]}.dist-info/METADATA",
            "metadata": f"Metadata-Version: 2.1\nName: {SHADOW[0]}\nVersion: {SHADOW[1]}\n",
        },
        "missing_lock": {
            "state": "installed, `_data/requirements.lock` deleted from the installed copy",
            "lock_sha256": "",
            "lock_findings": [TEMPLATES["F1"].format(where=WHERE)],
        },
        "states": states,
        "bundles": bundles,
        "replays": replays,
    }


def quoted_digests(document: dict[str, Any]) -> list[str]:
    """The digests the ADR quotes by prefix: V30's and V31's own hashes and the stray's."""
    by_id = {row["id"]: row for row in document["cases"]}
    return [
        by_id["V30"]["expect"]["sha256"],
        by_id["V31"]["expect"]["sha256"],
        document["end_to_end"]["stray"]["sha256"],
    ]


def check_adr(document: dict[str, Any]) -> None:
    """The ADR's tables and quoted counts equal this script's, in both directions."""
    text = ADR.read_text(encoding="utf-8")
    claim(LOCK_SHA256 in text, "the ADR quotes the lock's digest")
    line = next((x for x in text.splitlines() if x.startswith("**Registered runtime closure")), "")
    quoted = tuple(re.findall(r"`([a-z0-9-]+)`", line))
    claim(quoted == CLOSURE, f"the ADR's closure line names {quoted}")
    rows = dict(re.findall(r"^\| ([A-Z0-9_]+) \| `([^`]*)` \|", text, flags=re.MULTILINE))
    claim(rows == TEMPLATES, f"ADR template table vs script: {sorted(set(rows) ^ set(TEMPLATES))}")
    table = set(re.findall(r"^\| (X05\.A\d\d) \|", text, flags=re.MULTILINE))
    claim(table == set(ASSERTIONS), f"ADR table {sorted(table ^ set(ASSERTIONS))} vs catalogue")
    cases = dict(re.findall(r"^\| (V\d\d) \| (X05\.A\d\d) \|", text, flags=re.MULTILINE))
    registered = {row["id"]: row["assertion"] for row in document["cases"]}
    claim(cases == registered, f"ADR case table vs script: {sorted(set(cases) ^ set(registered))}")
    lock = document["lock"]
    for phrase in (
        f"{lock['lines']} lines",
        f"{lock['pins']} pins",
        f"{len(CLOSURE)} distributions",
        f"{document['f0']['bundles']} bundles",
        f"{len(document['end_to_end']['replays'])} cells",
        f"{len(registered)} registered states",
        f"{len(ASSERTIONS)} assertions",
        *(f"F2 line {n}" for n in (25, 48)),
        *(f"`{registered_sha[:8]}…`" for registered_sha in quoted_digests(document)),
    ):
        claim(phrase in text, f"the ADR quotes {phrase!r}")
    by_id = {row["id"]: row for row in document["cases"]}
    for case_id, number in (("V25", 25), ("V26", 48), ("V27", 25)):
        claim(f"at line {number}:" in by_id[case_id]["expect"]["findings"][0], case_id)


def build() -> dict[str, Any]:
    base = LOCK_PATH.read_bytes()
    claim(hashlib.sha256(base).hexdigest() == LOCK_SHA256, "requirements.lock is not ead4edf1…")
    pins = lock_pins(base)
    for name in CLOSURE:
        claim(name in pins, f"{name} is pinned in the lock")
    declared_dependencies(pins)
    measured = measured_closure(pins)
    claim(tuple(measured) == CLOSURE, f"measured closure {measured} is not the registered one")
    rows = cases(base, pins)
    check_cases(rows, pins, base)
    document = {
        "adr": ADR.relative_to(ROOT).as_posix(),
        "generator": Path(__file__).resolve().relative_to(ROOT).as_posix(),
        "lock": {
            "path": "requirements.lock",
            "packaged_as": WHERE,
            "sha256": LOCK_SHA256,
            "lines": base.count(b"\n"),
            "pins": len(pins),
            "runtime_closure": [{"name": name, "locked": pins[name]} for name in CLOSURE],
        },
        "templates": TEMPLATES,
        "cases": rows,
        "end_to_end": end_to_end(base, pins),
        "f0": f0_facts(),
        "assertions": ASSERTIONS,
    }
    check_adr(document)
    return document


def render(document: dict[str, Any]) -> bytes:
    return (json.dumps(document, indent=1, sort_keys=True, ensure_ascii=False) + "\n").encode()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--emit", type=Path)
    arguments = parser.parse_args(argv)
    try:
        document = build()
        produced = render(document)
    except RefusalError as refusal:
        print(f"x05_reference: REFUSED: {refusal}", file=sys.stderr)
        return 1
    if arguments.emit is not None:
        arguments.emit.parent.mkdir(parents=True, exist_ok=True)
        arguments.emit.write_bytes(produced)
        print(f"x05_reference: wrote {arguments.emit}")
        return 0
    if not OUT.is_file() or OUT.read_bytes() != produced:
        print(f"x05_reference: FAIL: {OUT.relative_to(ROOT)} differs from the regeneration")
        return 1
    counts = (len(document["cases"]), len(document["end_to_end"]["replays"]), len(ASSERTIONS))
    print("x05_reference: PASS ({} cases, {} replay cells, {} assertions)".format(*counts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
