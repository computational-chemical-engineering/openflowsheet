def check_cases(rows: list[dict[str, Any]], pins: dict[str, str], base: bytes) -> None:
    by_id = {row["id"]: row for row in rows}
    claim(len(by_id) == len(rows) == 36, "36 registered verifier states, ids unique")
    for case_id in ("V01", "V02", "V03"):
        claim(by_id[case_id]["expect"] == {"sha256": LOCK_SHA256, "findings": []}, case_id)
    single = [by_id[f"V{n:02d}"]["expect"]["findings"] for n in (*range(4, 22), 36)]
    claim(all(len(found) == 1 for found in single), "V04-V21, V36: exactly one finding each")
    flat = [found[0] for found in single]
    claim(len(set(flat)) == len(flat), "V04-V21, V36: the nineteen findings are pairwise distinct")
    claim(
        by_id["V34"]["expect"]["findings"] != by_id["V35"]["expect"]["findings"],
        "V34, V35: the error class is named",
    )
    for name in CLOSURE:
        claim(pins[name] + OFF_SUFFIX != pins[name], f"{name}: the off version differs")
    claim(len(by_id["V24"]["expect"]["findings"]) == len(CLOSURE), "V24: one finding per member")
    claim(by_id["V22"]["expect"]["findings"][0].startswith("numpy "), "V22: closure order")
    text = base.decode("utf-8").split("\n")
    for case_id, line in (("V25", "numpy==2.2.4"), ("V27", "numpy==2.2.4")):
        number = text.index(line) + 1
        claim(f"at line {number}:" in by_id[case_id]["expect"]["findings"][0], case_id)
    claim(f"at line {len(text)}:" in by_id["V26"]["expect"]["findings"][0], "V26: line")
    for case_id in ("V30", "V31"):
        expect = by_id[case_id]["expect"]
        claim(
            expect["findings"] == [] and expect["sha256"] == by_id[case_id]["lock"]["sha256"],
            f"{case_id}: verifies, and its hash is of its own bytes",
        )
        claim(expect["sha256"] != LOCK_SHA256, f"{case_id}: the edit changed the bytes")
    for row in rows:
        if row["id"] not in ("V01", "V02", "V03", "V30", "V31"):
            claim(row["expect"]["sha256"] == "" and row["expect"]["findings"], row["id"])
    claim(
        {row["assertion"] for row in rows} == {f"X05.A{n:02d}" for n in range(1, 10)},
        "every verifier assertion A01-A09 has a case",
    )


