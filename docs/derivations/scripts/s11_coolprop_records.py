"""Generate `benchmarks/s07/components.yaml`: one ComponentRecord per admitted CoolProp fluid.

S11 design §4.1 (ADR 0050 D1). A revision selects the `coolprop-heos-v1` basis by naming the
generated file as its `component_set.record_source`, with its one fluid as `components`. Every
value comes from `openflowsheet.thermo._coolprop_heos_fluids.FLUIDS` (S07's table, itself generated
from CoolProp 8.0.0 and committed), in the table's order, so CoolProp need not be installed:

- `id`, `name` and `identifiers.cas` from the row;
- `molecular_weight` from the row's `M` (written by `repr`, so the parsed float is the row's);
- `elemental_composition: null`, `elemental_verification: NOT_APPLICABLE` (the schema refuses
  `PENDING` with a null formula; `docs/S11A_DECISIONS.md`);
- `parameters: {}`;
- `rights` citing CoolProp's MIT notice and the row's `bibtex_eos` (R-715's conditions), and IAPWS
  for water.

Usage:
    PYTHONPATH=src python docs/derivations/scripts/s11_coolprop_records.py --emit
    PYTHONPATH=src python docs/derivations/scripts/s11_coolprop_records.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "benchmarks" / "s07" / "components.yaml"

_HEADER = """\
# CoolProp HEOS component records for `coolprop-heos-v1`, one per admitted fluid
# (COOLPROP-DEF-ref-v1).
#
# GENERATED by docs/derivations/scripts/s11_coolprop_records.py from
# src/openflowsheet/thermo/_coolprop_heos_fluids.py (S07's table, CoolProp 8.0.0); do not edit.
# Normative text: docs/derivations/S11-design.md section 4.1; ADR 0050 D1.
# A revision names this file as its record_source with exactly one admitted id as its components.
# Each record validates against schemas/component-record.schema.json.

schema_version: 1
record_schema: schemas/component-record.schema.json
reference_convention: COOLPROP-DEF-ref-v1
components:
"""

_MIT = "MIT License, Copyright (c) Ian H. Bell and the CoolProp contributors"
_IAPWS = (
    "IAPWS attribution for water: Publication in whole or in part is allowed in all countries "
    "provided that attribution is given to the International Association for the Properties of "
    "Water and Steam (S05 spec §16.3)"
)


def _text(value: str) -> str:
    """A YAML double-quoted scalar (JSON's quoting is a subset of YAML's)."""
    return json.dumps(value, ensure_ascii=False)


def _record(row: Mapping[str, Any]) -> str:
    name = str(row["name"])
    source = f"CoolProp 8.0.0 ({_MIT}); {row['bibtex_eos']}"
    notes = f"equation of state: {row['bibtex_eos']}"
    if row["id"] == "H2O":
        notes += f"; {_IAPWS}"
    lines = [
        f"  - id: {_text(str(row['id']))}",
        f"    name: {_text(name)}",
        "    synthetic: false",
        "    identifiers:",
        f"      cas: {_text(str(row['cas']))}",
        "    molecular_weight:",
        f"      value: {float(row['M'])!r}",
        "      unit: kg/mol",
        "      dimension: [0, 1, 0, 0, -1, 0, 0]",
        "      kind: molar_mass",
        f"      meaning: {_text(f'Molar mass of {name}')}",
        "      role: fixed",
        f"      provenance: {_text(f'CoolProp 8.0.0, fluid {name} (MIT)')}",
        "    elemental_composition: null",
        "    elemental_verification: NOT_APPLICABLE",
        "    parameters: {}",
        "    rights:",
        f"      source: {_text(source)}",
        "      redistribution: "
        + _text(
            "permitted with conditions: cite CoolProp with its MIT notice and the equation "
            "of state's source (R-715)"
        ),
        f"      notes: {_text(notes)}",
    ]
    return "\n".join(lines) + "\n"


def render(fluids: Sequence[Mapping[str, Any]]) -> str:
    """The file's text for the table `fluids`, in its order."""
    return _HEADER + "".join(_record(row) for row in fluids)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="compare the committed file")
    mode.add_argument("--emit", action="store_true", help="write the file")
    args = parser.parse_args(argv)
    from openflowsheet.thermo._coolprop_heos_fluids import FLUIDS  # noqa: PLC0415

    text = render(FLUIDS)
    if args.emit:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(FLUIDS)} records)")
        return 0
    if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
        print(f"MISMATCH: {OUT.relative_to(ROOT)} differs from the generator's output")
        return 1
    print(f"OK: {OUT.relative_to(ROOT)} ({len(FLUIDS)} records)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
