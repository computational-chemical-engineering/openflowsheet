DA_F, B_F, BETA_F = 0.072, 8.0, 0.3


def ode(t: float, x: Sequence[float]) -> list[float]:
    r = DA_F * (1.0 - x[0]) * math.exp(x[1])
    return [-x[0] + r, -x[1] + B_F * r - BETA_F * x[1]]


def ode_jac(t: float, x: Sequence[float]) -> list[list[float]]:
    e = DA_F * math.exp(x[1])
    return [[-1.0 - e, (1.0 - x[0]) * e], [-B_F * e, -1.0 - BETA_F + B_F * (1.0 - x[0]) * e]]


def geometry(claims: Claims, roots: dict[str, Any]) -> dict[str, Any]:
    low = (float(roots["LOW"]["x1"]), float(roots["LOW"]["x2"]))
    mid = (float(roots["MID"]["x1"]), float(roots["MID"]["x2"]))
    high = (float(roots["HIGH"]["x1"]), float(roots["HIGH"]["x2"]))

    # the saddle's stable manifold, by backward integration from the saddle
    a = np.array(ode_jac(0.0, mid))
    w, v = np.linalg.eig(a)
    vs = v[:, int(np.argmin(w.real))].real

    def back(t: float, x: Sequence[float]) -> list[float]:
        f = ode(t, x)
        return [-f[0], -f[1]]

    def back_jac(t: float, x: Sequence[float]) -> list[list[float]]:
        j = ode_jac(t, x)
        return [[-j[0][0], -j[0][1]], [-j[1][0], -j[1][1]]]

    def leave(t: float, x: Sequence[float]) -> float:
        return min(x[0] + 1e-9, 1.0 + 1e-9 - x[0], x[1] + 1.0, 9.0 - x[1])

    leave.terminal = True  # type: ignore[attr-defined]
    branches = []
    for sign in (1.0, -1.0):
        x0 = [mid[0] + sign * 1e-9 * vs[0], mid[1] + sign * 1e-9 * vs[1]]
        sol = solve_ivp(
            back,
            (0.0, 200.0),
            x0,
            method="Radau",
            jac=back_jac,
            rtol=1e-12,
            atol=1e-14,
            events=leave,
            dense_output=True,
            max_step=0.05,
        )
        claims.check(f"B08.branch_{int(sign)}_left_box", sol.status == 1, str(sol.status))
        branches.append(sol)

    crossings: list[float] = []
    for i in range(GRID_N):
        xi = i / 20
        found: list[float] = []
        for sol in branches:
            y = sol.y
            for k in range(len(sol.t) - 1):
                lo, hi = y[0, k] - xi, y[0, k + 1] - xi
                if lo == 0.0 or lo * hi < 0.0:
                    ta, tb = sol.t[k], sol.t[k + 1]
                    for _ in range(80):
                        tm = 0.5 * (ta + tb)
                        if (sol.sol(ta)[0] - xi) * (sol.sol(tm)[0] - xi) <= 0.0:
                            tb = tm
                        else:
                            ta = tm
                    found.append(float(sol.sol(ta)[1]))
        if i == 0 and not found:  # the branch ends on x1 = 0 (the event), take its end
            for sol in branches:
                if abs(sol.y[0, -1]) < 1e-6:
                    found.append(float(sol.y[1, -1]))
        claims.check(f"B08.one_crossing_column_{i}", len(found) == 1, str(found))
        crossings.append(found[0] if found else float("nan"))

    # physical basin label of every start (forward integration)
    def near(target: tuple[float, float]) -> Callable[[float, Sequence[float]], float]:
        def ev(t: float, x: Sequence[float]) -> float:
            return max(abs(x[0] - target[0]), abs(x[1] - target[1])) - 1e-3

        ev.terminal = True  # type: ignore[attr-defined]
        return ev

    labels: list[str] = []
    x2_max = 0.0
    min_vertical = math.inf
    for j in range(GRID_N):
        row = ""
        for i in range(GRID_N):
            x0 = [i / 20, 0.4 * j]
            sol = solve_ivp(
                ode,
                (0.0, 400.0),
                x0,
                method="LSODA",
                jac=ode_jac,
                rtol=1e-9,
                atol=1e-12,
                events=(near(low), near(high)),
            )
            x2_max = max(x2_max, float(sol.y[1].max()))
            lab = "L" if sol.t_events[0].size else ("H" if sol.t_events[1].size else "?")
            row += lab
            side = "H" if 0.4 * j > crossings[i] else "L"
            claims.check(f"B08.label_matches_side_{i}_{j}", lab == side, f"{lab} {side}")
            min_vertical = min(min_vertical, abs(0.4 * j - crossings[i]))
        labels.append(row)
    claims.check("B08.no_start_near_manifold", min_vertical >= 1e-3, repr(min_vertical))
    claims.check("B08.trajectory_bound", x2_max <= 16.0, repr(x2_max))
    counts = {"L": sum(r.count("L") for r in labels), "H": sum(r.count("H") for r in labels)}
    claims.check("B08.both_basins_present", counts["L"] > 0 and counts["H"] > 0, str(counts))
    return {
        "method": (
            "stable manifold: Radau backward from the saddle +/- 1e-9 along the stable "
            "eigenvector, rtol 1e-12; labels: LSODA forward, rtol 1e-9, stopped within 1e-3 "
            "of a stable root"
        ),
        "separatrix_x2_at_grid_columns": [f"{c:.6f}" for c in crossings],
        "min_vertical_distance_start_to_separatrix": f"{min_vertical:.3e}",
        "max_x2_along_physical_trajectories": f"{x2_max:.4f}",
        "physical_basin_labels_rows_j0_to_j20": labels,
        "physical_basin_counts": counts,
    }


