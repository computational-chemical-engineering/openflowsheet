class _Dumper(yaml.SafeDumper):
    pass


def _flow_lists(dumper: yaml.SafeDumper, data: list[Any]) -> yaml.Node:
    flow = all(not isinstance(v, dict | list) for v in data) and len(data) <= 8
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


_Dumper.add_representer(list, _flow_lists)


def dump(data: dict[str, Any]) -> str:
    header = (
        "# Generated by docs/derivations/scripts/t08_build_first_reference.py -- do not edit.\n"
        "# Re-derive with --check; regenerate with --emit.\n"
    )
    return header + yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="re-derive every claim and compare with the committed YAML",
    )
    parser.add_argument("--emit", metavar="PATH", help="write the reference YAML")
    args = parser.parse_args(argv)
    if not args.check and not args.emit:
        parser.error("choose --check and/or --emit PATH")
    claims = Claims()
    text = dump(build(claims))
    for name, ok, detail in claims.results:
        if not ok:
            print(f"FAIL {name}: {detail}")
    print(f"{len(claims.results) - len(claims.failed)} of {len(claims.results)} claims pass")
    if claims.failed:
        return 1
    data = text.encode("utf-8")
    if args.check:
        committed = YAML_PATH.read_bytes() if YAML_PATH.exists() else b""
        same = committed == data
        print(
            f"committed YAML {'equals' if same else 'DIFFERS FROM'} the regenerated bytes "
            f"(sha256 {hashlib.sha256(data).hexdigest()})"
        )
        if not same:
            return 1
    if args.emit:
        path = Path(args.emit)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {path} ({len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
