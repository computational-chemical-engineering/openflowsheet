DA_M, B_M, BETA_M = mpf(72) / 1000, mpf(8), mpf(3) / 10


def f_dimless(x1: Any, x2: Any) -> list[Any]:
    r = DA_M * (1 - x1) * exp(x2)
    return [-x1 + r, -x2 + B_M * r - BETA_M * x2]


def a_dimless(x1: Any, x2: Any) -> Any:
    e = DA_M * exp(x2)
    return matrix(
        [[-1 - e, (1 - x1) * e], [-B_M * e, -1 - BETA_M + B_M * (1 - x1) * e]],
    )


def steady_states() -> list[tuple[Any, Any]]:
    def g(x2: Any) -> Any:
        return (1 + BETA_M) * x2 - B_M * DA_M * exp(x2) / (1 + DA_M * exp(x2))

    out = []
    for guess in ("1.0", "1.5", "6.0"):
        x2 = findroot(g, mpf(guess))
        x1 = DA_M * exp(x2) / (1 + DA_M * exp(x2))
        out.append((x1, x2))
    return out


def eig2(a: Any) -> list[Any]:
    tr = a[0, 0] + a[1, 1]
    dt = a[0, 0] * a[1, 1] - a[0, 1] * a[1, 0]
    disc = tr * tr - 4 * dt
    return sorted([(tr - mp.sqrt(disc)) / 2, (tr + mp.sqrt(disc)) / 2])


class Dimensional:
    """The kinetic CSTR's rows on the registered realization (spec §A1.2, Amendment 1), columns
    (n_A, n_B, n_C, T, P, Q), rows (CSTR-mole:A, CSTR-mole:B, CSTR-mole:C, CSTR-duty,
    CSTR-cooling, CSTR-pressure). Index 2 is the trace component; `minor` deletes it."""

    SIGMA = (-1, -1, -1, -1, 1, 1)  # PTC_ROW_SIGN: holdup_balance -1, algebraic +1
    N = 6
    C = 2  # the trace component's row and column

    def __init__(self, data: dict[str, dict[str, Fraction]], ref_shift: tuple[Any, ...]) -> None:
        self.cp = mq(data["A"]["cp"])
        self.lat = tuple(mq(data[c]["L"]) + ref_shift[i] for i, c in enumerate("ABC"))
        self.n_in = (mp_of("feed_A_mol_s"), mp_of("feed_B_mol_s"), mp_of("feed_C_mol_s"))
        self.t_in, self.p_in = mp_of("feed_T_K"), mp_of("feed_P_Pa")
        self.nu = (mp_of("nu_A"), mp_of("nu_B"), mp_of("nu_C"))
        self.da, self.t_ref, self.t_s = mp_of("damkohler"), mp_of("T_ref_K"), mp_of("T_scale_K")
        self.ua = mp_of("coolant_flow_mol_s") * mp_of("coolant_cp_J_molK")
        self.t_c, self.dp = mp_of("T_coolant_K"), mp_of("pressure_drop_Pa")
        self.theta = mp_of("theta_s")

    def h(self, i: int, t: Any) -> Any:
        return self.cp * (t - mq(T_R)) + self.lat[i]

    def rate(self, x: Sequence[Any]) -> Any:
        return self.da * exp((x[3] - self.t_ref) / self.t_s) * x[1]

    def state(self, x1: Any, x2: Any) -> list[Any]:
        nb = self.n_in[1] * (1 - x1)
        na = self.n_in[0] + self.n_in[1] * x1
        t = self.t_in + self.t_s * x2
        return [na, nb, self.n_in[2], t, self.p_in - self.dp, self.ua * (self.t_c - t)]

    def rows(self, x: Sequence[Any]) -> list[Any]:
        r = self.rate(x)
        h_in = sum(self.n_in[i] * self.h(i, self.t_in) for i in range(3))
        h_out = sum(x[i] * self.h(i, x[3]) for i in range(3))
        return [
            self.n_in[0] - x[0] + self.nu[0] * r,
            self.n_in[1] - x[1] + self.nu[1] * r,
            self.n_in[2] - x[2] + self.nu[2] * r,
            x[5] + h_in - h_out,
            x[5] - self.ua * (self.t_c - x[3]),
            x[4] - self.p_in + self.dp,
        ]

    def jac(self, x: Sequence[Any]) -> Any:
        e = self.da * exp((x[3] - self.t_ref) / self.t_s)
        r = e * x[1]
        j = matrix(6, 6)
        for i in range(3):
            j[i, i] = -1
            j[i, 1] += self.nu[i] * e
            j[i, 3] = self.nu[i] * r / self.t_s
            j[3, i] = -self.h(i, x[3])
        j[3, 3], j[3, 5] = -self.cp * (x[0] + x[1] + x[2]), 1
        j[4, 3], j[4, 5] = self.ua, 1
        j[5, 4] = 1
        return j

    def mass(self, x: Sequence[Any]) -> Any:
        m = matrix(6, 6)
        for i in range(3):
            m[i, i] = self.theta
            m[3, i] = self.theta * self.h(i, x[3])
        m[3, 3] = self.theta * self.cp * (x[0] + x[1] + x[2])
        return m

    def signed(self, x: Sequence[Any]) -> tuple[list[Any], Any]:
        f = self.rows(x)
        j = self.jac(x)
        fs = [self.SIGMA[i] * f[i] for i in range(6)]
        js = matrix(6, 6)
        for i in range(6):
            for k in range(6):
                js[i, k] = self.SIGMA[i] * j[i, k]
        return fs, js

    def step(self, x: Sequence[Any], dtau: Any | None) -> list[Any]:
        """(M/dtau + J_sigma) d = -F_sigma; dtau None is Newton's step J d = -F."""
        fs, js = self.signed(x)
        a = js.copy()
        if dtau is not None:
            m = self.mass(x)
            for i in range(6):
                for k in range(6):
                    a[i, k] += m[i, k] / dtau
        d = lu_solve(a, matrix([-v for v in fs]))
        return [d[i] for i in range(6)]

    def to_dimless(self, d: Sequence[Any]) -> tuple[Any, Any]:
        return (-d[1] / self.n_in[1], d[3] / self.t_s)

    @classmethod
    def minor(cls, a: Any) -> Any:
        """`a` without the trace component's row and column."""
        keep = [i for i in range(cls.N) if i != cls.C]
        out = matrix(cls.N - 1, cls.N - 1)
        for r, i in enumerate(keep):
            for c, k in enumerate(keep):
                out[r, c] = a[i, k]
        return out

    def pencil_det(self, x: Sequence[Any], s: Any, *, reduced: bool) -> Any:
        _, js = self.signed(x)
        m = self.mass(x)
        a = js.copy()
        for i in range(6):
            for k in range(6):
                a[i, k] += s * m[i, k]
        return mp.det(self.minor(a) if reduced else a)

    def trace_factor_error(self, x: Sequence[Any]) -> Any:
        """B28: det(J_sigma + s M) = (1 + s theta) det(minor) at five values of s, relative."""
        worst = mpf(0)
        for s in (mpf(0), mpf("0.5"), mpf(1), mpf(2), mpf(-3)):
            full = self.pencil_det(x, s, reduced=False)
            factored = (1 + s * self.theta) * self.pencil_det(x, s, reduced=True)
            worst = max(worst, abs(full - factored) / max(abs(full), abs(factored)))
        return worst

    def pencil(self, x: Sequence[Any]) -> list[Any]:
        """Finite s with det(J_sigma + s M) = 0. The trace row factors out (1 + s theta) (B28), so
        the roots are those of the minor's determinant, a cubic (rank M = 3 there), and -1/theta."""
        pts = [mpf(k) for k in range(5)]
        vals = [self.pencil_det(x, p, reduced=True) for p in pts]
        # Newton divided differences -> monomial coefficients (degree <= 4)
        n = len(pts)
        coef = list(vals)
        for lvl in range(1, n):
            for i in range(n - 1, lvl - 1, -1):
                coef[i] = (coef[i] - coef[i - 1]) / (pts[i] - pts[i - lvl])
        poly = [mpf(0)] * n  # poly[k] = coefficient of s^k
        basis = [mpf(1)] + [mpf(0)] * (n - 1)
        for i in range(n):
            for k in range(n):
                poly[k] += coef[i] * basis[k]
            nxt = [mpf(0)] * n
            for k in range(n - 1):
                nxt[k + 1] += basis[k]
                nxt[k] -= pts[i] * basis[k]
            basis = nxt
        self.quartic = abs(poly[4]) / max(abs(p) for p in poly)
        roots = polyroots(list(reversed(poly[:4])), maxsteps=200, extraprec=200)
        return sorted([mp.re(r) for r in roots] + [-1 / self.theta])

    def step_det(self, x: Sequence[Any], dtau: Any) -> Any:
        _, js = self.signed(x)
        m = self.mass(x)
        a = js.copy()
        for i in range(6):
            for k in range(6):
                a[i, k] += m[i, k] / dtau
        return mp.det(a)


def closed_forms(claims: Claims, data: dict[str, dict[str, Fraction]]) -> dict[str, Any]:
    dim = Dimensional(data, (mpf(0), mpf(0), mpf(0)))
    roots = steady_states()
    names = ("LOW", "MID", "HIGH")
    t04 = yaml.safe_load(T04_YAML.read_text(encoding="utf-8"))["closed_form"][
        "ptc_r1_cstr_preregistered"
    ]
    out_roots: dict[str, Any] = {}
    residual_max = mpf(0)
    pencil_err = mpf(0)
    quartic_max = mpf(0)
    factor_err = mpf(0)
    trace_row_max = mpf(0)
    inv_norms: dict[str, Any] = {}
    for idx, (name, (x1, x2)) in enumerate(zip(names, roots, strict=True)):
        fd = f_dimless(x1, x2)
        claims.check(f"B02.{name}_dimless_root", max(abs(v) for v in fd) < mpf("1e-35"), "")
        ev = eig2(a_dimless(x1, x2))
        reg = t04["steady_states"][idx]
        claims.check(
            f"B02.{name}_vs_T04",
            abs(x1 - mpf(reg["x1"])) < mpf("1e-11")
            and abs(x2 - mpf(reg["x2"])) < mpf("1e-10")
            and all(
                abs(e - mpf(r)) < mpf("1e-14")
                for e, r in zip(ev, sorted(mpf(v) for v in reg["eigenvalues"]), strict=True)
            ),
            f"{s20(x1)} {s20(x2)}",
        )
        claims.check(
            f"B02.{name}_quoted_T04_8_4",
            nstr(x2, 7) == T04_QUOTED_X2[idx],
            str(nstr(x2, 7)),
        )
        x = dim.state(x1, x2)
        f = dim.rows(x)
        residual_max = max(residual_max, max(abs(v) for v in f))
        trace_row_max = max(trace_row_max, abs(f[Dimensional.C]))
        factor_err = max(factor_err, dim.trace_factor_error(x))
        pen = dim.pencil(x)
        quartic_max = max(quartic_max, dim.quartic)
        # physical modes, the total-moles mode and the trace's mode (Amendment 1)
        expected = sorted(ev + [-1 / dim.theta, -1 / dim.theta])
        pencil_err = max(pencil_err, max(abs(a - b) for a, b in zip(pen, expected, strict=True)))
        a = a_dimless(x1, x2)
        dt = a[0, 0] * a[1, 1] - a[0, 1] * a[1, 0]
        inv = matrix([[a[1, 1] / dt, -a[0, 1] / dt], [-a[1, 0] / dt, a[0, 0] / dt]])
        inv_inf = max(abs(inv[i, 0]) + abs(inv[i, 1]) for i in range(2))
        inv_norms[name] = inv_inf
        out_roots[name] = {
            "x1": s20(x1),
            "x2": s20(x2),
            "n_A_mol_s": s20(x[0]),
            "n_B_mol_s": s20(x[1]),
            "n_C_mol_s": s20(x[2]),
            "T_K": s20(x[3]),
            "P_Pa": s20(x[4]),
            "Q_W": s20(x[5]),
            "physical_eigenvalues_per_theta": [s20(e) for e in ev],
            "pencil_finite_eigenvalues_per_s": [s20(e) for e in pen],
            "stable": all(e < 0 for e in ev),
        }
    claims.check("B03.dimensional_rows_vanish", residual_max < mpf("1e-30"), s20(residual_max))
    claims.check("B03.pencil_is_physical_plus_two_unit_modes", pencil_err < mpf("1e-25"), "")
    claims.check("B28.trace_row_vanishes_at_roots", trace_row_max == 0, s20(trace_row_max))
    claims.check("B28.trace_mode_factors_out", factor_err < mpf("1e-30"), s20(factor_err))
    claims.check("B03.pencil_det_is_cubic", quartic_max < mpf("1e-25"), s20(quartic_max))
    claims.check(
        "B03.stability_pattern",
        [out_roots[n]["stable"] for n in names] == [True, False, True],
        "",
    )

    # the saddle: singularity, contraction threshold, determinant sign change
    x1m, x2m = roots[1]
    s_minus, s_plus = eig2(a_dimless(x1m, x2m))
    dtau_star = dim.theta / s_plus
    xm = dim.state(x1m, x2m)
    d_lo = dim.step_det(xm, dtau_star * (1 - mpf("1e-3")))
    d_hi = dim.step_det(xm, dtau_star * (1 + mpf("1e-3")))
    d_at = dim.step_det(xm, dtau_star)
    claims.check("B03.singular_at_dtau_star", abs(d_at) < mpf("1e-30") * abs(d_lo), s20(d_at))
    claims.check("B03.det_sign_change", d_lo * d_hi < 0, "")
    claims.check(
        "B03.quoted_T04_singularity",
        nstr(dtau_star, 3) == T04_QUOTED_SINGULARITY
        and nstr(s_minus, 4) == T04_QUOTED_SADDLE[0]
        and nstr(s_plus, 4) == T04_QUOTED_SADDLE[1],
        f"{nstr(dtau_star, 6)} {nstr(s_minus, 6)} {nstr(s_plus, 6)}",
    )
    claims.check("B03.tau0_below_singularity", mpf(1) < dtau_star, "")

    # single-step identities at off-grid states (B04)
    step_err = mpf(0)
    steps: list[dict[str, Any]] = []
    grid_x2 = {Fraction(8 * j, 20) for j in range(GRID_N)}
    grid_x1 = {Fraction(i, 20) for i in range(GRID_N)}
    for sx1, sx2 in OFF_GRID:
        claims.check(
            f"B04.off_grid_{sx1}_{sx2}",
            Fraction(sx1) not in grid_x1 and Fraction(sx2) not in grid_x2,
            "",
        )
        x1, x2 = mpf(sx1), mpf(sx2)
        x = dim.state(x1, x2)
        fvec = f_dimless(x1, x2)
        a = a_dimless(x1, x2)
        row: dict[str, Any] = {"x1": sx1, "x2": sx2}
        for label, dt in [*((f"ptc_dtau_{d}", mpf(d)) for d in STEP_DTAUS), ("newton", None)]:
            dd = dim.to_dimless(dim.step(x, dt))
            aa = a.copy()
            if dt is not None:
                aa[0, 0] -= dim.theta / dt
                aa[1, 1] -= dim.theta / dt
            # dimensionless: (theta/dtau I - A) d = f
            ref = lu_solve(-aa, matrix(fvec))
            err = max(abs(dd[0] - ref[0]), abs(dd[1] - ref[1])) / max(abs(ref[0]), abs(ref[1]))
            step_err = max(step_err, err)
            full = dim.step(x, dt)
            claims.check(
                f"B04.total_moles_and_algebraic_{sx1}_{sx2}_{label}",
                abs(full[0] + full[1] + full[2]) < mpf("1e-35")
                and abs(full[4]) < mpf("1e-35")
                and abs(full[5] + dim.ua * full[3]) < mpf("1e-30"),
                "",
            )
            claims.check(
                f"B28.trace_step_zero_{sx1}_{sx2}_{label}", abs(full[2]) < mpf("1e-35"), ""
            )
            row[label] = {"d_x1": s20(ref[0]), "d_x2": s20(ref[1])}
            row[label + "_dimensional"] = {
                "d_n_A": s20(full[0]),
                "d_n_B": s20(full[1]),
                "d_n_C": s20(full[2]),
                "d_T": s20(full[3]),
                "d_P": s20(full[4]),
                "d_Q": s20(full[5]),
            }
        steps.append(row)
    claims.check("B04.step_identity", step_err < mpf("1e-30"), s20(step_err))

    # reference invariance (B05): a reaction-consistent shift leaves the step unchanged
    shifted = Dimensional(data, (mpf(1000), mpf(1000), mpf(1000)))
    inv_err = mpf(0)
    for sx1, sx2 in OFF_GRID:
        x = dim.state(mpf(sx1), mpf(sx2))
        for d in STEP_DTAUS:
            a0, a1 = dim.step(x, mpf(d)), shifted.step(x, mpf(d))
            inv_err = max(inv_err, max(abs(u - v) for u, v in zip(a0, a1, strict=True)))
    claims.check("B05.reaction_consistent_shift_invariant", inv_err < mpf("1e-30"), s20(inv_err))
    skew = Dimensional(data, (mpf(0), mpf(1000), mpf(0)))
    moved = skew.rows(dim.state(roots[0][0], roots[0][1]))
    claims.check(
        "B05.inconsistent_shift_changes_the_problem",
        abs(moved[3]) > mpf(1),
        s20(moved[3]),
    )

    # classification radius argument (B09)
    r1 = TOL_FLOW / mp_of("feed_B_mol_s")
    r2 = (2 * TOL_HEAT + abs(dim.lat[1] - dim.lat[0]) * TOL_FLOW) / (
        (dim.n_in[0] + dim.n_in[1] + dim.n_in[2]) * dim.cp * dim.t_s
    )
    worst = max(inv_norms.values()) * max(r1, r2)
    sep = min(
        max(abs(roots[i][0] - roots[k][0]), abs(roots[i][1] - roots[k][1]))
        for i in range(3)
        for k in range(i + 1, 3)
    )
    claims.check("B09.radius_above_accuracy", R_CLASS >= 10 * worst, s20(worst))
    claims.check("B09.radius_below_separation", R_CLASS <= sep / 100, s20(sep))

    return {
        "steady_states": out_roots,
        "saddle": {
            "s_minus_per_theta": s20(s_minus),
            "s_plus_per_theta": s20(s_plus),
            "dtau_singular_over_theta": s20(dtau_star),
            "dtau_contracting_over_theta": s20(2 * dtau_star),
            "unstable_direction_factor": "1 / (1 - s_plus * dtau)",
        },
        "single_steps": steps,
        "single_step_max_relative_difference": s20(step_err),
        "trace_mode_factor_max_relative_error": s20(factor_err),
        "reference_shift_max_step_difference": s20(inv_err),
        "classification": {
            "radius_dimensionless_inf_norm": str(R_CLASS),
            "residual_bound_x1_row": s20(r1),
            "residual_bound_x2_row": s20(r2),
            "inverse_jacobian_inf_norm": {k: s20(v) for k, v in inv_norms.items()},
            "distance_bound": s20(worst),
            "min_root_separation": s20(sep),
        },
    }


