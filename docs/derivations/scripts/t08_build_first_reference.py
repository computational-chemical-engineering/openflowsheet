def dew_point(data: dict[str, dict[str, Fraction]], z_b: Any, p: Any) -> Any:
    """The outlet's dew point at key fraction `z_b`, with the trace C at its feed fraction and A
    the rest (the outlet's composition along x1, since n_tot = 1 and C is inert)."""

    def k(c: str, t: Any) -> Any:
        rec = data[c]
        return (mq(P_R) / p) * exp(
            (mq(rec["L"]) / R_GAS) * (1 / mq(rec["Tb"]) - 1 / t)
            + mq(rec["v"]) * (p - mq(P_R)) / (R_GAS * t)
        )

    z_c = mq(TRACE_C)
    z_a = 1 - z_c - z_b
    return findroot(lambda t: z_a / k("A", t) + z_b / k("B", t) + z_c / k("C", t) - 1, mpf(340))


def two_component_dew_point(data: dict[str, dict[str, Fraction]], z_b: Any, p: Any) -> Any:
    """The C_reg realization's dew point (no C), kept only to bound the trace's shift."""

    def k(c: str, t: Any) -> Any:
        rec = data[c]
        return (mq(P_R) / p) * exp(
            (mq(rec["L"]) / R_GAS) * (1 / mq(rec["Tb"]) - 1 / t)
            + mq(rec["v"]) * (p - mq(P_R)) / (R_GAS * t)
        )

    return findroot(lambda t: (1 - z_b) / k("A", t) + z_b / k("B", t) - 1, mpf(340))


def margins(claims: Claims, data: dict[str, dict[str, Fraction]]) -> dict[str, Any]:
    p = mp_of("feed_P_Pa")
    z_bs = [mpf(k) / 200 for k in range(0, 101)]  # z_B from 0 to 0.5 (x1 from 1 to 0)
    # Amendment 1: the trace moves the dew point by less than 1 K (the claim bounds it)
    shift = dew_point(data, mpf("0.5"), p) - two_component_dew_point(data, mpf("0.5"), p)
    claims.check("B28.trace_dew_shift_below_1K", 0 < shift < 1, s20(shift))
    dews = [dew_point(data, z, p) for z in z_bs]
    dew_max = max(dews)
    claims.check("B06.dew_max_at_feed", dews.index(dew_max) == len(dews) - 1, "")
    t_min_grid = mp_of("feed_T_K")
    t_s = mp_of("T_scale_K")
    claims.check("B06.grid_superheated", t_min_grid - dew_max > 10, s20(t_min_grid - dew_max))
    # physical trajectories from the grid: 0 <= x2 <= max(x2_0 + B (1 - x1_0), B) <= 16
    x2_bound = CASE_B + max(GRID_X2[1], CASE_B)
    t_top = fr("feed_T_K") + fr("T_scale_K") * x2_bound
    claims.check("B06.trajectory_bound_in_domain", t_top < DOMAIN_T[1], str(t_top))
    claims.check("B06.pressure_in_domain", DOMAIN_P[0] < fr("feed_P_Pa") < DOMAIN_P[1], "")
    return {
        "dew_point_max_K": s20(dew_max),
        "dew_point_shift_by_trace_K": s20(shift),
        "dew_point_max_x2": s20((dew_max - t_min_grid) / t_s),
        "grid_T_range_K": [str(fr("feed_T_K")), str(fr("feed_T_K") + 8 * fr("T_scale_K"))],
        "trajectory_x2_bound": str(x2_bound),
        "trajectory_T_bound_K": str(t_top),
        "domain_top_x2": str((DOMAIN_T[1] - fr("feed_T_K")) / fr("T_scale_K")),
    }


FEED64 = (0.4990234375, 0.5, 0.0009765625)
LAT64 = (25000.0, 30000.0, 35000.0)


def rows64(x: Sequence[float]) -> list[float]:
    """The registered rows in binary64, as an implementation would evaluate them; columns
    (n_A, n_B, n_C, T, P, Q)."""
    cp = 100.0
    r = 0.072 * math.exp((x[3] - 360.0) / 3.125) * x[1]
    h_in = sum(FEED64[i] * (cp * 60.0 + LAT64[i]) for i in range(3))
    h_out = sum(x[i] * (cp * (x[3] - 300.0) + LAT64[i]) for i in range(3))
    return [
        FEED64[0] - x[0] + r,
        FEED64[1] - x[1] - r,
        FEED64[2] - x[2] + 0.0 * r,
        x[5] + h_in - h_out,
        x[5] - 30.0 * (360.0 - x[3]),
        x[4] - 100000.0,
    ]


