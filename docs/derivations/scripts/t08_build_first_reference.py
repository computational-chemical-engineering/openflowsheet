"""Reference values and executable self-claims for the T08 build-first specification.

``docs/derivations/T08-build-first-spec.md`` registers (Part A) the dimensional realization of T04's
preregistered case PTC-R1 on a kinetic CSTR with holdup, the comparison that judges V14 (b) on it,
and (Part B) the compatible warm starts that judge V13 (e). Every number that document states about
PTC-R1 is re-derived here, and the script refuses to emit when one of its claims fails (spec §C.2).

Emitted, and labelled as such in the YAML:

* ``case`` -- the preregistered dimensionless case (T04 spec §8.4) and the registered dimensional
  realization, with the exact identities that map one onto the other (rational arithmetic).
* ``closed_form`` -- mpmath at 40 significant digits, written to 20: the three steady states in both
  coordinates, the physical Jacobian's eigenvalues, the finite generalized eigenvalues of the
  dimensional PTC pencil, the step-matrix singularity at the saddle, the single-step identities
  between the dimensional and dimensionless PTC and Newton steps at three off-grid states, the
  reaction-consistent reference invariance, and the numbers the classification radius is argued
  from.
* ``float64`` -- measured floors: the central-difference derivative floor of the dimensional rows.
* ``geometry`` -- the physical dynamics' separatrix (the saddle's stable manifold) and the basin
  label of every registered start under the physical dynamics (scipy, float64, written to six
  significant digits). These describe the physical ODE, never PTC or Newton: this script iterates
  neither method from any registered start (spec §A4.6).
* ``starts`` -- the 441 registered starts in dimensional coordinates, as exact binary64 values.
* ``criterion`` -- the resolved comparison criterion, the two comparison policies and the budgets.
* ``assertions`` -- the numbered-assertion catalogue, cross-checked against the specification.

It imports nothing from ``process_runtime`` or ``benchmarks`` (it reads committed files as data), so
none of its expectations comes from the code under judgement.

Amendment 1 (spec, 2026-09-29): the realization carries the third SYN-001 component ``C`` as an
inert trace (``2^-10`` mol/s, taken from ``A``'s feed), because the binder admits only ``(A, B, C)``
(ADR 0014 D9) and a component carried at exactly zero sits on its lower bound, where factorization
roundoff meets the bound rule (spec Amendment 1, Q1). The dimensional model is therefore six by six;
the claims of T08.B28 prove the trace inert, and every dimensionless number is unchanged.

Run from the repository root inside the project environment::

    python docs/derivations/scripts/t08_build_first_reference.py --check
    python docs/derivations/scripts/t08_build_first_reference.py \
        --emit benchmarks/t08/build_first_reference.yaml

``--check`` re-derives every claim and requires the committed YAML to equal the regenerated bytes.
``--emit`` is byte-reproducible.
"""

