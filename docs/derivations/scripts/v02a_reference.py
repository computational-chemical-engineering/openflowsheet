class Claims:
    def __init__(self) -> None:
        self.results: list[tuple[str, bool, str]] = []

    def check(self, name: str, ok: bool, detail: str = "") -> bool:
        self.results.append((name, bool(ok), detail))
        return bool(ok)

    @property
    def failed(self) -> list[str]:
        return [name for name, ok, _ in self.results if not ok]


def read(path: str | Path) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


def sha256_file(path: str | Path) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def tables(text: str) -> Iterator[tuple[int, list[str], list[list[str]]]]:
    """Every markdown table: (line index of its header, header cells, data rows' cells)."""
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        if (
            lines[index].lstrip().startswith("|")
            and index + 1 < len(lines)
            and re.fullmatch(r"\s*\|?[\s:|-]+\|?\s*", lines[index + 1])
            and "-" in lines[index + 1]
        ):
            start = index
            header = cells(lines[index])
            rows: list[list[str]] = []
            index += 2
            while index < len(lines) and lines[index].lstrip().startswith("|"):
                rows.append(cells(lines[index]))
                index += 1
            yield start, header, rows
        else:
            index += 1


def table_with_header(text: str, first: Sequence[str]) -> list[list[str]]:
    found = [rows for _, header, rows in tables(text) if header[: len(first)] == list(first)]
    if len(found) != 1:
        raise ValueError(f"{len(found)} tables headed {list(first)}, not 1")
    return found[0]


def table_after(text: str, marker: str) -> list[list[str]]:
    """The first table after the line that starts with `marker`."""
    lines = text.splitlines()
    starts = [n for n, line in enumerate(lines) if line.startswith(marker)]
    if len(starts) != 1:
        raise ValueError(f"{len(starts)} lines start with {marker!r}, not 1")
    following = [rows for start, _, rows in tables(text) if start > starts[0]]
    if not following:
        raise ValueError(f"no table after {marker!r}")
    return following[0]


def unquote(cell: str) -> str:
    """A table cell holding one example in backticks: the text between the outer backticks."""
    if len(cell) >= 2 and cell.startswith("`") and cell.endswith("`"):
        return cell[1:-1]
    raise ValueError(f"cell {cell!r} is not one backticked example")


def yes_no(cell: str) -> bool:
    if cell not in ("yes", "no"):
        raise ValueError(f"cell {cell!r} is not yes/no")
    return cell == "yes"


def assignments(path: str) -> dict[str, Any]:
    """Module-level constant assignments of a Python file, by `ast` (no import)."""
    tree = ast.parse(read(path))
    found: dict[str, Any] = {}
    for node in tree.body:
        target: ast.expr | None = None
        value: ast.expr | None = None
        if isinstance(node, ast.AnnAssign):
            target, value = node.target, node.value
        elif isinstance(node, ast.Assign) and len(node.targets) == 1:
            target, value = node.targets[0], node.value
        if isinstance(target, ast.Name) and value is not None:
            if isinstance(value, ast.Call) and getattr(value.func, "attr", "") == "compile":
                value = value.args[0]
            try:
                found[target.id] = ast.literal_eval(value)
            except (ValueError, TypeError, SyntaxError):
                continue
    return found


def register_section(register: str, entry: str) -> str:
    start = register.index(f"\n## {entry} ")
    end = register.find("\n## ", start + 1)
    return register[start : end if end >= 0 else len(register)]


def bare(cell: str) -> str:
    return cell.replace("*", "").replace("`", "").strip()


def first_status_line(text: str) -> str:
    return next(line for line in text.splitlines() if line.startswith("**Status:**"))


