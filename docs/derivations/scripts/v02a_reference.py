def adr_rows(text: str, column: str) -> list[list[str]]:
    """The rows of ADR 0028's one table whose header has `column` (lower-cased, bare)."""
    found = [
        rows
        for _, header, rows in tables(text)
        if column in [bare(cell).lower() for cell in header]
    ]
    if len(found) != 1:
        raise ValueError(f"ADR 0028 has {len(found)} tables with a {column!r} column, not 1")
    return found[0]


def dump(data: dict[str, Any]) -> str:
    header = (
        "# Reference values of docs/derivations/V02-alpha-release-spec.md (package M07a,\n"
        "# ADR 0028), emitted by docs/derivations/scripts/v02a_reference.py. Do not edit by hand.\n"
        "# Re-derive with --check; regenerate with --emit.\n"
    )
    return header + yaml.safe_dump(data, sort_keys=True, allow_unicode=True, width=100)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="re-derive every claim and compare with the committed YAML",
    )
    parser.add_argument("--emit", metavar="PATH", help="write the reference YAML")
    args = parser.parse_args(argv)
    if not args.check and not args.emit:
        parser.error("choose --check and/or --emit PATH")
    claims = Claims()
    text = dump(build(claims))
    for name, ok, detail in claims.results:
        if not ok:
            print(f"FAIL {name}: {detail}")
    print(f"{len(claims.results) - len(claims.failed)} of {len(claims.results)} claims pass")
    if claims.failed:
        return 1
    data = text.encode("utf-8")
    if args.check:
        committed = YAML_PATH.read_bytes() if YAML_PATH.exists() else b""
        same = committed == data
        print(
            f"committed YAML {'equals' if same else 'DIFFERS FROM'} the regenerated bytes "
            f"(sha256 {hashlib.sha256(data).hexdigest()})"
        )
        if not same:
            return 1
    if args.emit:
        path = Path(args.emit)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {path} ({len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
