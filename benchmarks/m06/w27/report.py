"""W27 Tier 0 item 4: `docs/m06-w27-coverage.md`, generated from `coverage.json` (M06 WO-16g).

Normative text: registration §12 W27-R53 (coverage reporting: class counts against 450 and 82,
reason counts, per family, the snapshot's and `list_models`' SHA-256 and the package version, and
the sentence "k of 450 (j of 82) cases are representable candidates …") and W27-R57 (what may and
may not be claimed). The report is a pure function of `coverage.json` and `access_report.json`;
`--check` re-generates it and compares byte for byte.

Run: `python -m benchmarks.m06.w27.report [--check]`.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping, Sequence
from typing import Any

from benchmarks.m06.w27 import registration


def _table(header: Sequence[str], rows: Sequence[Sequence[Any]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines


def sentence(coverage: Mapping[str, Any]) -> str:
    """W27-R53's sentence."""
    summary = coverage["summary"]
    k = summary["all_450"]["classes"]["CANDIDATE"]
    j = summary["full82"]["classes"]["CANDIDATE"]
    version = coverage["snapshot"]["package_version"]
    return (
        f"{k} of 450 ({j} of 82) cases are representable candidates for OpenFlowsheet {version}; "
        "the rest are classified with reasons."
    )


def render(coverage: Mapping[str, Any], access: Mapping[str, Any]) -> str:
    classes = registration.classes()
    summary = coverage["summary"]
    snap = coverage["snapshot"]
    all_450, full82 = summary["all_450"], summary["full82"]
    lines = [
        "# W27 coverage: OpenIDAES-450 against OpenFlowsheet (Tier 0)",
        "",
        "Generated by `python -m benchmarks.m06.w27.report` from "
        "`benchmarks/m06/openidaes450/coverage.json`; do not edit by hand. Rules: "
        "`docs/derivations/M06-W27-registration.md` §5 (classification) and §12 (reporting).",
        "",
        f"**{sentence(coverage)}**",
        "",
        "## Snapshot",
        "",
        *_table(
            ["Item", "Value"],
            [
                ["`openflowsheet` version", f"`{snap['package_version']}`"],
                ["built at commit", f"`{snap.get('git_commit')}`"],
                ["registry snapshot SHA-256", f"`{coverage['snapshot_sha256']}`"],
                ["`list_models` SHA-256", f"`{coverage['list_models_sha256']}`"],
                ["models", str(len(snap["models"]))],
                [
                    "property routes",
                    ", ".join(
                        f"`{r['provider_id']}` ({len(r['components'])} components, "
                        f"{sum(1 for c in r['components'] if c['synthetic'])} synthetic)"
                        for r in snap["routes"]
                    ),
                ],
                ["`registration.json` SHA-256", f"`{coverage['registration_sha256']}`"],
                ["`case_facts.json` SHA-256", f"`{coverage['case_facts_sha256']}`"],
            ],
        ),
        "",
        "## Classes",
        "",
        "Each case has one class, the first of the registered precedence that applies (W27-R08).",
        "",
        *_table(
            ["Class", "of 450", "of 82"],
            [[f"`{c}`", all_450["classes"][c], full82["classes"][c]] for c in classes]
            + [["total", all_450["total"], full82["total"]]],
        ),
        "",
        "## Reasons",
        "",
        "Cases carrying at least one reason of each kind (every applicable reason is recorded).",
        "",
        *_table(
            ["Reason kind", "of 450", "of 82"],
            [
                [f"`{c}`", all_450["cases_with_reason"][c], full82["cases_with_reason"][c]]
                for c in classes[:-1]
            ],
        ),
        "",
        "## By family (all 450)",
        "",
        *_table(
            ["Family", *[f"`{c}`" for c in classes], "total"],
            [
                [f, *[counts[c] for c in classes], sum(counts.values())]
                for f, counts in all_450["by_family"].items()
            ],
        ),
        "",
        "## Inaccessible assets",
        "",
        "Assets the CRAFTS paper's agent results depend on that the release does not contain "
        "(`access_report.json`, where each was sought is recorded there).",
        "",
        *[f"- {a['asset']} — {a['needed_for']}" for a in access["inaccessible_assets"]],
        "",
        "## What this does not establish",
        "",
        "- No headline score, no OpenIDAES-450 success rate, and no comparison with CRAFTS' "
        "reported results (blueprint §11.4; registration W27-R57).",
        "- A `CANDIDATE` is a necessary-condition class: functions, configuration tokens, chemical "
        "identity, method equality and phase admission are checked; port phase capabilities, "
        "specification modes, mixer pressures and stoichiometry are not (registration §16).",
        "- A non-`CANDIDATE` class is a judgement of the registration's maps, made from the case "
        "JSON; the maps are not validated against IDAES's or OpenFlowsheet's source.",
        "- No numerical agreement with IDAES, and no empirical validation of anything.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="W27 Tier 0 coverage report")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    coverage = json.loads(registration.COVERAGE_JSON.read_bytes())
    access = json.loads(registration.ACCESS_JSON.read_bytes())
    text = render(coverage, access)
    if args.check:
        same = registration.REPORT_MD.read_text(encoding="utf-8") == text
        print("OK" if same else f"DIFFERS: {registration.REPORT_MD}")
        return 0 if same else 1
    registration.REPORT_MD.write_text(text, encoding="utf-8")
    print(f"wrote {registration.REPORT_MD}: {sentence(coverage)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
