"""Loader for `benchmarks/p02/reference_values.yaml` (the 40-digit P02 reference).

The file is generated by `docs/derivations/scripts/p02_reference.py` from the plan §3.1
definitions and the SYN-001 §3 closed forms. It is never regenerated from a backend or from
`expected.py`; assertion A00 compares the two and would fail if either drifted.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Final

import yaml

from benchmarks.p02.expected import Parameters

REFERENCE_PATH: Final = Path(__file__).resolve().parent / "reference_values.yaml"


@dataclass(frozen=True)
class ReferenceState:
    """One registered evaluation state, with its expectations (specification §5)."""

    state_id: str
    purpose: str
    on_solution: bool
    oracle_phase_state: str | None
    parameters: Parameters
    x_l: dict[str, float]
    x_i: dict[str, float]
    residual_l: dict[str, float]
    residual_i: dict[str, float]
    jacobian_l: dict[str, float]
    jacobian_i: dict[str, float]
    numerically_zero_l: tuple[str, ...]
    numerically_zero_i: tuple[str, ...]


@dataclass(frozen=True)
class Reference:
    """The whole reference document."""

    states: dict[str, ReferenceState]
    origins_l: dict[str, str]
    pattern_l: tuple[str, ...]
    pattern_i: tuple[str, ...]
    directions: dict[str, tuple[float, ...]]
    fd_floors: dict[str, Any]
    linear_solve: dict[str, Any]
    second_order: dict[str, Any]
    raw: dict[str, Any]


def _floats(mapping: dict[str, Any]) -> dict[str, float]:
    return {key: float(value) for key, value in mapping.items()}


def _pattern(block: Any) -> tuple[str, ...]:
    """Return the pattern as sorted `"<row>|<col>"` keys, from either encoding in the file."""
    entries = block.get("entries", block) if isinstance(block, dict) else block
    if isinstance(entries, dict):
        return tuple(sorted(str(key) for key in entries))
    keys: list[str] = []
    for entry in entries:
        if isinstance(entry, dict):
            keys.append(f"{entry['row']}|{entry['col']}")
        else:
            keys.append(str(entry))
    return tuple(sorted(keys))


@lru_cache(maxsize=1)
def load_reference(path: str | None = None) -> Reference:
    """Read and parse the reference document (cached)."""
    target = Path(path) if path is not None else REFERENCE_PATH
    with target.open(encoding="utf-8") as handle:
        document: dict[str, Any] = yaml.safe_load(handle)

    states: dict[str, ReferenceState] = {}
    for entry in document["states"]:
        raw_parameters = entry["parameters"]
        feed = tuple(float(value) for value in raw_parameters["f_mol_per_s"])
        assert len(feed) == 3
        states[entry["state_id"]] = ReferenceState(
            state_id=entry["state_id"],
            purpose=str(entry.get("purpose", "")),
            on_solution=bool(entry.get("on_solution", False)),
            oracle_phase_state=entry.get("oracle_phase_state"),
            parameters=Parameters(
                feed=(feed[0], feed[1], feed[2]),
                h_feed=float(raw_parameters["H_feed_W"]),
                t_spec=float(raw_parameters["T_spec_K"]),
                p_spec=float(raw_parameters["P_spec_Pa"]),
            ),
            x_l=_floats(entry.get("x_L", {})),
            x_i=_floats(entry.get("x_I", {})),
            residual_l=_floats(entry.get("residual_L", {})),
            residual_i=_floats(entry.get("residual_I", {})),
            jacobian_l=_floats(entry.get("jacobian_L", {})),
            jacobian_i=_floats(entry.get("jacobian_I", {})),
            numerically_zero_l=tuple(entry.get("numerically_zero_entries_L", ())),
            numerically_zero_i=tuple(entry.get("numerically_zero_entries_I", ())),
        )

    patterns = document.get("patterns", {})
    origins: dict[str, str] = {}
    for entry in patterns.get("L_form", {}).get("entries", []):
        if isinstance(entry, dict):
            origins[f"{entry['row']}|{entry['col']}"] = str(entry.get("origin", ""))

    return Reference(
        states=states,
        origins_l=origins,
        pattern_l=_pattern(patterns.get("L_form", {})),
        pattern_i=_pattern(patterns.get("I_form", {})),
        directions={
            key: tuple(float(value) for value in values)
            for key, values in document.get("directions", {}).items()
            if isinstance(values, list)
        },
        fd_floors=document.get("fd_floors_measured", {}),
        linear_solve=document.get("linear_solve", {}),
        second_order=document.get("second_order_probe_expected", {}),
        raw=document,
    )
